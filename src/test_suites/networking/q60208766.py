"""
SO-60208766: "tls: server selected unsupported protocol version 301" -- on a Kubernetes node behind a
corporate proxy, a new Pod stays in ContainerCreating: the sandbox cannot be created because the Calico CNI
plugin fails with "error getting ClusterInformation: Get https://[10.96.0.1]:443/apis/crd.projectcalico.org/
v1/clusterinformations/default: tls: server selected unsupported protocol version 301". The author's finding:
containerd has the proxy settings of the node (HTTP_PROXY/HTTPS_PROXY in a systemd drop-in); the CNI plugin
is started by containerd and inherits them, so its request for the cluster-internal API Service address
goes to the corporate proxy, which cannot serve it. The fix is the address (or the Service range) in the
NO_PROXY of containerd's environment, then daemon-reload and a restart of the service.

Adaptation (reported as such): no real cluster. The API is a protocol fixture (helpers/api.py, HTTPS and a
bearer token, in-memory) that answers what the real Calico v3.20.6 CNI plugin (the official release binary,
sha256-pinned, Kubernetes datastore mode) reads and writes: ClusterInformation, IP pool, node, namespaces,
Pod, IPAM blocks/handles/affinities, Pod status. It listens on 10.96.0.1:443 (an alias of the loopback
interface: a Go client never exempts a loopback address from the proxy by itself, but does exempt this one
only if NO_PROXY names it). The corporate proxy (helpers/proxy.py) tunnels CONNECT to the lab's registry only
and answers a CONNECT to the API with 200 and a ServerHello of version 0x0301, which reproduces the exact
error text. The registry accepts connections only from the proxy's source address, so the node's image pulls
need the proxy: clearing all proxy settings or NO_PROXY=* breaks them, which is the second half of the
question's constraint. The Pod objects are made by the evaluator (the kubelet's job); the node is a private
containerd 2.0.0 unit (the lab of networking/q79305194, version 3 configuration) with its own CNI directories.

Case design: setup.sh pins and downloads the releases, builds the registry/images, certificates, API,
proxy, the CNI files and the unit with its proxy drop-in (NO_PROXY without the API address).
precondition.sh shows the symptom and the controls (the service has the proxy; the API answers directly and
not through the proxy; a cold pull works through the proxy and not around it; a new sandbox fails with the
301 error and the proxy log has the CONNECT to 10.96.0.1:443; the real plugin run by hand works when
NO_PROXY names the address). oracle.sh runs helpers/verify.py: lab unchanged (the kubeconfig's API URL, the
CNI configuration, the binaries), plain `systemctl restart`, then twice (the second after another restart
and an emptied store): a NEW image, its cold pull through the proxy (proxy and registry logs), two new Pods
whose sandboxes get their network from the real plugin (own netns, an IP of the pool that the netns really
has, a cali* route, Calico's annotation on the Pod object), Pod B reads Pod A's nonce over the Pod
network, the proxy log has no CONNECT to the API while the API log has the plugin's own requests, and the
Pods are taken down cleanly (route, interface and IPAM handles gone).

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/networking/q60208766/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Networking & Connectivity
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/networking/q60208766/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "networking" / "q60208766"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q60208766",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 240)   # setup (downloads of the releases, a compile, the daemon), solution and oracle (two restarts, pulls, four Pods)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the symptom (a new sandbox fails with the 301 error, the proxy log shows the CONNECT to
    #    10.96.0.1:443) and the controls (the API answers directly, a cold pull works through the proxy only)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=long_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=long_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: restart; twice (the second after another restart): cold pull through the proxy, two new
    #    Pods with the Calico network, the nonce from one to the other, the proxy and API logs, the Pods removed
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
