"""
SO-74243015: "How to resolve kube-proxy stuck in container creating state?" -- a kube-proxy Pod
(and every other Pod) stays in ContainerCreating on a CRI-O node: the kubelet's RunPodSandbox
fails because CRI-O cannot pull its pause image (registry.k8s.io/pause) -- the node reaches the
internet only through a proxy, and the CRI-O service, which does the pull, runs without
HTTP_PROXY/HTTPS_PROXY (shell exports, /etc/profile.d and /etc/environment do not reach a
systemd service). The fix is the proxy in the ENVIRONMENT OF THE SERVICE (a drop-in with
Environment=HTTPS_PROXY=..., or an EnvironmentFile), a daemon-reload and a restart.

Adaptation (reported as such): no Kubernetes and no internet. The registry is the lab's own
HTTPS registry registry.bench74243015.test:35743 (private CA, name in /etc/hosts), the "egress
control" is a registry that accepts connections from the lab proxy's source address only
(everything else is reset and logged as a direct connection), the proxy is a CONNECT-only HTTP
proxy at 127.0.0.1:35744, the failure is a connection reset instead of an i/o timeout, and the
sandbox is made with `crictl runp` in the host's network namespace (so no CNI plugin interferes).
CRI-O is a private instance (unit bench74243015-crio.service, own config, root, socket) next to
the machine's crio.service.

Case design (first networking case with the restructured five-stage skeleton): setup.sh builds
a pause image (random label, so the digests differ per setup), the registry, the proxy, the
private CRI-O and its unit; helpers/lab.py records the truth (digests, hashes, process identity).
precondition.sh shows the symptom from both sides (shell: direct curl refused, curl --proxy gets
the recorded manifest and layer; service: no proxy variable, an empty store, runp fails twice on
the pull) and a control (a throw-away CRI-O with the same configuration and HTTPS_PROXY creates
the sandbox). oracle.sh runs helpers/verify.py: the lab is unchanged (config, registries.conf*,
certificates, blobs, the same registry and proxy processes), plain `systemctl restart`, the store
is cleared, a fresh sandbox must be SANDBOX_READY, the image in the store must be the lab's
(manifest digest, image ID, /proc/PID/exe of the pause), the registry must have served the
manifest and blobs to the proxy's address only (no direct connection in the window) and the proxy
must have tunnelled a CONNECT to the registry. A failure is explained from the service's
environment (no proxy, HTTP_PROXY only, NO_PROXY, a TLS proxy URL, no daemon-reload).

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/networking/q74243015/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Networking & Connectivity
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/networking/q74243015/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "networking" / "q74243015"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q74243015",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup (a compile, certificates, the service), solution and oracle (a restart, a pull)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the symptom (direct curl refused, curl --proxy works, the service has no
    #    proxy variable, runp fails on the pull) and a control (a throw-away CRI-O with HTTPS_PROXY works)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=long_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=long_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: restart, clear the store, a brand-new sandbox, the registry/proxy logs
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
