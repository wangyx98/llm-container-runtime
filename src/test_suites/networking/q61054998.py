"""
SO-61054998: "Start a container without restricting its network access" -- can runC start a container
that is not cut off from the host's network, so that a development container can be reached over
localhost? The asker thinks of cgroups; the comments correct it: the network is a namespace, and the
OCI runtime spec lets config.json either carry no "network" entry in linux.namespaces (the container
then inherits the namespace runc runs in) or give the entry a "path" to the namespace file of the host.
The namespace is fixed when the container is created, so a running container has to be created again.

Adaptation (reported as such): the question has no concrete setup; the lab is the bare runc bundle of
isolation/q66547508 (rootfs with one static program, a host service on 127.0.0.1 that sends a nonce),
extended in both directions: the program also listens on its own loopback port and answers with the
last nonce it read and its process id. The engineer's container is running from the first moment, in
a network namespace of its own (the runc default), and cannot read the host's nonce; the host cannot
reach the program's port. Mount and pid isolation are part of the task ("only the network is shared").

Case design: setup.sh builds the bundle, starts the host service and the first container.
precondition.sh shows the symptom (the container is in its own network namespace, its /data/state says
reach=fail, the host is refused on the program's port) and a control (a throw-away container from a copy
of the config without the network entry starts in the host's network namespace with its own mount and
pid namespaces and works in both directions). oracle.sh runs helpers/verify.py on the host: a NEW
container from the bundle (not the setup's process), the same program and arguments, its
/proc/PID/ns/net equal to the host's one recorded at setup, mnt and pid namespaces not the host's
(NSpid ends with 1), the host service unchanged and on 127.0.0.1 only, then a fresh nonce that the
program must carry back over the host's loopback (the listener socket is open in the container's
process, so nothing else on the host can fake the answer) and into /data/state.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/networking/q61054998/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Networking & Connectivity
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/networking/q61054998/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "networking" / "q61054998"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q61054998",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 240)   # setup (a compile, the container), solution and oracle (a container, a check of the sockets)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the symptom (the running container is in its own network namespace, reach=fail, the
    #    host is refused on its port) and the control (a container without the network entry works both ways)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=long_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=long_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: a new container from the bundle in the host's network namespace, its own mount and
    #    pid namespaces, loopback traffic in both directions with a fresh nonce
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
