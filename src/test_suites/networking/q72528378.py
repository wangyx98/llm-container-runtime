"""
SO-72528378: "Pulling image from insecure registery with containerd" -- `crictl pull
192.168.12.10/calculator/app2:new` fails with "Head https://192.168.12.10/v2/...: dial tcp
192.168.12.10:443: connect: connection refused", although /etc/containerd/config.toml has a mirror
with the endpoint http://192.168.12.10:80 and a config entry for it. The reference has no port, so
containerd looks the registry up under the key 192.168.12.10; the tables of the configuration are
keyed 192.168.12.10:80, which never matches, and the default https://...:443 is used. Fix: the keys
without the port (legacy tables), or (the accepted answer, docs/hosts.md) a config_path directory
with a directory named like the reference's host (no port) and a hosts.toml with server =
"http://HOST", the legacy tables removed (containerd's CRI plugin does not load with both), and a
restart. The reference stays as it is.

Adaptation (reported as such): the original registry is Harbor at an IP address; the lab's registry
is a protocol fixture (Docker registry API v2, plain HTTP on port 80 of the machine's non-loopback
address, no authentication; no Harbor feature is used): registry.bench72528378.test, a test domain
in /etc/hosts (containerd treats loopback registries as plain HTTP by itself, so not a loopback
address). containerd is the official 2.0.0 release (downloaded, checked against its published
sha256) as a private unit with a version 2 configuration, as in the question. Repository
calculator/app2 has the tags new (the workload) and asdf (a different image: the decoy).

Case design: setup.sh downloads and pins containerd 2.0.0, builds the registry and the images
(random digests), the unit and the configuration with the registry tables keyed HOST:80.
precondition.sh shows the symptom and the controls (the registry answers on 80 and nothing on 443;
ctr --plain-http pulls the reference; the CRI pull fails with "dial tcp IP:443: connect: connection
refused"). oracle.sh runs helpers/verify.py: lab unchanged (binaries, unit, registry process, images
and tags), plain `systemctl restart`, daemon = 2.0.0 with the CRI images plugin ok, the tag new
re-pointed to a NEW image (new digests), the cold CRI pull of the given reference, the image's
digests (not the decoy's), the registry's log (manifest and blobs, 200, Host header without a
port), create and start of a container whose output carries the evaluator's nonce and the image's
label. A pull with ctr or another reference cannot pass: the evaluator pulls the reference itself.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/networking/q72528378/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Networking & Connectivity
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/networking/q72528378/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "networking" / "q72528378"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q72528378",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 240)   # setup (a download of the release, a compile, the daemon), solution and oracle (a restart, pulls, a container)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the symptom (the CRI pull of the reference without a port fails with
    #    "dial tcp IP:443: connect: connection refused") and the controls (HTTP registry on port 80, ctr --plain-http works)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=long_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=long_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: restart; from an empty store pull the reference (the tag new, re-pointed to a
    #    new image), run it, registry log (plain HTTP, Host header without a port)
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
