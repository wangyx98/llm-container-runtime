"""
SO-70704948: "Container fails to download gradle". On Rancher Desktop (WSL2, containerd, nerdctl 0.15.0) `nerdctl build` of a Dockerfile whose RUN step runs ./gradlew times out downloading
gradle-7.0.2-bin.zip, while the same command typed in a container made from the same image works; switching nerdctl to the namespace k8s.io changes nothing. The question has no answer. What
it hides: a build does not run as a "nerdctl run" container: BuildKit starts the build containers itself, on a CNI network of its own, and writes their /etc/resolv.conf from the [dns] section
of its own configuration (buildkitd.toml), while the containers of "nerdctl run" take their name servers from nerdctl (nerdctl.toml or the host). A resolver that does not know the internal
download site, in the one place and not in the other, fails exactly the build.

Rancher Desktop and its WSL2 VM cannot run in the benchmark's sandbox or in a plain VM, and nerdctl 0.15.0 / BuildKit 0.9 are not reproducible there. The case keeps its structure on real
components (a documented modern adaptation): containerd of the machine, BuildKit v0.23.2 (containerd worker, CNI network mode) and nerdctl 2.1.3, the last two pinned by sha256 for x86_64
and aarch64, started and run by wrappers (buildkitctl, nerdctl) that stand for the OpenRC service and for `rdctl shell nerdctl`. The whole VM is one network and mount namespace (a process
holds it): its bridges, addresses and mounts disappear with it, nothing of the machine's network is touched, and the addresses of the lab cannot collide with the machine's. Inside: the
corporate name server and the download site (https://dists.bench70704948.test:43670, the Gradle distribution as a fixed archive with its sha256 in gradle-wrapper.properties, served by the
lab; services.gradle.org is not used) and the old resolver (NXDOMAIN for everything). The gradlew of the project is a stand-in of the wrapper script (the real one needs a JVM): it reads
gradle-wrapper.properties, downloads, checks the sha256, unpacks and runs a stand-in bin/gradle whose artifact build/libs/my-app-1.0.jar carries the distribution's random token, its sha256
and the sha256 of the sources. The base image is made from the machine's own tools (nothing is pulled).

precondition.sh: the build containers use the name server of buildkitd.toml (the old resolver), the containers of nerdctl run the one of nerdctl.toml (the corporate one); controls: a container
of nerdctl run downloads the distribution by name, a build container that is given the address by hand downloads it too, the build of the project fails with "curl: (6) Could not resolve
host" and the old resolver logged NXDOMAIN for the build container. The oracle (verify.py): the lab is unchanged (processes, programs, CNI, nerdctl.toml, the whole project, the
distribution), buildkitd runs (it is started if a solution stopped it), the build cache is emptied, `nerdctl build --no-cache` of the project succeeds and downloads the distribution once, from
a build container, with the right size, the corporate name server answered that build container, the artifact in the image has the expected sha256, and a container of nerdctl run still
downloads the distribution.

Where the samples fail: nothing done; buildkitd.toml corrected but buildkitd not restarted (the daemon reads it at start); the network mode of BuildKit switched to host (BuildKit writes /etc/resolv.conf from [dns] in
host mode too, and without [dns] it copies the host's, which does not know the name either); a public resolver (8.8.8.8) put into [dns]; the name given to one build with --add-host (the check's build has no such flag); the Dockerfile
changed so that nothing is downloaded. The valid alternative puts the corporate name server first and the old resolver second and restarts buildkitd with stop and start.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/networking/q70704948/ and converts their exit codes / output into a
structured `cases` dict.

Taxonomy category: Networking & Connectivity
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/networking/q70704948/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "networking" / "q70704948"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q70704948",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # every process of the VM is stopped, directories removed
    setup_timeout = max(timeout, 900)        # downloads BuildKit (about 85 MB) and nerdctl the first time, then starts the VM
    pre_timeout = max(timeout, 300)          # controls: a few small builds and runs
    solution_timeout = max(timeout, 600)     # a solution may restart buildkitd, or build once
    oracle_timeout = max(timeout, 900)       # empties the cache, builds once, runs the image

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the build cannot resolve the download site's name; the run container can; the controls hold
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: an empty build cache, the build of the project, its artifact, the run control
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
