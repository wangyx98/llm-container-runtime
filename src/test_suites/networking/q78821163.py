"""
SO-78821163: "Containerd, extend network interface/access to DIND container to perform docker pull" -- a
privileged Docker-in-Docker container made with the containerd Go client; the Docker inside it cannot
pull from a private registry: `lookup private-repo.local on [::1]:53 ... connection refused`. The
container has a network namespace of its own with nothing in it (containerd's spec has no resolv.conf and
no network setup; Kubernetes' CNI would have given the pod one), so there is neither a route nor a
resolver: the lookup goes to the defaults of Go's resolver, the loopback on port 53.

Adaptation (reported as such): the question has no concrete setup. The lab has two network namespaces of
its own (made without the ip tool): a node network (a bridge with a DNS server and a TLS registry
behind the name private-repo.local, reachable from nothing else on the machine) and a pod network (a
veth pair to that bridge, made by the CNI plugins bridge/host-local/loopback). The DIND image is made
from the Docker engine of the machine (Docker Hub is not needed); the Go program is a small starter
built on the containerd client v2.0.5 that makes and starts the container as the question does. The
choice between "keep the bridge/pod network" and "use the host network" is made in the task: the
container joins the pod network, the host's namespace is forbidden (and could not reach the registry).

Case design: setup.sh builds the images, the networks, the servers, the program and the first container.
precondition.sh shows the symptom (the inner Docker's pull error) and four controls with a probe in
throw-away containers of the same image, one thing changed at a time (network namespace, resolv.conf):
own namespace / pod namespace without resolv.conf (loopback :53), own namespace with resolv.conf
(network unreachable), pod namespace with resolv.conf (DNS, TCP, TLS and HTTP all fine). oracle.sh runs
helpers/verify.py: the container is removed, the program built from /tmp/bench78821163/app is run with
the fixed command line, the new container is in the pod's namespace (not the host's), the inner Docker
pulls a NEW image cold, the DNS and registry logs show the question and the pull from the container's
address (user agent of Docker), and the inner Docker runs it with a nonce (three pid namespaces, a
descendant of the container's first process).

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/networking/q78821163/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Networking & Connectivity
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/networking/q78821163/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "networking" / "q78821163"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q78821163",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 240)   # setup (images, networks, a compile, the container), solution (a compile) and oracle (a compile, a pull)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the symptom (the inner Docker cannot pull) and the four controls (namespace and resolv.conf, one at a time)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=long_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=long_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the program is built and run again; the new container is in the pod's network namespace, its Docker
    #    pulls a new image through the lab's DNS and registry and runs it with a nonce
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
