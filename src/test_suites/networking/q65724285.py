"""
SO-65724285: "Kubernetes with containerd : http: server gave HTTP response to HTTPS client" -- `sudo ctr
image pull 192.168.1.2:5000/my-alpine:latest` fails with "Head https://192.168.1.2:5000/v2/...: http:
server gave HTTP response to HTTPS client" although /etc/containerd/config.toml has a mirror with an
http endpoint and an insecure_skip_verify entry for the registry, and a Pod pull fails with the same
error. Two entrances, two causes: ctr does not read config.toml (the CRI plugin's settings are for the
CRI, i.e. kubelet and crictl); it needs --plain-http, or --hosts-dir with a hosts.toml (server =
"http://HOST:PORT") in the directory HOST:PORT. The CRI reads config.toml, where insecure_skip_verify only
skips the certificate check and does not turn https into http, so the registry needs a mirror whose
endpoint is http:// (or a config_path directory with hosts.toml), then a restart.

Adaptation (reported as such): no Kubernetes, so no Pod; the Kubernetes entrance is the CRI itself
(crictl pull, a sandbox and a container, the "minimal version" of the cluster). The CRI's mistake is
made deterministic: its mirror endpoint is https://HOST:5000 (a typo of the question's http://), next
to the skip_verify entry; the question itself does not say why the Pod fails. The registry is the lab's
own plain HTTP registry registry.bench65724285.test:5000 (test domain in /etc/hosts, the machine's
non-loopback address because containerd treats loopback registries as plain HTTP by itself, no
authentication, as in the question). The fixture is the private-unit lab of networking/q79305194 and
q72528378 (containerd 2.0.0, official release, sha256-pinned, version 2 configuration), not the
docker.io proxy rig of configuration/q76729881, whose egress gateway and Nexus stand-in this question
does not need; the exact ctr command with --hosts-dir is the same idea as in that case.

Case design: setup.sh downloads and pins containerd 2.0.0, builds the registry and the images (random
digests), the unit and the configuration (skip_verify + an https mirror). precondition.sh shows the
symptom and the controls (the registry is plain HTTP; ctr --plain-http pulls; the exact ctr command and
the CRI pull both fail with the HTTPS error; the mirror endpoint is https; no hosts directory).
oracle.sh runs helpers/verify.py: lab unchanged, plain `systemctl restart`, daemon = 2.0.0 with the CRI
images plugin ok, then the ctr entrance (the tag latest re-pointed to a NEW image, the exact command
`ctr images pull --hosts-dir /etc/bench65724285/certs.d REF` in the default namespace, digest, registry
log, `ctr run` with the evaluator's nonce and the image's label) and, separately, the CRI entrance
(store emptied, `latest` re-pointed to ANOTHER new image, crictl pull, digests, registry log, a sandbox
and a container with nonce and label). A success of one entrance never counts for the other; the FAIL
line names the failing entrance first.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/networking/q65724285/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Networking & Connectivity
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/networking/q65724285/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "networking" / "q65724285"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q65724285",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 240)   # setup (a download of the release, a compile, the daemon), solution and oracle (a restart, pulls, a container)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the symptom (the exact ctr command of the check and the CRI pull both fail
    #    with "server gave HTTP response to HTTPS client") and the controls (HTTP registry on port 5000, ctr --plain-http works)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=long_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=long_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: restart; the ctr entrance (exact command with --hosts-dir, ctr run) and, separately,
    #    the CRI entrance (pull, sandbox, container), each with a new image under the tag latest
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
