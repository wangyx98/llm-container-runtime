"""
SO-78631941: "containerd client + soci snapshotter: http: server gave HTTP response to HTTPS client" -- a Go
containerd client with a resolver for plain HTTP pulls an image through the SOCI snapshotter (lazy
loading through FUSE); the snapshotter does its own registry requests with its own configuration, uses
HTTPS for every host but localhost, and fails with "http: server gave HTTP response to HTTPS client": it
reports "failed to prepare remote snapshot", containerd falls back to downloading the whole layer and
unpacking it locally, and the pull still "works" without any lazy loading.

Adaptation (reported as such): the question has no concrete setup. The lab pins the SOCI snapshotter to
v0.16.1 (the first release whose resolver configuration also governs where the SOCI index and the ztocs
are fetched from; older releases use HTTPS for them for every host but localhost, which no configuration
can change) and the Go client to containerd v2.0.5; the images are made by `soci convert --standalone`
(a layer of ~48 MiB with twelve random 4 MiB files, a valid SOCI index and ztoc), so a missing ztoc can
not be the cause of a failure; the registry is plain HTTP at 10.78.63.2, an address that is not
localhost, in a network namespace of its own joined to the host by a veth pair (CNI ptp). The fix lives
in the snapshotter's configuration (an insecure mirror for the registry, a restart of the snapshotter),
not in the client.

Case design: setup.sh pins and downloads the CNI plugins and the SOCI release (checksums), builds the
workload, the Go program and the lab's own copy of it, starts the SOCI snapshotter (soci-service) and a
private containerd with the proxy plugin soci, and helpers/lab.py makes the registry, the image and the
first container (made by the program: it works, but without lazy loading). precondition.sh shows the
symptom (no FUSE mount; the snapshotter's log has the HTTPS error; the registry saw TLS handshakes on its
plain HTTP port and the layer sent whole to containerd) and two controls with a NEW image each, one thing
changed (the snapshotter's configuration): as it is, the container runs and the file reads but nothing
is lazy; with the insecure mirror the layer is mounted through FUSE, the snapshotter fetches the index,
the ztoc and ranges of the layer over HTTP, and the registry sends 8 of 48 MiB. oracle.sh runs
helpers/verify.py: the container and the images are removed, the program is built from
/tmp/bench78631941/app and run with a NEW image, the container runs with the snapshotter soci, the
layer is a FUSE mount of the snapshotter under the container's overlay root, a deep file (random)
reads with the sha256 it was made with, and the registry log shows ranged requests of the snapshotter
(user agent soci-snapshotter, one beyond 16 MiB), the index and ztoc fetched by it, no whole GET of the
layer by anything else and less than 60 % of the layer sent.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/networking/q78631941/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Networking & Connectivity
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/networking/q78631941/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "networking" / "q78631941"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q78631941",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 240)   # setup (downloads, images, a compile, the container), solution (a compile, a restart) and oracle (a compile, a pull)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the symptom (no lazy loading, the HTTPS error) and the two controls (the snapshotter's configuration as it is and with the insecure mirror)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=long_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=long_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the program is built and run again with a new image; the layer is lazy-loaded by the snapshotter through FUSE,
    #    a deep file reads with the right sha256, the registry saw ranged requests of the snapshotter over plain HTTP and no whole download
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
