"""
SO-71671179: "Kubernetes with CRI-O and docker private registry: pods running only on master node"
-- a three-node cluster (CRI-O) pulls from a private HTTPS registry (valid credentials in the
imagePullSecret): the master runs the Pods, both workers stay in ImagePullBackOff with "x509:
certificate signed by unknown authority". The secret is not the problem: the registry's CA is
not trusted by the CRI-O of the workers. CRI-O (containers/image) reads the CA from
/etc/containers/certs.d/HOST:PORT/ (or /etc/docker/certs.d/HOST:PORT/), keyed by host AND port,
on EACH node; /etc/crio/certs.d, a key without the port, or a certificate that was only copied
somewhere is ignored.

Adaptation (reported as such): no Kubernetes, no purchased certificate, no three machines. The
registry is the lab's own HTTPS registry registry.bench71671179.test:35751 (basic authentication,
private CA, name in /etc/hosts); the three nodes are three private CRI-O units (master, worker1,
worker2; own configuration, store and socket) on one machine, and the files a node's CRI-O reads
for registry certificates are the node's own (the unit bind-mounts
/var/lib/bench71671179/NODE/etc/{containers/certs.d,docker/certs.d,ssl/certs} over the machine's
directories; in a real cluster: the /etc of each machine). Workload = `crictl pull --creds` and a
sandbox with one container of the image on each node (the "minimal version" of the cluster); the
imagePullSecret is the credentials the oracle gives with every pull.

Case design: setup.sh builds the registry, two CAs, the images (random digests and label), the
three nodes; the master has the CA under etc/containers/certs.d/HOST:PORT, worker1 under
etc/crio/certs.d/HOST:PORT (a directory nothing reads), worker2 under etc/containers/certs.d/HOST
(no port). precondition.sh shows the symptom (valid credentials, master pulls and runs, workers
fail with x509 unknown authority) and the negative control (the registry presents a certificate of
ANOTHER CA for the same name: even the master fails). oracle.sh runs helpers/verify.py: lab
unchanged (node configurations, certificates, images, credentials, registry process), plain
`systemctl restart` of the three nodes, then for each node from an empty cache a pull, the
image's digests, a container whose output carries the oracle's nonce and the image's label, the
registry's log (valid credentials, verified certificate); then the negative control again: every
node must refuse the other CA (a node that pulls has stopped verifying).

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/networking/q71671179/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Networking & Connectivity
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/networking/q71671179/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "networking" / "q71671179"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q71671179",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 240)   # setup (a compile, certificates, three nodes), solution and oracle (three restarts, pulls, containers)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the symptom (the master pulls and runs the image, both workers fail with
    #    x509 unknown authority) and the negative control (another CA for the same name fails everywhere)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=long_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=long_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: restart the nodes; per node from an empty cache pull, run, registry log;
    #    the negative control (another CA, same name) must still be refused everywhere
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
