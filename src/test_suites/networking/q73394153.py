"""
SO-73394153: "How to set proxy credentials for Rancher Desktop". Behind a corporate firewall neither `nerdctl run` nor the Pods of k3s can pull from the registry: the name server cannot
resolve it (lookup ... no such host); the only way out is an HTTP proxy that wants credentials. The accepted answer exports HTTP_PROXY/HTTPS_PROXY/NO_PROXY in the VM's /etc/conf.d/docker;
a comment says the file is reset at every restart of Rancher Desktop. What the question hides: the two entries have two different environments (nerdctl pulls in the CLIENT process, the Pods
are pulled by the containerd of k3s, a child of the k3s service), the credentials belong in the proxy URL percent-encoded (a domain user name has a backslash, a password has "/", "#", "%"),
files the application writes again at every start do not keep the setting (a provisioning script does), and with HTTPS_PROXY on k3s the API server's traffic to the kubelet at the node's own
address goes through the proxy too unless NO_PROXY names it (`kubectl logs` breaks).

Rancher Desktop is a desktop application with a VM of its own and cannot run in the benchmark's sandbox or in a plain VM. The case keeps its structure on real components: the real k3s
v1.30.5+k3s1 with its embedded containerd (the containerd engine of Rancher Desktop) and nerdctl 2.1.3 (both pinned by sha256 for x86_64 and aarch64), started by a service script
(k3sctl; it sources /etc/bench73394153/conf.d/k3s) and a nerdctl wrapper (it sources /etc/bench73394153/profile) that stand for the OpenRC service and for `rdctl shell nerdctl`, and a
restart script (rdrestart) that writes those two files again from the VM image and runs the provisioning scripts (/etc/bench73394153/provision.d/*.sh) before k3s starts. The registry
(HTTPS, a name only the proxy resolves, a connection from any address but the proxy's is reset and logged as direct) and the proxy (Basic Proxy-Authorization; 407 without credentials or with
a wrong password; CONNECT to the registry only; the log never holds a password) are lab fixtures; the credentials are random per setup and in a root-only file.

precondition.sh: the proxy rules, the VM's files and services without a proxy, nerdctl and the Pod failing on the DNS lookup (the proxy and the registry see nothing); controls: nerdctl given
the proxy in its own environment pulls through it and a wrong password gets 407, a Pod from the local sandbox image runs and `kubectl logs` of it works. The oracle (verify.py): the lab is
unchanged, rdrestart, then for nerdctl and for k3s each: image cache emptied, a NEW image made (new digests, random label), pulled and run with a nonce (output, digest, registry log window with
manifest and both blobs, proxy log window with authenticated CONNECTs, no 407, no direct, no other target), `kubectl logs` of the Pod, and finally the password in no log, no output of the
restart and no command line.

Where the samples fail: nothing done; the settings only in the two files that rdrestart rewrites; credentials not percent-encoded; only one of the two entries configured (either one);
the accepted answer's variables without the node's address in NO_PROXY (the Pod runs, `kubectl logs` does not); a provisioning script that traces the password (set -x). The valid alternative
keeps the proxy URL in a separate root-only file that the provisioning script sources into both files, with all its variables in lower case.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/networking/q73394153/ and converts their exit codes / output into a
structured `cases` dict.

Taxonomy category: Networking & Connectivity
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/networking/q73394153/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "networking" / "q73394153"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q73394153",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 300)      # k3s and its containers are stopped, mounts and cgroups removed
    setup_timeout = max(timeout, 600)        # downloads k3s and nerdctl the first time, starts k3s, waits for the node and for the pull error
    pre_timeout = max(timeout, 300)          # controls: two pulls, a Pod
    solution_timeout = max(timeout, 600)     # a solution may restart Rancher Desktop (k3s) itself
    oracle_timeout = max(timeout, 900)       # a restart of Rancher Desktop and two pulls with their pods

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: neither nerdctl nor the Pod can pull (DNS); the proxy wants credentials; the controls hold
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: restart of Rancher Desktop, then nerdctl and k3s each pull and run a new image through the credentialed proxy
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
