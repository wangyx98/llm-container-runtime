"""
SO-60714937: "Pull images from local (insecure) registry on kind cluster". The asker follows the kind documentation of the time (a containerdConfigPatches entry with an HTTP
mirror for the registry), sees the mirror in /etc/containerd/config.toml of every node, and the pods still fail with ErrImagePull: "http: server gave HTTP response to HTTPS
client". Loading the image with kind load does not help either. The answer (insecure_skip_verify) is not the mechanism: what matters is that the configuration is the one containerd
really reads. The registry settings of the CRI plugin are read from the plugin id of the configuration FORMAT the file has; kind's node configuration is a version 2 file, whose registry
table is the one of io.containerd.grpc.v1.cri. The same lines under another plugin id (io.containerd.cri.v1.runtime, the id that the documentation of containerd 2.x uses for the
runtime settings) are visible in config.toml, are ignored by containerd ("Ignoring unknown key in TOML for plugin ... key=registry"), and the node pulls over HTTPS.

Measured in a sandbox with containerd 2.0.0, 2.1.3 and 2.2.3 and a version 2 file like kind's: the table under io.containerd.grpc.v1.cri (mirrors, mirrors+configs.tls, or config_path with a
hosts.toml) works; the same under io.containerd.cri.v1.runtime does not; `containerd config dump` (the configuration after containerd migrated it) shows the difference: with the table
under the right id its images plugin has a config_path or the mirror, otherwise an empty registry section and the warning in stderr.

Real kind: kind v0.30.0 (sha256 pinned for amd64 and arm64, cached), kindest/node v1.34.0 pinned by digest, three nodes (control-plane, worker, worker) on a Docker network of the lab
(10.249.60.0/24; the registry listens on its gateway address 10.249.60.1, a process of this machine, so the nodes reach it and the registry log carries the address of the node that asks).
The sandbox of the benchmark authors has no Docker daemon and cannot reach Docker Hub, so the kind part (cluster, pods, rebuild) is verified on a real VM only.

precondition.sh: three Ready nodes; each node shows the HTTP mirror in config.toml, runs containerd without --config, has an empty effective registry configuration; a cold CRI pull
fails on each node with "server gave HTTP response to HTTPS client" and the registry saw the TLS client hello of that node; cache semantics: an image loaded into a worker with kind load
runs there with imagePullPolicy IfNotPresent (the registry sees nothing) and fails with Always. The oracle (verify.py) checks the live cluster and then the rebuilt one (deleted and created
by the original create-cluster.sh from the solution's cluster file): same effective registry configuration on every node, a NEW image (new digests, nonce as argument) pulled by one Pod
per node (nodeName, imagePullPolicy Always, cache emptied) with the right label in its log and the new manifest as imageID, and the registry log shows each node fetching the manifest and
both blobs over plain HTTP.

Where the samples fail: no change; kind load only (a new image cannot be loaded); the fix inside the running nodes (right plugin id, containerd restarted: live cluster passes, the
rebuild does not). The valid alternative is the layout of the kind documentation: config_path in the cluster file and a hosts.toml of the registry mounted into every node.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/networking/q60714937/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Networking & Connectivity
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/networking/q60714937/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "networking" / "q60714937"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q60714937",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 300)      # docker rm of three node containers and their volumes
    setup_timeout = max(timeout, 1200)       # pulls the node image (about 1 GB) the first time and creates a three-node kind cluster
    pre_timeout = max(timeout, 600)          # three cold pulls, two control pods
    solution_timeout = max(timeout, 900)     # a solution may delete and create the cluster again (a few minutes)
    oracle_timeout = max(timeout, 1800)      # two rounds of three pods, and a rebuild of the cluster in between

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: three Ready nodes that show the HTTP mirror and still pull over HTTPS; the cold CRI pull fails on every node; controls: a loaded image runs with IfNotPresent and fails with Always
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the same working registry configuration on all three nodes, a new image pulled over HTTP by a Pod on every node, and the same again after the cluster was deleted and created again from the cluster file
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
