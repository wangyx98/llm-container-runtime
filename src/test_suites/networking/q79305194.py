"""
SO-79305194: "Unable to pull image from insecure registry, http: server gave HTTP response to HTTPS
client" -- containerd 2.0.0 with a configuration that says "version = 3" but still has the registry
tables of a version 1/2 configuration (mirrors with an http endpoint, configs with the credentials)
under the plugin id io.containerd.grpc.v1.cri. A version 3 configuration reads the registry
settings of the CRI plugin under io.containerd.cri.v1.images (the CRI plugin is split in an images
and a runtime plugin), so the old tables are ignored and the plain HTTP registry is contacted over
HTTPS. The supported fix is a config_path directory with a hosts.toml per registry (server =
"http://HOST:PORT") and a restart; the old tables moved to the new plugin id work too (deprecated).
The credentials in the Pod's secret carry the key of Docker Hub, so they never applied to the
registry: they must keep travelling with each pull request, not become node-wide.

Adaptation (reported as such): no Kubernetes 1.32 runner, so no Pod / imagePullSecret version: the
workload is a CRI pull (crictl pull --creds, as the kubelet does with the secret's credentials), a
sandbox and a container of the image; the credentials of the right domain are given by the
evaluator with each pull. The registry is the lab's own plain HTTP registry
registry.bench79305194.test:35791 on the machine's non-loopback address (containerd treats loopback
registries as plain HTTP by itself), basic authentication; containerd is the official 2.0.0 release
(downloaded, checked against its published sha256) as a private unit.

Case design: setup.sh downloads and pins containerd 2.0.0, builds the registry and two images
(random digests), the unit and the version 3 configuration with the old registry tables and the
credentials under the Docker Hub key. precondition.sh shows the symptom and the controls (the
registry is HTTP, 401/401/200; ctr --plain-http pulls with the credentials and not with wrong
ones; the CRI pull fails with "server gave HTTP response to HTTPS client"). oracle.sh runs
helpers/verify.py: lab unchanged (binaries, unit, registry process, images), plain `systemctl
restart`, daemon = 2.0.0 with a version 3 file and the CRI images plugin ok, a NEW image added to
the registry (new digests), the CRI pull with the credentials, the image's digests, the registry's
log (authenticated plain HTTP), a pull without credentials and one with wrong credentials (both must
be refused with 401: the credentials are not node-wide), create and start of a container whose
output carries the evaluator's nonce and the image's label.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/networking/q79305194/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Networking & Connectivity
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/networking/q79305194/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "networking" / "q79305194"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q79305194",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 240)   # setup (a download of the release, a compile, the daemon), solution and oracle (a restart, pulls, a container)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the symptom (the CRI pull with the right credentials fails with "server
    #    gave HTTP response to HTTPS client") and the controls (HTTP registry, ctr --plain-http works)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=long_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=long_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: restart; from an empty store pull a new image, run it, registry log;
    #    a pull without or with wrong credentials must still be refused
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
