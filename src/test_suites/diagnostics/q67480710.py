"""
SO-67480710: "Where do the log files live in a K8s cluster using the Containerd runtime?". An AKS cluster moved from Docker to containerd; the Fluentd
DaemonSet no longer collected the logs of the Spring applications, and the asker thought the files had moved. The answer: they have not (they are still
under /var/log/containers, symlinks into /var/log/pods); the DaemonSet's image reads them with the Docker JSON parser, but containerd (like CRI-O)
writes CRI lines, "TIMESTAMP STREAM FLAG TEXT", so the collector has to use the CRI parser. Fluentd and Fluent Bit are two tools for the same job; this
case uses Fluent Bit (its pinned binary is the one q73123230 fetches), whose tail input takes a regex parser called cri or the built-in "cri" multiline
parser. The AKS cluster itself is not reproduced: it is the log files and the collector that matter.

Local version: a private containerd (own socket, root and state) with its CRI plugin and crictl, which are real, runs one pod, web-0 of the namespace
default, with two real containers, app and sidecar, whose workload logs lines on stdout and on stderr as told. The runtime writes the CRI log files in
the kubelet layout (WORK/var/log/pods/default_web-0_UID/CONTAINER/0.log), and the lab makes the symlink the kubelet would make for each in
WORK/var/log/containers (web-0_default_CONTAINER-CID.log). The lines have a marker first and then a text that has to come through byte for byte:
indented, with a tab, with unicode, a JSON text, quotes and backslashes, trailing spaces. The record comes from what the lab told the workloads to log.
Fluent Bit is run by the oracle with the lab's main.conf (it includes the node's pipeline.conf and Parsers_File parsers.conf, and its output posts JSON
lines to the lab's local collector); the node's pipeline today is a tail input on the symlinks with the Docker parser. precondition.sh proves it:
with it, every record that reaches the collector is a whole CRI line with its envelope and has no stream.

The solution changes pipeline.conf and parsers.conf (the cri regex parser, or the built-in multiline cri parser). The oracle starts Fluent Bit and
checks, for the lines already in the files and again after the lab made both containers log more while Fluent Bit ran, that every line arrives as one
record whose `log` is the text exactly as written and whose `stream` is the stream it was written on, in order, nothing twice. Before and after, lab.py
check proves the runtime's files and the symlinks are untouched (still CRI format, still the recorded lines, links pointing to their files).

Where the samples fail: nothing changed (the envelope in `log`); a regex that leaves the flag in the text; a regex that takes the flag for the
stream; a pipeline that names the cri parser without defining it (Fluent Bit does not start); reading only what is written after the start
(Read_from_Head Off); a copy in Docker format made today and read instead (the new lines never arrive); and the runtime's own log files rewritten as
Docker JSON (the runtime does not write that). The built-in cri multiline parser is a valid alternative.

NOTE for whoever reads this: the sandbox this case was written in cannot reach the Fluent Bit package host, so the lab, the oracle and the sample
branches were exercised there against a stand-in that implements only the used parts of the configuration; the Fluent Bit configuration itself
(the cri parser, the multiline.parser, time parsing, what is kept in a record) is checked for real the first time on a machine with the pinned binary.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/diagnostics/q67480710/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Diagnostics & Observability
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q67480710/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q67480710"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q67480710",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup compiles the workload, starts the node, one pod with two containers and the collector, and fetches the pinned Fluent Bit once; the oracle runs Fluent Bit for up to about a minute

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: real CRI workloads log on both streams; read with the node's Docker parser, every record has the CRI envelope and no stream
    pre = run_script(CASE_DIR / "precondition.sh", timeout=long_timeout)   # it runs the real Fluent Bit once
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: with the solution's pipeline Fluent Bit delivers every line as one record (text and stream exact), old and new; the runtime's files and symlinks are untouched
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
