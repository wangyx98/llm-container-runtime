"""
SO-71482106: "Why I can't see pause containers in GKE containerd CRI?". On a node whose runtime is containerd, `crictl ps` (even `-a`) lists no
pause container, and the asker suspects the pods have none. They do: the CRI separates the pod sandbox from the containers. `crictl ps` lists
containers only, `crictl pods` lists the sandboxes (the IDs match those of the pods), and the sandbox's process (the "pause" container) is the one
that holds the pod's network namespace, which the pod's containers join. (`ctr -n k8s.io containers ls` shows both kinds.)

Local version: a GKE node cannot be reproduced in a sandbox, so this case is an adaptation, a CRI node: a private containerd (own socket, root and
state) with its CRI plugin and crictl, which are real. GKE specifics (the managed node image, the Google-built pause image, cos-toolbox) are not
kept; a runner with a real GKE node would be needed for them. The pods get a network namespace of their own through a CNI plugin that sets
nothing up (a few lines of shell: the namespace is created by containerd, the stub only answers; no network is configured).

Setup imports two images (a sandbox image whose only program is /pause, and a workload image whose only program is /work) and runs two pods through
the CRI: shop/web-0 (containers app and sidecar) and shop/db-0 (containers db and holder; holder runs the SANDBOX image, so a process called pause
exists that is not a sandbox). The lab records what the node holds from what it created and from /proc: every sandbox with the PID of its pause
process and its net namespace, every container with its pod, name, PID and net namespace. precondition.sh proves it, and that crictl ps -a shows no
sandbox while three processes are called pause.

The solution is a script /tmp/bench71482106/pause-map.sh OUTPUT_FILE that writes a JSON list with one object per sandbox: sandbox_id (64 hex),
pod (namespace/name), pause_pid, netns (the number of the net namespace of that process) and its containers (id, name, pid, netns). The oracle runs it,
compares with the record (verify.py), checks the node is unchanged (lab.py check: nothing deleted, recreated, restarted or added); then the lab
changes the node (a new pod infra/cache-0 and a new container in shop/web-0) and the script runs again: the answers are those of the new state, so
neither a replay nor a guess by process name survives.

Where the samples fail: no script; the processes called pause taken for the sandboxes (right for the first run, wrong for the pod added later:
the guess takes the pid of the workload that runs the program of that name); a replay of the mapping frozen at solution time (the new pod is
missing); short (13-character) IDs; the net namespace of the sandbox left out; every container of the node listed under each pod; a pod
removed after mapping it (the node is changed). `crictl inspectp` / `inspect`, and the tasks of `ctr -n k8s.io`, are valid.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/diagnostics/q71482106/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Diagnostics & Observability
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q71482106/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q71482106"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q71482106",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup compiles a program, starts the node and two pods; the oracle runs the script twice

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: a CRI node with two pods whose sandboxes crictl ps -a does not list, a workload called pause-like, no pause-map.sh
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: pause-map.sh maps every pod sandbox to its pause PID, net namespace and own containers, before and after the node changes, and changes nothing
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
