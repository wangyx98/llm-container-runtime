"""
SO-72361508: "The amount of container-runtime's logs increased significantly after migration to containerd at GKE" (GKE 1.21.11, node image changed from Docker to containerd: the
`container-runtime` log stream got millions of info records a day, mostly containerd's own operations, and costs money; asks whether containerd's logging level can be
configured at GKE or how else to reduce it; no answer, no comment, no sample of the log lines).

Adaptation (stated in task.txt): a GKE node image is managed and its containerd configuration is not the user's to edit (the user's tool there is a logging exclusion in
the cloud, another layer), so the case is the self-managed version: a private containerd node whose operator owns its configuration file and has to cut the volume of the
runtime's own log (the stand-in of the container-runtime stream) while keeping warnings and errors and the workload's own logs. The bill is not an oracle.

Setup: a busybox image built offline (also the pods' sandbox image), a private containerd (version-3 configuration with `[debug] level = "info"`, own socket/root/state, CRI on,
no NRI, no CNI), node-ctl (start|stop|restart|status; containerd's stderr is appended to the node's log and a second raw copy goes to the root-only state), node-crictl, and the
workload web (a numbered line a second; its CRI log file). precondition.sh: node, web (growing log) and configuration as recorded; the node's log is the raw stream and holds
>= 50 info lines; one pod's life adds >= 15 info lines and a failing pull an error; control: a second containerd with the same configuration writes ~100 info lines at level
info and at most 10 at level warn, keeping its warnings. Oracle (dynamic): wrappers unchanged; `node-ctl restart`: at most 10 info lines at the start (those before the
configuration is read) and all the warnings of the baseline; 5 pods (a container that prints and ends, then removed) and a failing image pull: no info/debug line in the raw
stream, an error line; the node's log file equals the raw stream (no filtering after the write); web is the same running container and its CRI log is intact (same inode, first
line, every number once in order, growing); `node-ctl stop` + `start` and the same replay again.

Taxonomy category: Diagnostics & Observability
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q72361508/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q72361508"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q72361508", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 600)        # a first run may install busybox-static
    pre_timeout = max(timeout, 120)
    solution_timeout = max(timeout, 180)
    oracle_timeout = max(timeout, 240)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the node and web as recorded, the node's log is full of info lines, a lower level in the same configuration cuts them (control)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the node is restarted and works again, the raw stream of containerd is the truth
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
