"""
SO-73550556: "Error no OpenTelemetry when containerd starts. Containerd version 1.6.8" (2022). containerd 1.6.8 logs at every start `level=error msg="failed to initialize a tracing processor \\"otlp\\""
error="no OpenTelemetry endpoint: skip plugin"`. The question's only answer says the message is harmless: containerd works, the tracing plugin is optional. The case therefore has NO fault to repair and
the task says so; it is an OPERATION ADAPTATION: the message is read as "tracing is off" and the goal is to turn tracing on, judged by real spans, never by the message.

What was measured (containerd 1.6.8 and OpenTelemetry Collector 0.91.0, linux/amd64 in the Claude sandbox; arm64 pinned too, run on the VM): with the default configuration the line of the question is
logged (plus an info `skip loading plugin ... otlp`) and containerd serves CRI normally; the processor `[plugins."io.containerd.tracing.processor.v1.otlp"]` needs `endpoint` as a URL: `127.0.0.1:4318`
is rejected (`first path segment in URL cannot contain colon`, a failed plugin and the same error line); spans are exported only to an OTLP/HTTP (protobuf) endpoint, http://127.0.0.1:4318 (also with
/v1/traces, also localhost), protocol "" or "http/protobuf"; http://127.0.0.1:4317 (the collector's gRPC port), protocol "grpc" and https:// export nothing and log nothing (silent failures: no error line,
no span). The otelgrpc server interceptors give one span per CRI call (rpc.service, rpc.method, status code), and the CRI plugin adds events naming the pod, the container and the returned ids
(`RunPodSandbox for &PodSandboxMetadata{Name:...}` ... `returns sandbox id "..."`), which is what ties a span to a call of the check. The batch exporter sends every ~5 s. The configuration is read at start.

What is built: a private containerd 1.6.8 with the CRI plugin and a pod whose container logs a numbered line every half second (a per-run token); the lab's real OpenTelemetry Collector 0.91.0 (OTLP gRPC
127.0.0.1:4317 and HTTP 127.0.0.1:4318, file exporter to spans.jsonl) started by otelctl; offline images; downloads (containerd, runc, crictl, collector) pinned by sha256, cached in /var/cache.

precondition.sh: lab files and processes; the default otlp section and the question's error line in containerd's log (one start only); the container logs; the collector listens on 4317 and 4318 and takes an
empty OTLP request; after CRI calls and 8 s the collector has no span (the control: no endpoint, no trace, and nothing broken).
The oracle (oracle.sh): lab files unchanged; containerd and the collector are the lab's (the collector was not restarted); the container of setup is the same one, Running, and still logs; the log of the
current start of containerd has no tracing-processor error; then random N1 (2..5) `crictl pods`, N2 (2..5) `crictl images` and a new pod `trace-<random>` with a container `app-<random>` that must run and
log; the spans that started after the check began must be exactly N1 ListPodSandbox, exactly N2 ListImages, and one RunPodSandbox / CreateContainer / StartContainer span each whose events carry the pod's
name and id, the container's name and id; status 0. It waits up to 40 s for the batch and 6 s more before it counts.

Where the samples fail: no-op; endpoint without scheme; http on the gRPC port 4317; protocol grpc on 4317 (the two silent ones); the configuration edited but containerd not restarted; the message hidden by
disabling the tracing plugins; tracing on but the CRI plugin disabled (the workload dies); spans forged by a POST to the collector (the ids are not theirs); the collector stopped after the fix. Valid: the
reference (http://127.0.0.1:4318, restart); the /v1/traces path; localhost with protocol http/protobuf; another service_name.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/diagnostics/q73550556/ and converts their results into the structured `cases` dict.

Taxonomy category: Runtime Diagnostics
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q73550556/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q73550556"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q73550556",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containerd, the collector, mounts
    setup_timeout = max(timeout, 600)        # the first run downloads 60 MB; later runs take 10 s
    pre_timeout = max(timeout, 240)          # 8 s of waiting for spans that must not come
    solution_timeout = max(timeout, 180)     # a solution edits a configuration and restarts containerd
    oracle_timeout = max(timeout, 120)       # the batch export (5 s), up to 40 s of waiting and 6 s of grace

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: containerd logs the "no OpenTelemetry endpoint" error and works, the collector is up and has received nothing
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the spans of the check's own random calls reach the collector and the workloads run
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
