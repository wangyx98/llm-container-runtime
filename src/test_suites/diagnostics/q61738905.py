"""
SO-61738905: "How to list docker containers using runc". `runc list` shows nothing for the containers Docker runs; the asker tried /var/lib/docker/containers as the root (runc says the
containers do not exist) and does not know which root directory Docker passes. The answer: Docker keeps runc's state in <exec-root>/runtime-runc/moby (usually /run/docker/runtime-runc/moby),
`sudo runc --root DIR list`; ways to find it: the `--runtime-root` argument of a process (`ps aux | grep runtime-root`), the containerd configuration, /etc/docker/daemon.json, or strace on
containerd while a container is restarted (the answer warns about this one). The asker's `ps` shows dockerd with only `-H fd:// --containerd=...`: no root named.

Same mechanism as q57009928 (runc root of Docker); this is its thin variant: only the runc root and the containers, no containerd socket/namespace/images, and the root cannot be read from the
command line: the daemon is started with `--host unix://SOCK --config-file daemon.json` and everything else (exec root with a random name, containerd socket, data root) is in the file.
precondition.sh proves that: the command line has no root, `ps | grep runtime-root` finds nothing, default `runc list` is empty, `runc --root <exec-root>/runtime-runc/moby list` shows Docker's two
running containers with the PIDs Docker gives.

The solution is a script /tmp/bench61738905/find-runc-root.sh OUTPUT_FILE that writes {"runc_root", "containers": [{id, pid, status}]}. The oracle (verify.py) runs it, checks that the node is
unchanged (lab.py check: the same containers in Docker, every one running with the PID it had, the same directories in the runtime root), and compares the root and the containers (the full 64-hex
IDs `docker run` printed, the PIDs `docker inspect` says) with the lab's record; then the lab changes the node (a container started, one removed) and the script is run and compared again.

Where the samples fail: no script; the usual Docker root of the answer (not there: the script fails); the root from `ps` with runc's default root as the fallback (wrong root); `docker ps -q` short
IDs; a replay of the first run's output (after the change); a container restarted "to catch runc's arguments" (the node is changed). Scanning /run for state.json files is a valid alternative.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/diagnostics/q61738905/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Diagnostics & Observability
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q61738905/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q61738905"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q61738905",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup compiles one program, starts containerd and Docker and two containers; the oracle runs the script twice

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: Docker (settings in a configuration file, random exec root) runs two containers, nothing is visible with runc's defaults, no find-runc-root.sh
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: find-runc-root.sh finds Docker's runtime root and lists the containers with their full IDs and PIDs, before and after the node changes, and changes nothing
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
