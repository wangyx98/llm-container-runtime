"""
SO-63115522: "Creating a sibling process to a container using containerd"

Weave's kube-utils (started by launch.sh) shows up in `ps --forest` as a SIBLING of launch.sh, a child of the
containerd-shim; the asker's own experiment gives children of launch.sh. The thread's answer says hostPID plus
privileged; the comment says double fork plus a shim that is a subreaper. Here it is measured.

Setup: a private containerd 1.6.17 with the CRI plugin and runc 1.1.12, an offline image whose main process starts an
ordinary child and a short-lived parent that starts a grandchild (random token in its argv) and exits; three pods run:
host (hostPID), iso (own pid namespace), priv (privileged, own pid namespace). The grandchild is the shim's child with
hostPID and the container init's child in the other two: privileged does not matter.

Task: write the read-only tool /var/lib/bench63115522/proctree that prints one JSON object with, per container, the
orphan (pid, ppid, starttime, NSpid, pid namespace), that its creator exited, who adopted it (pid, comm, kind
shim / container_init / host_init / other) and the containerd-shim among its ancestors and whether that shim owns the
container.

Oracle (nothing is taken from what the solution says): the report equals an independent measurement (the oracle's
own record of the ids, the log files, ctr tasks, /proc) field by field; the lab's modes give the expected adopters;
the tool is read-only (processes, containers, tasks, pods, logs); and the oracle creates four NEW pods (hostPID, own
pid namespace, privileged, hostPID + privileged) with fresh tokens, for which the tool must be right as well.
"""



from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q63115522/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q63115522"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q63115522",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containerd, mounts
    setup_timeout = max(timeout, 600)        # the first run downloads 30 MB; later runs take 20 s
    pre_timeout = max(timeout, 120)          # reads only
    solution_timeout = max(timeout, 120)     # a tool and one run of it
    oracle_timeout = max(timeout, 400)       # four new pods, and the tool run twice with fingerprints

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the grandchild is the shim's child with hostPID and the container init's child without it
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: proctree equals the measured process trees for the pods that run and for four new ones, and is read-only
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
