"""
SO-75622952: "failed to unpack image on snapshotter overlayfs: unexpected media type text/html" (2023). A Kubernetes node (containerd v1.6.17, Harbor v2.5.5 as the registry, CA file and account in the
registry settings of containerd) cannot pull an image: `failed to unpack image on snapshotter overlayfs: unexpected media type text/html for sha256:...`. The question did not save a single HTTP response, and
the thread's answer ("trust the CA") does not fit: a certificate problem is an x509 error, not text/html.

What is built (a CONTROLLED STAND-IN, not a Harbor, and the cause below is an inference measured in the lab, not reproduced on a real Harbor): a private containerd 1.6.17 with the CRI plugin and runc v1.1.12
(below /var/lib/bench75622952 and /run/bench75622952; the machine's own containerd is not touched), and a small Python TLS front at 10.75.62.29:8443 (a /32 alias of lo: containerd takes 127.x for a plain-HTTP
registry) that has only the ROUTES of a Harbor 2.5: /v2/ the registry API with Bearer tokens, /service/token the account check (admin / Harbor12345), any other path the portal page ("200 text/html", the catch-all
of the single page application). It serves one offline image (a static program that prints a per-run token) and logs every request as a JSON line. Its certificates: the lab CA's, and a second one for the same
name from a CA nobody trusts (a mode file switches them) to prove that a client verifies. The node has the question's registry settings: configs.<host>.tls.ca_file, insecure_skip_verify=false, configs.<host>.auth,
and mirrors.<host>.endpoint = ["https://<host>/"] - with a trailing slash.
Measured (containerd 1.6.17): the path of a mirror endpoint is the root of the registry API and /v2 is added only if the path is empty ("https://host") or "/v2/"; "https://host/" gives
`HEAD /k8mtest/k8m/manifests/v1.0` (no /v2). That path is the portal page (200, text/html, no Docker-Content-Digest), containerd takes its bytes for the manifest, and the digest in the error is the sha256 of the
page. That is exactly the question's message. A wrong CA gives x509, not this. (Whether the thread's real config had that slash is not known; the lab only shows that this config produces this error.)

precondition.sh: the lab's files, the front, containerd 1.6.17; the effective settings (crictl info) are the question's; the registry is fine (401 + Bearer challenge, token for the account, manifest under the recorded
digest, anonymous refused, portal page outside /v2/, second certificate not trusted); the CRI pull fails with the question's error and the digest in it is the portal page's; the front's log shows the node asking a
path without /v2, with no authorization, and getting 200 text/html.
The oracle (oracle.sh): lab files, front process, node containerd and the machine's trust store unchanged; effective settings not weakened (https endpoints on the registry's address, verification on); cold pull
(pods and image removed) succeeds with the recorded digest; the front's log shows the token request (Basic, 200) and HEAD/GET of the manifest below /v2/ with a Bearer token, nothing text/html; the pod and the
container run and print the token; with the second certificate shown a cold pull must fail with "certificate signed by unknown authority"; an anonymous manifest request is still 401.

Where the samples fail: no-op; only the CA put into the system trust (the endpoint is the problem); the endpoint fixed but containerd not restarted; the account removed; an http:// endpoint; the loopback address
as endpoint; the image put into k8s.io with ctr (the check pulls cold); insecure_skip_verify=true (pull works, the second certificate is accepted); the front edited. Valid: the endpoint without the slash (the
reference); the endpoint "https://<host>/v2/"; the mirror entry removed altogether.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/diagnostics/q75622952/ and converts their results into the structured `cases` dict.

Taxonomy category: Runtime Diagnostics
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q75622952/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q75622952"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q75622952",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containerd, mounts
    setup_timeout = max(timeout, 600)        # the first run downloads 60 MB; later runs take 15 s
    pre_timeout = max(timeout, 240)          # curl controls and one failing pull
    solution_timeout = max(timeout, 180)     # a solution edits the configuration, restarts containerd and pulls
    oracle_timeout = max(timeout, 400)       # two cold pulls, a pod and a failing pull

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the registry is fine, the node's settings are the question's, the pull fails with text/html and the digest of the portal page
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: cold pull and run through the CRI, authenticated, with the verification and the registry's authentication still working
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
