"""
SO-67889258: "Docker service doesn't start after hard host reboot" (2021). After a hard reset the system containerd (1.4.6) does not start any more, it panics in bbolt in the metadata plugin
(`slice bounds out of range [::4294852604] with length 2147483647`, `bbolt.(*leafPageElement).key <- Cursor.nsearch <- metadata.(*DB).Init`); reinstalling the packages does not help (they do not touch
/var/lib/containerd), and Docker's own containerd (another root, /var/lib/docker/containerd/daemon) still starts. The thread has no answer and no comment: the truth below is an ADAPTATION measured in the lab.

What is built: a private containerd 1.6.17 (1.4.6 has no arm64 build; the same panic was measured with 1.4.6 and 1.6.17) with runc v1.1.12 and no CRI plugin, below /var/lib/bench67889258 and
/run/bench67889258 (the machine's own containerd is not touched). setup.sh starts it, imports one offline image, starts a container c1 (label bench.token) whose program writes /marker once and /beat every
second into its writable snapshot, records images / c1 (creation time, label) / manifest digest, makes one more transaction (a label on c1), kills everything with SIGKILL, removes /run (a hard reboot) and
tears the root page of the newest bbolt transaction (garbage in the 'pos' of its first element, which gives the question's panic). The previous transaction is intact in the same file.
Measured: bbolt keeps two meta pages and writes copy-on-write; if the newer meta page is not valid (wrong magic or checksum; a checksum of 0 means "none" and is ACCEPTED) it opens the older one. Only the last
transaction is lost. Deleting meta.db or moving it aside starts the daemon but loses images, container records, leases and the link to c1's snapshot.

precondition.sh: lab files, the node is not running and its start panics as in the question (leafPageElement.key / nsearch / metadata.DB.Init), meta.db is the recorded broken file with two valid meta pages of
two transactions with different roots, the manifest blob and c1's snapshot (with /marker) are on disk, the evidence directory is empty.
The oracle (oracle.sh): lab files and containerd.toml unchanged, the running containerd is the node's 1.6.17; a copy of the broken meta.db (recorded sha256) is in the evidence directory; the image (name, digest),
c1 (creation time, image, bench.token) and its active snapshot are the original ones; c1's task starts and writes /beat with the token, the /marker written before the accident is still there; after a restart
of the node's containerd the same records are there.

Where the samples fail: no-op; deleting meta.db; moving it aside and importing the image again with a new c1; no evidence copy; evidence copied after the file was patched; the older meta page invalidated (the
newer one is still used); the newer meta's checksum set to 0 (accepted); restarting only; the configuration pointed at a new root. Valid: the newer meta's checksum made wrong (the reference), its magic zeroed,
the older meta's contents copied over the newer one.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/diagnostics/q67889258/ and converts their results into the structured `cases` dict.

Taxonomy category: Runtime Diagnostics
"""


from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q67889258/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q67889258"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q67889258",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containerd, mounts
    setup_timeout = max(timeout, 600)        # the first run downloads 30 MB; later runs take 20 s
    pre_timeout = max(timeout, 240)          # one failing start of containerd
    solution_timeout = max(timeout, 180)     # a solution copies and patches the database and starts containerd
    oracle_timeout = max(timeout, 400)       # a task start and a restart of containerd

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the node's start panics in bbolt as in the question, the data is on disk
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the original image, c1 and its snapshot are back, the workload runs, the broken file is kept
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
