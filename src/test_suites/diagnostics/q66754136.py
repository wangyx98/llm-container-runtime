"""
SO-66754136: "How Do I define a microk8s.ctr filter?". The asker could not tell how to list only the images of a MicroK8s node whose ref contains
"kafka" with `microk8s.ctr image ls`. The answer is the filter grammar of `ctr images list`: the field is `name` (the ref; there is no field `ref`, and a
filter on an unknown field silently lists nothing), `~=` is an UNANCHORED regular expression (`==` and `!=` are exact), a comma inside one filter is
AND and several filters are OR, and in a quoted value a backslash must be written twice (`\\.`; `\.` is "illegal escape sequence").

Local version: a private containerd (own socket, root and state; MicroK8s's containerd is the same program, its images are in the namespace k8s.io).
Setup imports images into two namespaces: k8s.io holds nine refs (five contain "kafka": bitnami/kafka:2.7.0-debian-10-r1, bitnami/kafka:3.4.0-debian-11-r2,
registry.local/data/kafka-exporter:1.2.0, registry.local/bitnami/kafka:2-7-0 and registry.local/data/kafkaesque:1; and zookeeper, nginx, pause and a
"radio/stat" image that do not) and default holds two (one of them a kafka ref, which is the namespace plain `ctr` shows). The refs have the characters
a regular expression treats in its own way: dots (the ref "bitnami/kafka:2.7.0-..." and the lookalike "bitnami/kafka:2-7-0" differ only where the
pattern's dot matches anything) and slashes. precondition.sh proves the problem: plain `ctr images list` shows the default namespace only, a filter on
`ref` lists nothing, and the text "bitnami/kafka:2.7.0" put unescaped in the regex lists two refs of which one does not contain it.

The solution is a script /tmp/bench66754136/ref-filter.sh TEXT OUTPUT_FILE that writes ONE filter line, and the filter has to list, through
`ctr -n k8s.io images list -q FILTER`, exactly the refs that contain TEXT as plain text (regular expression characters are literal). The oracle runs it for
seven texts (kafka, bitnami/kafka:2.7.0, kafka-exporter, 10-r1, google_containers, .io/, nginx:1.21), runs `ctr` with each filter, compares the refs with
those containing the text, and checks that the images and the content stores are exactly as the lab left them; then the lab imports new images (kafka 3.5.0,
kafka-connect, redis and a second "stat" image) and the script is run again for four more texts (the two new ones among them).

Where the samples fail: no script; the filter on `ref` (lists nothing, no error); the text put in the regex unescaped (an extra ref); `re.escape` with single
backslashes inside the quotes (ctr rejects the filter); an alternation of the refs of the day the script first ran (right first, wrong after the new
images); and the images that do not match removed first (the node is changed). Escaping with bracket expressions instead of backslashes is a valid
alternative.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/diagnostics/q66754136/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Diagnostics & Observability
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q66754136/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q66754136"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q66754136",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup starts the node and imports thirteen images; the oracle runs the script for eleven texts

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: a containerd with images in k8s.io and default, plain ctr showing default only, the filter grammar traps present, no ref-filter.sh
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: ref-filter.sh writes a filter that lists exactly the refs containing the text, for seven texts, then again after new images arrive, and the images are unchanged
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
