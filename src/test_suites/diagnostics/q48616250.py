"""
SO-48616250: "Can docker and cricontainerd co exist". A node has Docker and cri-containerd. `docker ps` shows nothing while `crictl ps` lists containers, and `ctr containers
list` lists nothing either; the asker wants to know how the commands differ. The only answer: the CRI plugin keeps its objects in the containerd namespace `k8s.io`
(crictl's documentation says so), `ctr ns ls` lists the namespaces (k8s.io, moby), and `ctr -n k8s.io containers ls` shows what crictl created; `ctr` looks at `default`
unless -n is given. (Docker's namespace is moby.)

Local version: ONE containerd (own socket, root and state; the CRI plugin on, a local sandbox image) shared by a private Docker daemon (own socket, `--containerd` that socket,
images in containerd) and the CRI. Docker has three containers in the namespace moby: two run and one ran and exited. The CRI has one pod sandbox (web-0, in the Kubernetes
namespace default) with three containers in the namespace k8s.io: two run and one exited. The namespace default of containerd is empty. Each client shows a different set:
`docker ps` the running ones of Docker (`-a` all three), `crictl ps` the running CRI containers (`-a` all three) and `crictl pods` the sandbox, `ctr -n k8s.io containers ls` the
sandbox and the three CRI containers (a sandbox is a container of containerd), `ctr -n moby containers ls` only the RUNNING Docker containers (Docker removes a container from
containerd when it stops), `ctr containers ls` nothing. precondition.sh proves all of it, and that the Kubernetes namespace of the pod is "default" (which is not the containerd
namespace "default": the two must not be mixed, and neither is a Linux namespace).

The solution is a script /tmp/bench48616250/list-containers.sh OUTPUT_FILE that writes a JSON object: docker (socket, containerd_namespace, containers of `docker ps -a`), cri (socket,
containerd_namespace, kubernetes_namespace, containers of `crictl ps -a`, sandboxes of `crictl pods`) and ctr (socket, namespaces: for every namespace of `ctr namespaces ls` and
default, the IDs `ctr -n NAME containers list` shows). The oracle runs it, checks that the node is unchanged (lab.py check: the same containers in Docker, in the CRI and in both
containerd namespaces, every running one with the same process and start time, every exited one still exited) and compares each API's exact set, socket and containerd namespace
with the lab's record (the IDs are what `docker run`, `crictl runp` and `crictl create` printed); then the lab changes the node (Docker gets a new running container and loses the
exited one; the pod gets a new running container and loses the exited one) and the script is run and compared again.

Where the samples fail: no script; `docker ps` without -a; `crictl ps` without -a; ctr read in the namespace default only; the containers of ctr in k8s.io given as the containers of the
CRI (the sandbox is not one); the Kubernetes namespace given as the containerd namespace; Docker's socket named as the CRI's; a replay of the first run's output (after the change); and the
stopped Docker containers pruned first (the node is changed). Reading the JSON output of docker and crictl is a valid alternative.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/diagnostics/q48616250/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Diagnostics & Observability
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q48616250/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q48616250"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q48616250",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup compiles one program, starts containerd and Docker, makes Docker containers and a CRI pod; the oracle runs the script twice

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: one containerd shared by Docker (moby) and the CRI (k8s.io), default empty, each client showing its own set, no list-containers.sh
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: list-containers.sh reports what Docker, the CRI (containers and sandboxes) and ctr (every namespace) list, with the socket and the containerd namespace of each, before and after the node changes, and changes nothing
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
