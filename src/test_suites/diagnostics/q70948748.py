"""
SO-70948748: "How to retrieve the pod/container in which run a given process". With crictl on a containerd node, which pod and container does a host PID
(as `ps` shows it) belong to? The answers: compare the PID with the `info.pid` of every container (`crictl inspect`), which is the PID of the
FIRST process of a container only; read /proc/PID/environ for HOSTNAME (a process can change it) or /proc/PID/mountinfo (the container ID is in it);
`nsenter -t PID -u hostname` for the pod name (the asker's own answer says it fails for two pods of the same name, even in different namespaces); or
the cgroup of the process, which names the container whatever the depth of the process. The cgroup route and a climb of the parent chain to a
container's first process are the ones that are exact.

Local version: a node cannot be reproduced in a sandbox, so this case is an adaptation, a CRI node: a private containerd (own socket, root and
state) with its CRI plugin and crictl, which are real. The kubelet is not there: the lab gives the pods and containers the labels the kubelet gives
them (pod name, namespace, UID, container name), a host name equal to the pod's name, a network namespace of its own through a CNI plugin that sets
nothing up (cni-stub.sh), and a PID namespace per container, as the kubelet does (a pod's default would be one for the whole pod, with the pause
process taking over the orphans). pause and the pod sandbox are not the subject; owners of workload processes are.

Setup runs two pods of the SAME name, team-a/api-0 and team-b/api-0 (each with its own UID), with two containers each, app and sidecar. The
workload is an application that starts processes when its script says so: every container has its first process, a child, a grandchild below the
child, and an orphan (its parent exited; the first process took it over). A decoy process of the node (it is in no container) has HOSTNAME=api-0 in
its environment. The PIDs are whatever the kernel gave, with throw-away processes started between the steps so that they are not in step. The record
comes from what the lab created and from the process table of the host. precondition.sh proves it, and that the target (the grandchild of the
sidecar of team-b/api-0, in target.pid) is no first process, that crictl ps lists four containers in pods named api-0, that the host name of the
target is api-0 as for the pods of both namespaces, and that the cgroup of the target names its container while the decoy's does not.

The solution is a script /tmp/bench70948748/pid-owner.sh PID OUTPUT_FILE that writes a JSON object (container_id in full, pod_uid, pod_namespace,
pod_name, container_name, init_pid) for a process of a container, and null for a process of the node. The oracle asks for the first process, a
grandchild and an orphan of every container, and for the decoy; checks the node and its processes are unchanged; then the lab adds a pod
(team-c/api-0) and a container to team-a/api-0 (new PIDs) and the script is asked again, for the new containers' processes at every depth and one
process of each older container.

Where the samples fail: no script; the pod taken from the host name (two pods of the same name: the wrong container is found); only the first
process of each container compared (a grandchild has no owner); a short (13-character) container ID; the queried PID reported as the first process;
a script that does not survive a process of the node (it exits with an error instead of writing null); and a replay of the owner of the one PID
asked for at solution time. A climb of the parent chain to the first process of a container is valid too.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/diagnostics/q70948748/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Diagnostics & Observability
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q70948748/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q70948748"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q70948748",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup compiles two programs, starts the node and four containers; the oracle runs the script about 26 times

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: a CRI node with two same-named pods in two namespaces, processes below each container's first process, a decoy on the host, no pid-owner.sh
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: pid-owner.sh names the container, pod and first process of any process of a container (null for one of the node), before and after the node changes, and changes nothing
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
