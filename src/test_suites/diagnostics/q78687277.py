"""
SO-78687277: "Is there any programmatic way to detect that a process running under containerd has its stdin and stdout closed?" (2024). A process was started in a container with kubectl exec (a terminal: -it); the
kubectl on the other side is killed (or the connection is lost), and the process in the container goes on as if the terminal were still there: nothing on its stdin, stdout writes succeed, /dev/tty and the
window size are fine, no SIGHUP. The question wants a way for the process to know that its client is gone (kubectl issue #1076 has the same leak: the process of a lost exec session is never ended).

What is built: a private containerd 1.7.20 with its CRI plugin (own root, state and socket below /var/lib/bench78687277 and /run/bench78687277; the machine's own containerd is not touched), runc 1.1.12, crictl
1.34.0, one pod on the network of the node and in it one container, app, that runs /bin/idle for ever, with /probe (the host directory the solution writes its program to, read-only in the container), /lab (the
lab's passive observer) and /out (read-write). The images are made by setup (nothing is pulled). The sessions are the CRI's exec streams, as kubelet serves them to kubectl: `crictl exec -i [-t]`. The version is
pinned for a reason: the CRI of containerd 2.3 kills the exec process half a second after its client is gone (nothing leaks, nothing to detect); the 1.7 line keeps it. Measured in the container (x86_64,
cgroup v1): a session with a terminal whose client is killed gives the process NO passive signal at all (no POLLHUP, EOF, EIO, SIGHUP; stdout writes, TIOCGWINSZ and /dev/tty keep working; only when it writes
about 126 KB the pseudo terminal fills and a non-blocking write fails), while what a terminal emulator types does reach it; a session without a terminal gets POLLHUP (0x10) on stdin and EOF (read() = 0) at once,
and its stdout writes still succeed (no EPIPE). So the solution has two parts: passive detection without a terminal, and asking the terminal (cursor position report, ESC [ 6 n, answered ESC [ row ; col R) with one.
The task says that the client of a terminal session is a real emulator.

cgroup v1 / v2: not gated. containerd 1.7.20 and runc 1.1.12 support both (cgroupfs driver); the cgroup v2 / arm64 path was not run in the sandbox (cgroup v1, x86_64).

precondition.sh: the lab's files are as recorded; the node's containerd is the 1.7.20 of the lab; the container app is the Running one setup started, /probe read-only and /out read-write in it; three sessions
run the passive observer /lab/watch: a terminal session whose client is killed (alive seconds later, nothing changed), a session without terminal whose client is killed (POLLHUP and EOF, stdout writes fine, alive),
a terminal session that is connected and gets a line typed (the process reads it).
The oracle (oracle.sh): five sessions side by side with a token each - terminal killed with SIGKILL, terminal ended with SIGTERM, pipes killed (the client ends after 3 to 6 s), terminal connected, pipes connected
(22 s). The killed ones: exactly one report with the token within 8 s of the kill and not before, made by the exec process itself (the report is a line on the unix socket /out/events.sock of the checker; the kernel's
SO_PEERCRED says who connected: that pid has to be the host pid of the process /probe/detect TOKEN); the connected ones: no report and the program still running. At most 2 KB of output to a session. Then the
lab's files are unchanged, containerd is the same, and the container app was not restarted.

Where the samples fail: no program; passive signals only (fails the terminal); "/dev/tty cannot be opened" (a false positive without terminal); a timer; the terminal query used without a terminal too (false
positive); repeated reports; a 20 s reply timeout; flooding the terminal until the write blocks; a report made by a forked child; a host-side watcher that reports for the process. Valid: the reference; DSR every 2 s with
another structure.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/diagnostics/q78687277/ and converts their results into the structured `cases` dict.

Taxonomy category: Runtime Diagnostics
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q78687277/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q78687277"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q78687277",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # pod, containerd, shims, mounts
    setup_timeout = max(timeout, 600)        # the first run downloads about 60 MB; later runs take 10 to 20 s
    pre_timeout = max(timeout, 120)          # three exec sessions of about 12 s
    solution_timeout = max(timeout, 180)     # a solution compiles a program
    oracle_timeout = max(timeout, 120)       # five exec sessions of about 25 s

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: a terminal exec process gets no passive signal when its client is gone, a non-terminal one gets POLLHUP and EOF, typed input reaches the terminal process
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: both kinds of exec session report once, from inside, within 8 s of the client's end; the connected controls report nothing; the container app kept running
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
