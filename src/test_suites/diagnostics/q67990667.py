"""
SO-67990667: "Containerd: Equivalent of docker inspect in containerd". The only answer: `ctr --namespace k8s.io containers ls`, then
`ctr --namespace NAMESPACE containers info ID`. That gives the record of ONE container of ONE namespace (image, runtime, labels, the OCI spec with the
environment and the mounts) but nothing of the task, which is what `docker inspect` mixes in (state, PID): the state of a task and its PID are in
`ctr tasks ls` of the same namespace, and a container that has no task has none. Docker's inspect is a wide object; the case does not ask for an
equivalent of all of it but for named fields.

Local version: a private containerd (own socket, root and state; no CRI pods, the containers are made with `ctr`, as the asker did). Setup creates six
containers in three containerd namespaces (bench67990667-shop, -pay, -ops): web in shop and pay (different images, labels, env, mounts), api in shop,
pay and ops (the same image name, everything else different), db in ops. Every container has two random labels, two random variables and two bind
mounts of directories of its own (/data read-only, /cfg read-write). Three have a running task (a program that does nothing), three were created and
never started. The record comes from what the lab created and, for the PID of a task, from the process table of the host (the child of the
container's shim), never from what `ctr` reports about tasks. precondition.sh proves it, that plain `ctr containers ls` (namespace default) shows
nothing, and that a container's record has the image, runtime, labels and spec but no task state.

The solution is a script /tmp/bench67990667/inspect.sh OUTPUT_FILE that writes a JSON array with one object per container of every namespace: namespace,
id, image, runtime, labels, env, mounts (destination, source, type, options), status (running, stopped, ... or none) and pid (null without a task).
The oracle runs it, checks that the node is unchanged (lab.py check: the same namespaces, containers, records, tasks and PIDs), and compares the
fields; then the lab changes the node (a task is started for shop/web, the process of pay/web is killed so its task is stopped, the task of ops/api is
removed, and a container edge/web runs in a new namespace) and the script is run and compared again.

Where the samples fail: no script; only the first namespace is read (containers missing); a container's data is looked up by ID in the first
namespace that has it (the twin's image); the environment taken from /proc of the task (a container without a task has none); the mount options left
out (a read-only mount looks read-write); a PID of 0 for a container without a task; the created containers started to read a PID (the node is
changed); a stopped task treated as no task (after the change); and a replay of today's output (after the change). Image and runtime of the table of
`ctr containers ls` with the spec from `info --spec` is a valid alternative.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/diagnostics/q67990667/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Diagnostics & Observability
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q67990667/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q67990667"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q67990667",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup compiles one program, starts the node and six containers; the oracle runs the script twice

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: a containerd with containers in three namespaces (the same IDs in different ones), some with a task and some without, no inspect.sh
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: inspect.sh reports every container of every namespace with its record, spec fields and the state and PID of its task (none and null without a task), before and after the node changes, and changes nothing
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
