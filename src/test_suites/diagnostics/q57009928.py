"""
SO-57009928: "runc and ctr commands do not show docker images and containers". Docker containers run on a VM but `runc list` shows none of them, and the asker wants
runc/containerd to be aware of the Docker images. The only answer: runc keeps the state of its containers in a runtime root (a directory with one subdirectory and a
state.json per container); the default is /run/runc, but a container engine can pass --root, and Docker does: its root is <exec-root>/runtime-runc/moby (the exec root
is /run/docker by default), so `sudo runc --root /run/docker/runtime-runc/moby list` lists Docker's containers with their IDs and PIDs. How to find the root is not
simple (the comments suggest strace on containerd). As for images: runc has no notion of an image, it operates on bundles; building a bundle from an image is the
caller's job (here containerd's), so there is nothing to make runc "see". The case does not invent an image listing for runc.

Local version: a private containerd and a private Docker daemon (own socket /run/bench57009928/docker.sock, own data root) with a container exec root
(/run/bench57009928/exec-RANDOM) and a containerd socket (/run/bench57009928/ctd-RANDOM/containerd.sock) whose names have a random part chosen at setup, so the old
path of the answer and Docker's default paths are wrong. The daemon keeps its images in containerd (the containerd image store, namespace moby) and runs two
containers (bench57009928-web and -db) from one image. precondition.sh proves the problem: `runc list` with the default root shows nothing, the old Docker root of the
answer holds nothing here, `ctr` with the default namespace shows no container and no image, `runc --root <exec-root>/runtime-runc/moby list` shows the two containers,
the namespace moby of that containerd holds the image, and runc has no image command.

The solution is a script /tmp/bench57009928/find-runtime.sh OUTPUT_FILE that writes a JSON object: runc_root, containers (id, pid, status, from runc with that root),
containerd_socket, containerd_namespace, images (ref, digest, from ctr) and runc_has_images (false). The oracle runs it, checks that the node is unchanged (lab.py
check: the same containers in Docker and containerd, each running with the PID it had, the same images) and compares it with the lab's record (the IDs are what
`docker run` printed, the PIDs come from the process table: the child of the container's shim; the digest is what the node's containerd reports once after the load,
which Docker confirms); then the lab changes the node (a second image is loaded, a new container runs, one container is removed, the first keeps running) and the script
is run and compared again.

Where the samples fail: no script; the runtime root of the answer (hardcoded); the PID of the shim instead of the container's process; the default containerd namespace
(no images); bundles of runc presented as images with runc_has_images true; a replay of the first run's output (after the change); the containers restarted "so that
runc registers them" (the node is changed); and a hardcoded containerd socket. Finding the root from the state.json files and the socket from a shim's command line is a
valid alternative to reading the daemon's command line.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/diagnostics/q57009928/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Diagnostics & Observability
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q57009928/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q57009928"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q57009928",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup compiles one program, starts containerd and Docker, loads an image and runs two containers; the oracle runs the script twice

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: Docker with two running containers whose runtime root and containerd socket have random names, nothing visible with the defaults, runc without images, no find-runtime.sh
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: find-runtime.sh reports the runtime root, the containers of that root with their IDs and PIDs, the containerd socket and namespace and the images of containerd (runc has none), before and after the node changes, and interrupts nothing
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
