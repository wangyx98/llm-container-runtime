"""
SO-65981878: "How to get more information for an error generated in libcontainer/rootfs_linux.go?"

The asker edits runc's prepareRootfs (fmt.Printf, another error constructor) and sees nothing; the thread has no
answer. Measured here (runc v1.1.12 built with such a Printf): the output goes to the container's stdio, which the
node drops when the start fails (bare runc shows it); the runc the node executes is the file of the node's PATH, not
the one the asker builds; and the failing mount's source, destination, flags and errno text are already in the
error of runc 1.1.12 - but not the pid of the init that did it nor which runc ran.

Setup: a private containerd 1.6.17 with the CRI and the runc of the node's directory, a "rebuilt" runc (other
bytes) elsewhere, strace, the pod lab, `newbad` (creates a container whose start fails at a bind mount: thousands
of good mounts first, then a directory onto a file or a file onto a directory), and one such container (bad.cid).

Task: write /var/lib/bench65981878/mountfail CONTAINER-ID: it starts the container and prints one JSON object with
the failing mount (source, destination, flags, errno name and number), the host pid of the runc init that issued
it and the runc the shim executed (path, sha256).

Oracle (nothing is taken from what the solution says): three NEW containers from newbad, each given to the tool
while a /proc watcher (no ptrace) records the runc inits and the `runc create` and the file it ran from; the tool's
mount equals the bad mount, init_pid is the init the watcher saw, runc is the node's file and its hash, the
container was started by the tool, the lab's files are unchanged.
"""



from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q65981878/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q65981878"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q65981878",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containerd, mounts
    setup_timeout = max(timeout, 600)        # the first run downloads 30 MB; later runs take 20 s
    pre_timeout = max(timeout, 120)          # reads only
    solution_timeout = max(timeout, 120)     # a tool and one run of it
    oracle_timeout = max(timeout, 400)       # three traced starts of thousands of mounts and the watcher's retries

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the start of a container fails in runc init at a bind mount; the init and the runc of the node are visible in /proc
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: mountfail reports the failing mount, the init's pid and the runc that ran, for three new containers
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
