"""
SO-64401699: "microk8s containerd - failed to reserve sandbox name" (2020). On a MicroK8s node (Raspberry Pi, aarch64) the containerd service does not start: `Failed to run CRI service ... failed to recover
state: failed to reserve sandbox name "<pod>_<ns>_<uid>_3": name ... is reserved for "<id>"`; stop/start and reset do not help, and `ctr containers info <id>` says "not found" (containerd is down, so ctr cannot answer).
The thread's answer moves the whole containerd data directory away: a rebuild with no images and no pods. The real store was not kept: the truth below is an ADAPTATION measured in the lab.

What is built: a private containerd 1.6.17 with the CRI plugin and runc v1.1.12 (MicroK8s 1.18/1.19 carry containerd 1.3/1.4, no arm64 build; the CRI plugin's recovery is the same code), below
/var/lib/bench64401699 and /run/bench64401699 (the machine's own containerd is not touched), two offline images, the pod web (cert-manager, attempt 3) and the unrelated pod other, each with a running container
(host-network pods). setup.sh copies the sandbox record of web through containerd's gRPC API (a small Python HTTP/2 client in the script, no grpc library): another id (it sorts AFTER the real one, so the
error names the real sandbox), the same name; then SIGKILL of everything and removal of /run (a hard reboot). The CRI plugin recovers the sandbox records of k8s.io one by one and reserves each name; the second
reservation of the name fails, and that is fatal.
Measured: containerd runs without the CRI plugin (`disabled_plugins` in the configuration); there `ctr -n k8s.io containers` lists the sandbox records (label io.cri-containerd.kind=sandbox) with the CRI's
metadata in the extension io.cri-containerd.sandbox.metadata (base64 JSON, the Name in it); the twin is the record of the name that has no snapshot; `ctr containers rm` of it, the configuration put back and a
start give a node with every image, pod and container it knew, and a new sandbox (next attempt of web) works. The id in the error is only the record loaded first.

precondition.sh: lab files (the CRI plugin enabled in the configuration), the node is not running and its start fails with the question's fatal error naming the real sandbox, no process left, the database and
the snapshots are on disk.
The oracle (oracle.sh): lab files and containerd.toml unchanged, the running containerd is the node's 1.6.17 with that configuration; the CRI answers; crictl lists the two images (ids as before), the pods web
(exactly its real sandbox) and other and their containers under their recorded ids; the twin's record is gone from k8s.io; the snapshots of the sandboxes and the containers are there; the next attempt of web with a
container runs and prints the token; after a restart of containerd the same records and the new pod are there.

Where the samples fail: no-op; the thread's answer (the store moved away); the record named in the error removed (the real one); both sandbox records removed; the CRI left disabled; every record of k8s.io
removed; restarts only; a new root in the configuration. Valid: the reference; `containerd rm --keep-snapshot`; containerd started by hand with a copy of the configuration.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/diagnostics/q64401699/ and converts their results into the structured `cases` dict.

Taxonomy category: Runtime Diagnostics
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q64401699/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q64401699"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q64401699",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containerd, mounts
    setup_timeout = max(timeout, 600)        # the first run downloads 30 MB; later runs take 20 s
    pre_timeout = max(timeout, 240)          # one failing start of containerd
    solution_timeout = max(timeout, 180)     # a solution changes the configuration, starts containerd, removes a record and restarts
    oracle_timeout = max(timeout, 400)       # a new pod and a restart of containerd

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the node's start fails with the question's fatal error, the data is on disk
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the original images, pods and containers are back, the twin is gone, a new sandbox runs
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
