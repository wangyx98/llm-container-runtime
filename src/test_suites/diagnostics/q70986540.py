"""
SO-70986540: "Need to get "created" date in crictl images - List images call". `crictl images` prints the image, tag, image ID and size of the
images of a CRI node and has no CREATED column like `docker images`, and `--help` shows no option for one. The date Docker shows is the `created`
field of the image configuration (the OCI image config): when the image was BUILT. The accepted route (the only answer): `crictl inspecti IMAGE_ID`,
whose info.imageSpec.created is that field (`jq '.info.imageSpec.created'`). It is not the time the image reached the node (the blobs of the content
store and the image record in containerd's metadata are as old as the pull or import), and a config does not have to have the field.

Local version: a node cannot be reproduced in a sandbox, so this case is an adaptation, a CRI node: a private containerd (own socket, root and
state) with its CRI plugin and crictl, which are real. Images are imported (not pulled: no registry), which changes nothing about the question:
the build time is in the config, the import time is not.

Setup imports three small images into the namespace the CRI uses (k8s.io), built (their created fields) in different years between 2018 and 2022,
long before the import: shop/web:1 (also named shop/web:stable; created in UTC), shop/api:2 (created with a time zone offset, +08:00) and
tools/legacy:1, whose config has NO created field (its history has dates). Each created field is written the way Go writes a timestamp (nine digits of
fraction, the last not 0), so the CRI prints it as it is stored. The history of every image has a base step of 2017 and a last step that is the
created field (or a date of 2020 for the config without it), so no history entry gives the created field of a config that has none. The lab
records the image ID (the digest of the config) and the created field of every name from what it built. precondition.sh proves it, that crictl
images has no created column, and that the blobs were written minutes ago while the created fields say 2018-2022.

The solution is a script /tmp/bench70986540/image-created.sh OUTPUT_FILE that writes one line per name the CRI lists: NAME IMAGE_ID CREATED, with the
created field exactly as in the config, or unknown. The oracle runs it, checks the node is unchanged (names, image IDs, blobs); then the lab imports
a new image (shop/worker:3) and moves the name shop/web:stable to it, and the script runs again: the answers are those of the new state, so a replay
does not survive, and neither does a table keyed by a name.

Where the samples fail: no script; the mtime of the config blob (the time of the import); the date of the first history step; the date of the last
history step for the config that has no created field (it must be unknown); the timestamp converted with date (the fraction and the zone are lost);
the image without a created field left out; a replay of today's list (the new image is missing); and the unused images pruned after reading (the
node is changed). `crictl inspecti` and the config blob read with `ctr content get` are valid.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/diagnostics/q70986540/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Diagnostics & Observability
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q70986540/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q70986540"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q70986540",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup starts the node and imports three images; the oracle runs the script twice

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: a CRI node with images built in different years (one config without created), imported just now, no image-created.sh
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: image-created.sh lists every image name of the CRI with its image ID and the created field of its config, before and after the node changes, and changes nothing
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
