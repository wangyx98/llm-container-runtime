"""
SO-63515845: "Retrieve cri-o information using golang" (a Go program that runs `docker ps` / `crictl ps --no-trunc -a --quiet` through /bin/sh and prints its output works on
the asker's Mac; containerized and deployed on OpenShift 3.11 it prints nothing; the thread has no answer; the program ignores the error of `Output()`, so a missing
client or a missing socket is an empty output with exit status 0. The second part of the question, a darwin build of cadvisor's crio package, is not part of the case).

Adaptation (stated in task.txt): OpenShift 3.11 is a CRI-O node with crictl-made pods (host network), no OpenShift, no SCC; the cause is inferred from the code and measured in
the lab, not given by the thread. The node is a private CRI-O (own socket, storage root, stub-free network: its pods use the node's), with two workloads (web, db: a sleeping
container each, a per-run nonce in its environment) and a reporter pod that ran the asker's program (static, in a busybox image built offline) as a non-root user (uid and gid
1000540000) and printed nothing, exit status 0. The solution makes the pod report `<container id> <pid>` for the node's running containers through CRI-O's socket (the client and
the socket mounted; the socket is root:root 0660, so a non-root user needs the group 0), and make the program report an error (stderr, non-zero exit) instead of an empty success.

Setup: static Go program and pause (Go, CGO off, host architecture), the busybox image with every applet and /app/cmdrun, images copied with skopeo into the CRI-O's own storage,
the private CRI-O (default runtime/monitor from `crio config`), the two workloads and the reporter pod; ids, pids, nonces, hashes in a root-only state. precondition.sh: CRI-O
and workloads as recorded (pid and /proc/PID/environ nonce), the reporter exited 0 and printed an empty `output is`, a control container made by hand (root, crictl and socket
mounted) lists the workloads. Oracle (dynamic): lab unchanged; the newest reporter container is NEW, runs the lab's image, is not privileged and its log has `<id> <pid>` for web
and db (true for CRI-O); the CRI-O socket is mounted; a NEW workload made by the oracle and a COPY of the reporter container made from its OCI spec (command, env, user, mounts)
in a new pod: exit status 0 and all three reported; the same copy with a dead socket: non-zero exit, stderr, no container data.

Taxonomy category: Diagnostics & Observability
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q63515845/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q63515845"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q63515845", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 900)        # a first run may install golang-go, skopeo and busybox-static
    pre_timeout = max(timeout, 120)
    solution_timeout = max(timeout, 180)     # a solution may build a Go program
    oracle_timeout = max(timeout, 240)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the node runs the workloads, the reporter printed nothing, a container with the client and the socket does answer
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the pods and containers it creates are real objects of the node's CRI-O
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
