"""
SO-68684356: "How to check the K8s / K3s pod status programmatically with containerd runtime?" (a Go program on the node wants the real readiness of a pod, as the Docker SDK
gives `State.Health`, without the API server and straight from the runtime; `crictl` says only that the pod sandbox is Ready, which ignores the readiness probe; comments: use the
Kubernetes API, containerd knows nothing of pods or health checks; no answer).

Adaptation (stated in task.txt): the node reduced to what the question talks about, a private containerd (CRI) and a standalone kubelet (v1.34.1, pinned sha256 for x86_64 and arm64,
downloaded by setup into /var/cache/bench68684356) without any API server, running three static pods with exec readiness probes (every 3 s, 2 successes / 2 failures): gate (passes
while a file exists; the test opens and closes it), steady (passes), never (fails). The authority for a pod's readiness on such a node is the kubelet (its /pods endpoint, read-only
port or https port with anonymous access), not the CRI: crictl keeps showing every sandbox Ready and every container Running.

Setup: busybox image built offline, containerd with its own socket and root, the kubelet with its own configuration (cgroupfs, no QoS cgroups, no iptables chains, no eviction), the
three manifests, node-ctl and node-crictl, state (hashes, process start times, sandbox and container ids). precondition.sh: no API server; the kubelet judges gate NotReady, steady
Ready, never NotReady while the CRI shows three Ready sandboxes and three running containers; control: opening the gate makes the kubelet judge gate Ready after ~5 s, closing it
NotReady after ~6 s, and a pulse of 2 s in either direction changes nothing. The task: write /tmp/bench68684356/bin/pod-ready POD (prints true or false). Oracle (dynamic): lab unchanged
(files, manifests, probes, the same containerd and kubelet processes, the same sandboxes and containers); then, while the gate is opened, closed, pulsed to pass once, opened, pulsed to
fail once and closed (about 55 s), pod-ready for all three pods must equal the kubelet's own judgement at every sample (1.8 s allowed to follow a change; the kubelet is read before and
after each round of answers); an unknown pod must exit non-zero without true/false. A reader of the probe's file, a CRI reader, fixed answers, a probe removed or a fake kubelet fail.

Taxonomy category: Diagnostics & Observability
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q68684356/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q68684356"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q68684356", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 600)        # a first run may install busybox-static and download the kubelet (about 60 MB)
    pre_timeout = max(timeout, 120)
    solution_timeout = max(timeout, 180)
    oracle_timeout = max(timeout, 240)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the node as recorded, no API server, the kubelet's judgement against the CRI's view, the control flip of the gate
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: pod-ready follows the kubelet's judgement while the gate flips and pulses; the node is unchanged
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
