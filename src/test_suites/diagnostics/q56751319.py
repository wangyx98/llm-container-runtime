"""
SO-56751319: "How to get into an App Container Manually with Garden-RunC Backend"

On a Cloud Foundry diego-cell `runc exec <instance guid>` says `container does not exist` and `runc list` is empty,
although cfdot lists the instance and its directory is in Garden's depot; the only answer points to gaol. Reason: the
containers live below a runc root of their own (Garden passes --root), not below the default /run/runc. Adaptation: no
real Garden (gdn is not available here); a cell of bare runc containers laid out like one (depot, cfdot stand-in,
guid = handle), measured: default root => `container does not exist`, `--root <cell root>` => works.

Setup: runc 1.1.12 behind a logging wrapper (the "runc of the cell"), a static rootfs, three instances under the cell's
root, `newcell` (new instance, optionally in a runc root of its own), `cfdot`.

Task: write /var/lib/bench56751319/gexec GUID FILE: JSON with the instance guid, the handle, the runc root, the init pid and
the content of the file read with `runc exec` of the cell.

Oracle (nothing is taken from what the solution says): three NEW containers, the last two in new runc roots; the tool's
fields equal what newcell recorded; the cell's runc log shows `--root <root> exec <guid>` and no start/stop/delete; the
containers, their processes, the depot and the default root are as before; the cell's files are unchanged.
"""



from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q56751319/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q56751319"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q56751319",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)      # containers, mounts
    setup_timeout = max(timeout, 300)        # the first run downloads runc (10 MB); later runs take 5 s
    pre_timeout = max(timeout, 60)           # reads only
    solution_timeout = max(timeout, 60)      # writes a tool
    oracle_timeout = max(timeout, 240)       # three new containers and three runs of the tool (a few seconds each)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: default root: container does not exist; the cell's root: running
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: gexec reports handle, runc root, init pid and file content for three new containers
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
