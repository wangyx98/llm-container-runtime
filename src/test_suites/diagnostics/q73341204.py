"""
SO-73341204: "Linuxkit where is the container running" (2022; a LinuxKit VM booted from examples/redis-os.yml: `pstree` in the getty shows redis-server, `runc list` shows only the stopped
onboot container 000-dhcpcd, the container is not found. The only answer, by the asker: the container is in the containerd namespace `services.linuxkit`, and
`ctr -n services.linuxkit t exec -t --exec-id bash_1 redis sh` enters it; `redis-cli` answers PONG.)

What is measured, and what is NOT: a real LinuxKit VM (kernel, `linuxkit build` from Docker Hub images, QEMU, a serial console for the commands) cannot be built or run here, so the case is a controlled
adaptation of the situation on the host: a private containerd; the onboot container `000-dhcpcd` is run once by runc itself (the node's default root, so `runc list` shows it stopped, as in the
question); the services `getty` and `redis` are created by containerd in the namespace `services.linuxkit` (`ctr run --rootfs`, host network, own runc root `<root>/services.linuxkit`), the default
namespace of ctr is empty. The commands of the getty container are two wrappers (`ctr` with the node's socket, `runc` with the node's default root). Redis is a stand-in written in C (box: RESP PING and
CLIENT SETNAME; its redis-cli names itself with the mount namespace it runs in; the server logs every PING with that name), and the configuration has a random part, so its hash cannot be guessed.
The reference solution is the asker's answer (ctr -n services.linuxkit tasks exec).

Measured (containerd 2.3.6 and 2.2.3, runc 1.5.1): `ctr run --rootfs` takes the root file system as the positional argument (`--rootfs` is a flag), the container then has NO PATH (the lab passes `--env PATH`);
containerd's runc shim appends the namespace to the root it is given, so `--runc-root <dir>` makes the runc root `<dir>/services.linuxkit` (the default is `/run/containerd/runc/services.linuxkit`);
a `ctr task exec` process joins the container's mount namespace, so the PING it sends carries the container's mount namespace name.

precondition.sh: the lab is as its record says (hashes, the processes of redis and getty with their start ticks); redis is a running redis-server answering PING; the node's runc lists only the stopped 000-dhcpcd; the
default namespace of ctr has no container and no task; control: the namespace services.linuxkit has getty and redis; exec of sha256sum in redis gives the lab's hash and exec of redis-cli ping gives PONG, redis logged a
PING from inside its mount namespace; a runc with the root of that namespace lists redis (the lab can be solved).
The oracle (oracle.sh): the lab's files unchanged (so /etc/redis.conf of the container too); redis and getty are the same processes (pid and start tick); exactly one redis-server on the machine and it answers PONG;
the namespaces, the containers of services.linuxkit (getty, redis), the empty default namespace and the onboot container are as the lab made them; container.txt is `services.linuxkit redis`, config.sha256
is the lab's hash, ping.txt is PONG; and the log of redis has a PING since the lab started whose client name is redis's own mount namespace, which only a command run in the container produces.

Where the samples fail: nothing done; answers only from `runc list` and the default namespace ("none"); the wrong container (getty) or namespace (default); the hash of the wrong file; the reply faked without asking;
the PING sent from the host (no client name of the container); the configuration edited before the hash is taken; a second redis started; redis killed after the answers.
Valid: the reference (ctr tasks exec); the container found by looping over the namespaces; `sh -c` in the container; runc with the namespace's root (`runc --root .../services.linuxkit exec`); the hash read
through /proc/PID/root/etc/redis.conf with the PING by exec.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/diagnostics/q73341204/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Diagnostics
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q73341204/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q73341204"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q73341204",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)      # containerd, its shims, the lab's processes
    setup_timeout = max(timeout, 240)        # two static programs are compiled, the node starts
    pre_timeout = max(timeout, 120)          # a few exec calls
    solution_timeout = max(timeout, 120)     # a solution may start a few commands
    oracle_timeout = max(timeout, 120)       # reads the answers and the processes

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: redis runs but runc list and ctr show nothing of it; in the right namespace it can be listed, read and PINGed by exec
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the three answer files are right, redis was PINGed from inside its container, nothing was restarted or added
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
