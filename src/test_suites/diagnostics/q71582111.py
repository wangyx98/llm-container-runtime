"""
SO-71582111: "List local container images in AKS nodes" -- an AKS node has no Docker; the asker wants the equivalent of `docker images` and does not
know which tool. The answers: `crictl images` (the CRI client, the images of the namespace "k8s.io" that the kubelet uses), or `ctr -n <namespace>
images list` after `ctr namespaces list` (the commenter notes that ctr is not installed on AKS nodes). Plain `ctr images ls` looks at the
namespace "default" only, so it shows nothing of what the kubelet runs.

Local version: an AKS node cannot be reproduced in a sandbox, so this is an adaptation, a CRI node: a private containerd (own socket, root and
state) with its CRI plugin, ctr and crictl, which are real. The AKS constraints (az, kubectl debug node, ctr missing from the node image) are
not kept.

Setup imports small images (no program in them, nothing runs) into three namespaces: default (shop/web:1 with a second name :stable, tools/curl:7),
k8s.io (shop/web:1, a DIFFERENT image than the one of default under the same name, with a second name :canary; shop/api:2; pause:3.9) and ci
(ci/builder:3 with a second name :latest). The CRI plugin adds an entry named by the bare image ID (sha256:...) for each image of k8s.io. The lab
records what the node holds from what it imported and tagged: names with digests per namespace, and the blobs of the content store of each
namespace. precondition.sh proves it, and that plain ctr shows the images of default only.

The solution is a script /tmp/bench71582111/list-images.sh OUTPUT_FILE that writes one line per image name in every namespace, "NAMESPACE NAME
DIGEST" (the DIGEST column of ctr, the digest of the target of the name), without the ID entries. The oracle runs it and compares the set
of lines with the record (a missing namespace, a name merged with the same name of another namespace, aliases dropped, a config digest instead of
the digest, ID entries all fail), then checks that the node was not changed (no name or digest moved, no blob added or removed in any namespace:
nothing pulled, imported, tagged, removed or pruned). Then the lab changes the node (images added in default, k8s.io and a new namespace, the
name :stable of default moved to another image) and the script is run again, so a copy of today's list fails.

Where the samples fail: no script; only the default namespace that ctr looks at; `crictl images` (k8s.io only, and the image ID instead of the
digest: the imported images have no repo digest for crictl); the ID entries counted as images; one line per name over all namespaces; one line per
image (aliases lost); `crictl rmi --prune` after listing (the images are gone); a copy of today's list. `ctr` over every namespace, in shell or in
Python, is valid.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/diagnostics/q71582111/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Diagnostics & Observability
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q71582111/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q71582111"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q71582111",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup starts the node and imports the images; the oracle runs the script twice and imports more images

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: a node with images in three namespaces (the same name as two images, several names for some), plain ctr shows default only, no list-images.sh
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: list-images.sh lists every image name of every namespace with its digest, before and after the node changes, and changes nothing on the node
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
