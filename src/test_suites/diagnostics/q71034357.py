"""
SO-71034357: "How show containerd logs for stopped containers". On a node whose runtime is containerd, `/var/log/pods` seems to hold only the logs of
the containers that run, and the asker wants the Docker behavior (docker logs on a stopped container). The logs of a stopped container are not
removed by the runtime: the CRI log file of a container is written by containerd at the log_path the kubelet gave (<log directory>/<container
name>/<attempt>.log) and the kubelet removes it only when it garbage-collects the dead container. A container that restarts is a NEW container with
the same name and the next attempt number and its own log file, so the logs of the old attempt are in the file of the old attempt. `crictl ps -a`
lists the stopped containers, `crictl inspect` gives their exit code, reason and logPath, and `crictl logs ID` prints a stopped container's log
too, but only the current file: what the node's log rotation (the kubelet renames the file to NAME.TIMESTAMP, has the runtime reopen the path,
and gzips the older rotated files) moved away is not in it.

Local version: a GKE or kubeadm node cannot be reproduced in a sandbox, so this case is an adaptation, a CRI node: a private containerd (own
socket, root and state) with its CRI plugin and crictl, which are real. The kubelet is not there: the lab does what it does to a log (rename,
ReopenContainerLog through a few lines of gRPC over the unix socket, gzip) and keeps the logs; garbage collection of dead containers is not
simulated, and what a node does once its logs are collected is outside the task (setup keeps them).

Setup runs one pod, default/batch-0, with three real containers that log what a script tells them to (the lab writes it): web (running), job
attempt 0 and job attempt 1 (its restart, running). Attempt 0 logs random messages on stdout and stderr (leading blanks and a tab, UTF-8, an empty
line, backslashes and quotes, 3000 and 20000 characters, the last one written by the node as partial records), has its log rotated twice, and exits
with an exit code the lab chose (so its reason is Error): its log is spread over 0.log, 0.log.TIME2 and 0.log.TIME1.gz. The lab records the bytes each
container must have logged, its state, exit code and reason, and the hashes of its log files. precondition.sh proves it, and that `crictl logs`
gives only the end of the stopped container's log.

The solution is a script /tmp/bench71034357/stopped-logs.sh NAME ATTEMPT OUTDIR that writes stdout.txt, stderr.txt (the application's bytes of each
stream, from the first message, in order) and exit.txt (the exit code, then the reason). The oracle runs it for job attempt 0, checks the node and
its logs are unchanged; then the lab makes job attempt 1 log four more messages and exit with 0, and the script runs again for attempt 1 and for
attempt 0: the answers are those of the container asked for (no messages of the other attempt, the exit information of its own), so neither a replay
nor the newest container called job survives.

Where the samples fail: no script; `crictl logs` (only the current file: the first lines are missing); the raw records with their timestamp,
stream and tag prefixes; the newest container called job (attempt 1, not 0); every log file of the container name (the attempts mixed); the exit
information of the reading command instead of the container's; a replay of today's output (it is attempt 0's, for attempt 1); and the stopped
container removed after reading (the node is changed). `crictl inspect` with the rotated and compressed files read in order, in Python or in
shell with awk, is valid.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/diagnostics/q71034357/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Diagnostics & Observability
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q71034357/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q71034357"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q71034357",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup compiles two programs, starts the node, runs three containers and rotates a log twice; the oracle runs the script three times

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: a CRI node with a stopped container whose log is rotated over three files, its restart and a neighbor running, no stopped-logs.sh
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: stopped-logs.sh writes the whole log, the exit code and the reason of a stopped container, nothing of the other attempt, for two containers, and changes nothing
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
