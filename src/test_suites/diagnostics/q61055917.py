"""
SO-61055917: "How to list microk8s' containers with microk8s.ctr". On a MicroK8s node `microk8s.kubectl get pod` shows the pods, but `microk8s.ctr c ls` and
`microk8s.ctr image list` show nothing. The only answer: `ctr` works in one containerd namespace ("default" unless -n is given) and MicroK8s (like the
kubelet with any containerd) keeps everything in the namespace k8s.io, so `microk8s.ctr -n k8s.io c ls` lists the containers (the pods' sandbox and workload
containers, with their images and the runtime). `containers ls` has the columns CONTAINER IMAGE RUNTIME only: the digest of an image is in `images ls`
(DIGEST) and the PID of a container's process in `tasks ls` (a container without a task has none).

Local version: a private containerd (own socket, root and state) stands for the containerd of MicroK8s: its images and containers are in the namespace
k8s.io and the namespace default is empty. Setup imports five images (two named pause:3.1 from different registries, with different digests; the proxy and
jsonnetd workloads; busybox that no container uses) and makes six containers with 64-hex-digit IDs: five run (a task each), one was created and never started.
The CRI plugin of k8s.io also lists every image under its bare ID (sha256:...); the oracle ignores those entries. A second socket of "another containerd of
the host" (/run/bench61055917/docker/containerd.sock) is a listener that only logs the connections it gets. precondition.sh proves the problem: plain ctr
shows no container and no image, with -n k8s.io the containers have no digest and no PID column, and nothing has connected to the other socket.

The solution is a script /tmp/bench61055917/list-node.sh OUTPUT_FILE that writes a JSON object: containers (id, image, digest, pid or null) for every
container of the node's containerd and images (ref, digest) for every image. The oracle runs it, checks that the node is unchanged (lab.py check: the same
images, digests, blobs, containers, records and tasks with the same PIDs) and that nothing connected to the other socket, and compares the lists with the lab's
record (the digests are the ones the images were built with, the PIDs come from the process table: the child of the container's shim); then the lab changes the
node (the task of the proxy is killed and removed, the container that was never started is started, a new image and a new container run) and the script is run
and compared again.

Where the samples fail: no script; the namespace default (empty lists); the PID of the shim instead of the container's process; the digest of an image found by
its name without the registry (the wrong pause); the other containerd socket asked as well (the tripwire); a replay of the first run's output (after the
change); an image that no container uses removed to shorten the list (the node is changed); and the images taken from the containers (the unused one is
missing). Walking every namespace and keeping the CRI aliases is a valid alternative.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/diagnostics/q61055917/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Diagnostics & Observability
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q61055917/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q61055917"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q61055917",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup compiles one program, starts the node, imports five images and starts six containers; the oracle runs the script twice

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: a containerd whose images and containers are in k8s.io (default empty), five tasks and one container without, another socket nobody has connected to, no list-node.sh
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: list-node.sh reports every container with its image, the digest and the PID of its task (null without one) and every image with its digest, before and after the node changes, changes nothing and never connects to the other socket
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
