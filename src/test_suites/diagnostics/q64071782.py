"""
SO-64071782: "runc container cpu usage". The asker runs bare runc containers and wants the CPU time one container has used. /proc/<pid>/ of the PID that `runc list` shows has no
file for it; the answer (self-answered): the cgroup directories named after the container hold it, e.g. /sys/fs/cgroup/cpu,cpuacct/user.slice/<container_folder>/cpuacct.usage.

Local version: two bare runc containers (bundles under /var/lib/bench64071782, a rootfs with one static program), bench64071782-job and bench64071782-app. In each the first process
(`app init`) only sleeps and its child (`app burn`) uses CPU time when the lab tells it to (the child reports the CPU time it used from its own CPU clock). The two cgroups are
/bench64071782-RAND/bench64071782-job and .../bench64071782-app: a random parent, so no path can be written down. The host has cgroup v1 (cpuacct) or v2 (cpu.stat): the case works with
either, and the script must find out. precondition.sh proves the problem: when the worker uses 200 ms the first process's CPU time does not move and the counter of the cgroup grows by
200 ms, the other container's counter does not move.

The solution is a script /tmp/bench64071782/cpu-usage.sh CONTAINER_ID OUTPUT_FILE that writes {"cgroup", "usage_ns"}: the cgroup of the container as /proc/PID/cgroup shows it and the total CPU
time of that cgroup in nanoseconds. The oracle (verify.py) runs it for the app container, then makes ONLY the job container work and reads app again (must not move), makes app work 300 ms and
150 ms (the counter must grow by what the worker says it used, not by 0 and not by a thousandth), checks the total since the start; then starts a third container with no cgroupsPath (another ID,
runc's own path), reads it while it works, and reads app again while only the new one works. After each phase lab.py check proves nothing was stopped, paused, restarted or moved.

Where the samples fail: no script; the path guessed from the answer (user.slice: the script fails); the process found by its name instead of the container ID (the other container's cgroup); the
counter of the parent cgroup (it holds both containers: it grows while only the other works); the CPU time of the first process (it sleeps: no growth); microseconds written as nanoseconds; the cgroup
of the first container kept for a later container. Reading `runc events --stats` (cpu.usage.total, in nanoseconds on both cgroup versions) with the cgroup from /proc/PID/cgroup is a valid alternative.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/diagnostics/q64071782/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Diagnostics & Observability
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q64071782/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q64071782"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q64071782",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup compiles one program and starts two containers; the oracle starts a third and makes the containers work several times

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: two runc containers (sleeping first process, working child) in cgroups with random paths; the CPU time is in the cgroup and not in the first process; no cpu-usage.sh
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: cpu-usage.sh names the right cgroup and reports its CPU time in nanoseconds for the first container and for one started later: still while idle, grown by what the worker used while it works, nothing stopped or changed
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
