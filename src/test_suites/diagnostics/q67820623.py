"""
SO-67820623: "Containerd pull multiple images while creating a Pod in Kubernetes"

A node whose runtime is containerd lists three "images" for the one image the kubelet pulled (name:tag,
name@sha256:<manifest digest>, sha256:<config digest>); the asker expects one, sees two /images/create events and
fears that each Pod pulls and stores the image again. The thread's answer only says that the tag is resolved to the
digest; it measures nothing. Here the node is measured.

Setup: a private containerd 1.6.17 with the CRI plugin and runc 1.1.12, a REAL registry (distribution 2.8.3,
plain HTTP on 127.0.0.1:5067, its access log is the record of what was transferred); bench/a (tags 1 and 2 with
one manifest) and bench/b share a 2 MiB base layer and the program layer; the node has pulled the sandbox image and
bench/a:1 through the CRI and runs two pods whose programs write 1 and 2 MiB into their writable layers.

Task: write the read-only tool /var/lib/bench67820623/imgreport that prints one JSON object: every record of the
namespace k8s.io -> manifest digest, the content store's blob count and bytes, the number of committed/active
snapshots, every container's image and writable-layer bytes (regular files of the upper directory) and what the
registry's log shows (200 lines: blob GETs and bytes, manifest GETs, manifest HEADs).

Oracle (nothing is taken from what the solution says): the tool equals an independent measurement (ctr, find, the
upper directories, the log) taken around its run, it is read-only (fingerprint of records, content store, snapshots,
containers, leases, pods and the registry's log), and it is right again after the node changes (the CRI pulls
bench/a:2 = a new name, no blob; bench/b:1 = 3 blobs, 2 blob GETs; a third pod writes 3 MiB = 2 containers, no
transfer); a tool with the first answer written into it fails.

"""



from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q67820623/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q67820623"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q67820623",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containerd, registry, mounts
    setup_timeout = max(timeout, 600)        # the first run downloads 60 MB; later runs take 30 s
    pre_timeout = max(timeout, 120)          # reads only
    solution_timeout = max(timeout, 120)     # a tool and one run of it
    oracle_timeout = max(timeout, 400)       # two pulls, a pod, and the tool run twice with fingerprints

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: two images under three records each, two pods, the registry's log holds the two pulls
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: imgreport equals the measured truth now and after the node changes, and is read-only
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
