"""
SO-74310243: "Why am I getting 'failed to flush chunk' when sending container logs to syslogs with fluent-bit?" (2022). Fluent Bit 2.0.3 tails /var/log/containers/*.log (containerd's CRI format,
Parser cri) and sends them with the syslog output (rfc5424, UDP, 127.0.0.1:514, a row of syslog_*_key options); the log is full of `failed to flush chunk ..., retry in 9 seconds`. The question has no
answer on the page; the thread's only comment asks whether the output was tried on stdout.

What was measured (Fluent Bit 2.0.3 .deb, aarch64, Ubuntu 22.04 VM; the probe is not part of the case): with a receiver on the UDP port the question's configuration delivers every line as a valid RFC 5424
message (the text is the record's `message` key, which is what the stock cri parser produces; HOSTNAME, APP-NAME, PROCID, MSGID and STRUCTURED-DATA are `-` because the records have no such keys; the text
starts with a BOM; the TIMESTAMP is the CRI line's, to the microsecond). Without a receiver every chunk fails to flush: one retry, then `chunk ... cannot be retried` and the chunk is dropped
(Retry_Limit 1). Setting syslog_message_key to `log` is wrong: the message is then empty. So the trigger of the symptom that was reproduced is a missing receiver on 127.0.0.1:514/udp (the stock Ubuntu
rsyslog does not listen on UDP); whether the asker's host was in that state the question does not say.

What is built: a private containerd 1.6.17 with the CRI plugin and a pod whose container logs one numbered line every half second (a per-run token in each); the log directory is the kubelet's layout
(pods/NAMESPACE_POD_UID/CONTAINER/0.log written by containerd, containers/POD_NAMESPACE_CONTAINER-CID.log a symlink made by the lab); the pinned Fluent Bit 2.0.3 with the question's configuration (no
kubernetes filter: the lab has no API server); the lab's syslog daemon (a Python stand-in for the machine's rsyslog, NOT rsyslog) whose configuration has no `listen udp` line, so nothing receives on port 514.
The daemon logs every datagram it receives as a JSON line. The task changes the receiving end (syslogd.conf, restart with syslogctl), or both ends consistently.

precondition.sh: lab files and processes; the CRI log lines; no socket on udp 514 and a connected socket is refused; Fluent Bit's log has `failed to flush chunk` for syslog.0 and its counters show a
failing output that sent nothing; with a throw-away receiver for 10 s Fluent Bit delivers valid RFC 5424 messages of the container's lines (so the configuration is fine); the receiver is gone again.
The oracle (oracle.sh): lab files and processes unchanged and not restarted during the check; for 18 s the container logs on; the lines of the window [4 s, end-2 s] arrived exactly once each in the lab's
daemon, in order, as valid RFC 5424 with the CRI line's timestamp; no invalid or foreign datagram; Fluent Bit's log has no flush failure after the start; its monitoring counters (-H, port 20310)
show the syslog output sent at least as many records. Lines logged before the receiver was up are not required (they are dropped).

Where the samples fail: no-op; only Log_Level error (the warning is gone, nothing is delivered); only Retry_Limit False; message key changed to log; the listener added but the daemon not restarted; a listener
on another port only; a listener of the solution's own (the lab's daemon never sees a line); a shipper of the solution's own that sends to another port of the daemon (Fluent Bit still fails); the daemon
edited. Valid: the reference (a listener on 127.0.0.1:514, restart); the wildcard address; another port on both ends (daemon and Fluent Bit restarted).

SANDBOX NOTE: Fluent Bit and rsyslog cannot be fetched in the Claude sandbox; there a Python stand-in for Fluent Bit (not committed, FLUENT_BIT_BIN) with the measured behaviour exercised the lab and every
branch of the oracle. The real Fluent Bit run is on the VM (FLB package pinned for aarch64 only; FLUENT_BIT_BIN for another architecture).

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/diagnostics/q74310243/ and converts their results into the structured `cases` dict.

Taxonomy category: Runtime Diagnostics
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q74310243/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q74310243"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q74310243",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containerd, mounts
    setup_timeout = max(timeout, 600)        # the first run downloads 100 MB; later runs take 15 s
    pre_timeout = max(timeout, 240)          # up to 30 s for the failures, 10 s of a receiver
    solution_timeout = max(timeout, 180)     # a solution edits a configuration and restarts a daemon
    oracle_timeout = max(timeout, 120)       # 18 s of logging, 5 s of grace

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the container logs, Fluent Bit cannot flush because nothing listens on udp 514, and it delivers when something does
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the new lines arrive once, in order, as valid RFC 5424, Fluent Bit flushes without failures
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
