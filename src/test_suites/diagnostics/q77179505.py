"""
SO-77179505: "jdk vulnerability displaying in containerd overlay snapshot" (2023). A security scan reports java-1.8.0-openjdk in directories below /var/lib/containerd/io.containerd.snapshotter.v1.overlayfs/snapshots;
the platform team asks from which image each snapshot was made and what the complete Dockerfile was. `ctr container list` and `ctr snapshot ls` show nothing (they look at the namespace "default"; the CRI keeps
everything in k8s.io). The question has no answer on the page. What can be answered: the numbered directory of the snapshotter -> snapshot key -> the images that have that layer; the Dockerfile cannot be recovered
from an image (only its history), so the case asks for a read-only attribution report and an honest "unrecoverable".

What is built: a private containerd 1.7.20 without the CRI plugin and without garbage collection (a snapshot that ctr makes has no lease: a collection would take a temporary view away under a reader), below
/var/lib/bench77179505 and /run/bench77179505 (the machine's own containerd is not touched), with the overlayfs snapshotter and three offline OCI images with layers (a per-run token is in every layer): orders-api =
[jdk, app] and billing-worker = [jdk, app] share ONE jdk layer, static-site has none. k8s.io holds the three images, a container record orders-api-7d9f (its writable layer has a copy-up of the scanner's file) and a
stale active snapshot (prepared on the jdk layer, with the file, used by nothing); the namespace moby (Docker's) holds orders-api alone, so the jdk layer is a directory of its own there; default is empty (the question's
symptom). The scanner's file is in exactly four directories (setup checks it against the record). Measured (x86_64, cgroup v1; no runc, no shim, no mounts are needed): the directory of a committed snapshot is the first
path of the mount of a temporary view of it (a bind mount for a one-layer chain), the directory of an active one the upperdir of its mount; chain IDs are sha256("parent diff_id") from the image config; the numbered
directories of removed snapshots go away later, in a collection, so the state check does not list them.

precondition.sh: the lab's files and containerd as recorded; nothing in default; the namespaces k8s.io and moby; the scanner's file in four directories; the shared layer (one snapshot of two images in k8s.io, one of
one image in moby); the two writable layers (a container's, a stale one); the views and mounts give the recorded directories (and are removed); the configs keep a history of created_by lines and no FROM.
The oracle (oracle.sh): report.json against truth.json: the four directories, each with namespace, kind, key, ALL its images, containers and unreferenced; "dockerfile" is {"status": "unrecoverable"} with the real
history of every image named; the node (every snapshot, image and container of every namespace, the scanner's files, the lab's files, containerd) is exactly as before: nothing removed, nothing left behind.

Where the samples fail: no report; only the namespace default; one image per layer instead of all; an active layer reported as a committed one; the active layers left out; an invented Dockerfile; the stale snapshot
removed "to clean up"; a temporary view left behind; directories guessed from the order of the snapshots. Valid: the reference; the directories found with one view per image chain instead of one per snapshot.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/diagnostics/q77179505/ and converts their results into the structured `cases` dict.

Taxonomy category: Runtime Diagnostics
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q77179505/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q77179505"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q77179505",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containerd, mounts
    setup_timeout = max(timeout, 600)        # the first run downloads 30 MB; later runs take 5 s
    pre_timeout = max(timeout, 60)           # a few ctr calls
    solution_timeout = max(timeout, 180)     # a solution walks the namespaces with views and mounts
    oracle_timeout = max(timeout, 60)        # a comparison

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: nothing in default, the scanner's file in four directories, a layer shared by two images, the way through views and mounts, no Dockerfile in the images
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the report attributes the four directories to all their images, containers and namespaces, marks the Dockerfile unrecoverable, and the node is untouched
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
