"""
SO-68471241: "How to enable https on cri-o socket metrics" (2021; CRI-O 1.20.3). The metrics endpoint is configured as the documentation says (enable_metrics, metrics_port, metrics_cert, metrics_key in a drop-in
of crio.conf.d; the certificate and key exist and are readable) but the port still answers in plain HTTP: http://host:port/metrics works, https://host:port/metrics does not. The only answer, and the CRI-O
issue it refers to (#5112): the secure metrics endpoint is a feature of CRI-O 1.22, it is not backported to 1.20, which ignores metrics_cert and metrics_key.

What is built: a private CRI-O (its CRI socket, root and state below /var/lib/bench68471241 and /run/bench68471241; the machine's own CRI-O is not touched) that runs a program set chosen by the link
node/current. Three official static bundles are on the disk: v1.20.7 (the node runs it; 1.20.3 itself is not published as a static bundle, 1.20.7 is the nearest release and behaves the same: it ignores the
two keys), v1.21.0 (still no TLS: an upgrade that does not fix it) and v1.22.4 (serves HTTPS). The CA, the server certificate (SAN localhost and 127.0.0.1) and the key are made by setup; the images (the
sandbox image and the lab's workload) are in the node's storage, so nothing is pulled. The commands: crioctl start|stop|restart|status, crictl, scrape (GET https://localhost:5555/metrics with the lab's CA),
run-workload NAME. Measured (CRI-O bundles, cgroup v1, x86_64): 1.20.7 and 1.21.0 log "Serving metrics on :5555", serve plain HTTP and answer a TLS handshake with "wrong version number"; 1.22.4 logs "Serving
metrics on :5555 via HTTPs" and the validity of the certificate, serves the metrics to a client that trusts the CA and answers a plain request with 400 "Client sent an HTTP request to an HTTPS server"; when
a certificate path does not exist 1.22.4 stops at its start ("Creating key pair reloader: load certificate ... no such file"), and when the drop-in sets no certificate and key it serves plain HTTP ("via HTTP");
1.20's `crio config` does not show metrics_cert and metrics_key at all.

cgroup v1 / v2: not gated. The sandbox is cgroup v1; the CRI-O bundles are run with cgroupfs and a pinned runc v1.1.12 (the arm64 bundles of 1.20 to 1.22 have no runc, only an old crun that fails on a hybrid cgroup layout), which support cgroup v2, but a pod on 1.22.4 under cgroup v2 / arm64 was not run in the sandbox.

precondition.sh: the lab's files are as recorded; the node runs v1.20.7; the certificate chains to the CA, has the SANs and its key; the node's own program, asked for its configuration, shows the drop-in's port
(and no metrics_cert); the node answers metrics in plain HTTP and a TLS client fails; and the upgrade boundary is measured with CRI-Os started beside the node (same drop-in, other ports, no pod): v1.21.0 still
serves plain HTTP, v1.22.4 serves HTTPS (trusted CA reads, plain HTTP, another CA and another host name are refused).
The oracle (oracle.sh): the lab's files unchanged; exactly one CRI-O of the node, a program of a release of the lab, 1.22 or later; the listener of the metrics port and of the CRI socket is that process (no
proxy); a client with the lab's CA reads 200 and CRI-O metrics over HTTPS and is shown the lab's certificate; no CA, another host name and plain HTTP get no metrics; the images are still on the node; a workload run
now is Running and prints its marker; the CRI-call counters read from the endpoint before and after grew by exactly what the check did.

Where the samples fail: nothing done; the upgrade to v1.21.0; the release switched but CRI-O not restarted; the upgrade with a typo in the certificate path (CRI-O does not start); the upgrade with the certificate and key dropped from the drop-in (plain HTTP); a TLS proxy on 5555 in
front of 1.20.7; the upgrade with the metrics switched off; the upgrade with the storage reset (the images gone); the scrape tool made plain HTTP. Valid: the reference; the new release started by hand.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/diagnostics/q68471241/ and converts their results into the structured `cases` dict.

Taxonomy category: Runtime Diagnostics
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q68471241/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q68471241"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q68471241",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # pods, CRI-O, mounts
    setup_timeout = max(timeout, 900)        # the first run downloads about 300 MB of CRI-O bundles; later runs take half a minute
    pre_timeout = max(timeout, 240)          # starts two more CRI-Os beside the node
    solution_timeout = max(timeout, 240)     # a solution stops and starts CRI-O
    oracle_timeout = max(timeout, 180)       # scrapes several ways and runs a workload

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the drop-in is loaded, the node answers metrics in plain HTTP and TLS fails, 1.21.0 has no TLS and 1.22.4 has
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the metrics of the node's CRI-O are served over HTTPS with the lab's certificate by CRI-O itself, and the node still works
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
