"""
SO-73971174: "How to make containerd forward logs to journald" (k8s with containerd as the CRI; the question does not say whose logs; its only answer, `journalctl -u containerd`,
is about the daemon's own messages, which systemd already puts in the journal; the case is the other reading, the one a node operator needs: the output of the containers).

Adaptation (stated in task.txt): the question has no failure to reproduce, so the case builds the missing piece: a private containerd node (own socket, own root, CRI on, the
pods use the node's network) whose containers log to CRI files below /var/log/bench73971174/pods/<namespace>_<pod>_<uid>/<container>/<n>.log, and nothing of them in the
machine's systemd journal. containerd has no journald log driver; the solution is a forwarder (CRI files -> collector -> journal) that the solver writes and starts.

Setup: static busybox as an OCI image built offline (it is the pods' sandbox image too), the private containerd, and two workloads (web, db) that print a numbered line to stdout
every second or two and to stderr every third time; ids, nonces, log files (inode, first line), hashes, the time in a root-only state. precondition.sh: containerd and the
workloads as recorded, the log files grow, the journal has no entry of them and no process reads the logs, the journal takes an entry with MESSAGE / PRIORITY 3 /
CONTAINER_ID_FULL (control). Oracle (dynamic): lab unchanged; new pods made by the oracle (alpha and beta in one pod, gamma in a second pod a few seconds later, a 20000-character
line, special characters, a burst at the first instant); the CRI log files are the truth: every line of every container once in the journal (not twice), PRIORITY 6 / 3 by
stream, CONTAINER_ID_FULL = the container's id (entries with the line but without the right id are named), the whole text of a line that the CRI cut into pieces, within 15 s of
the line's time in the CRI file; the lab's files are not truncated or replaced; `crictl logs` still works.

Taxonomy category: Diagnostics & Observability
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/diagnostics/q73971174/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "diagnostics" / "q73971174"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q73971174", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 600)        # a first run may install busybox-static
    pre_timeout = max(timeout, 120)
    solution_timeout = max(timeout, 180)
    oracle_timeout = max(timeout, 240)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the node runs the workloads, the journal has none of their lines, the journal takes an entry with the fields the task asks for
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the pods and containers it creates are real objects of the node's containerd, the CRI files are the truth for the journal
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
