"""
SO-72183367: "Create kubectl secrets when pulling from private registry using crio" (no error text and no configuration in the thread; the question: with CRI-O instead of Docker there is no `docker login`, how do the
nodes pull from a private registry; the answer: a Kubernetes Secret of type kubernetes.io/dockerconfigjson, referenced by the pod's (or the ServiceAccount's) imagePullSecrets, which the kubelet passes to
CRI-O in the CRI PullImage call). CRI-O does not read Secrets itself.

Adaptation (stated in task.txt): no Docker, no real cluster or registry: a single-node k3s (kubelet + API server) on a private CRI-O instance (own socket, storage, stub CNI), and a small stand-in registry on
127.0.0.1:15183 (plain HTTP, Basic auth for /v2/ and the secure/ repositories, a request log, CRI-O's insecure_registries lists the address). The error is the one the probe showed: "unauthorized".

Setup: static images built offline (two tags of the private repository with different tokens, one anonymous sandbox image), pushed with the credentials of this run (random, in registry.cred); k3s (pinned release,
sha256 checked; x86_64 and aarch64) with the private CRI-O as its runtime; pod app (default) created without credentials and left in ErrImagePull; pids + start ticks + hashes in a root-only state dir.
precondition.sh: daemons and files as recorded, the registry refuses anonymous and wrong credentials, no credential file on the node, CRI-O cannot pull the private image, the pod waits on "unauthorized".
Oracle (dynamic): daemons, files and registry content unchanged and auth still enforced; no node-wide credentials, and a pull without credentials fails; a Running+Ready pod of the image (image id = registry digest,
log shows the token) with imagePullSecrets naming a registry Secret with the right server, user and password; then a new pod with the same Secrets pulls the second tag (never on the node) and the registry log shows
CRI-O's authenticated 200s for its manifest and both blobs.

Taxonomy category: Configuration Management
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/configuration/q72183367/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "configuration" / "q72183367"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q72183367", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 900)        # a first run may install gcc and download k3s
    pre_timeout = max(timeout, 180)
    solution_timeout = max(timeout, 180)
    oracle_timeout = max(timeout, 300)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the registry needs credentials, the node has none, the pod app waits on "unauthorized"
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the pod that runs and the oracle's own pod are real pods of the node's kubelet and CRI-O
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
