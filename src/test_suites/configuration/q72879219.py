"""
SO-72879219: "container process label is set to spc_t after setting selinux-enable=true in containerd-config.toml" (2022; containerd 1.6.6 and Kubernetes 1.23.8 on an SELinux
distribution; the engineer wrote `enable_selinux = true` into the CRI section of config.toml and restarted containerd, but the container processes run as spc_t, the label that the type transition of
container_runtime_t gives to a process whose file is container_ro_file_t. The only answer, by the asker: add `version = 2` to config.toml.)

What is measured, and what is NOT: a label of a process is set by the SELinux policy of the distribution (container-selinux), by privileged or not, and by the CRI plugin of containerd, which only
asks for container_t if its SELinux support is on; so seeing spc_t does not prove a configuration fault. The real SELinux behaviour (a process labelled container_t, refused file operations) needs an
SELinux host (policy, relabelled file system, reboot) and cannot be built here: this case is the configuration-level variant of the question, and it is the part that the answer of the question
solves: does the RUNNING containerd use the setting at all. Measured with containerd 1.6.6 (official amd64 build, CRI on; `crictl info` shows `config.enableSelinux`): a config.toml without `version` is
read as version 1, whose plugin tables are named `cri` etc., so a table named by the URI, `[plugins."io.containerd.grpc.v1.cri"]`, is ignored (enableSelinux false, and so are sandbox_image, runc's
SystemdCgroup and the registry config_path of the same table); with `version = 2` on top it works; a top-level `enable_selinux = true` is ignored; the legacy `[plugins.cri]` table works in a version 1 file;
`version = 2` alone, without the key, gives false.

Adaptation (stated in task.txt): a private containerd 1.6.6 (official release, sha256 pinned for amd64 and arm64; its own socket, root and state; CRI on; no kubelet; no SELinux on the host and none touched),
started with `--config /var/lib/bench72879219/etc/config.toml`; the engineer's file has the URI-keyed CRI table with enable_selinux, a sandbox image, runc SystemdCgroup and the registry config_path (the three
other settings are there so that a replaced default file, or the legacy table with only the SELinux key, cannot pass).

precondition.sh: the lab runs containerd 1.6.6 from the file, the file has `enable_selinux = true` and no version; `crictl info` shows enableSelinux false and the other three settings not in force; control:
a throw-away second containerd 1.6.6 with the same file plus `version = 2` on top shows all four in force.
The oracle (oracle.sh): the lab's containerd (binary sha256 unchanged, version 1.6.6, process = the lab's binary, started with --config of the lab's file and the lab's socket), the LIVE `crictl info` shows
enableSelinux true, the sandbox image, SystemdCgroup true and the registry config_path (so the daemon was restarted on the file left behind), and the file still holds the four settings.

Where the samples fail: nothing done; `version = 2` without a restart; an explicit `version = 1`; a top-level `enable_selinux = true` and a restart; the key under the `.containerd` table; only the SELinux key in a legacy `[plugins.cri]`
table (the other three settings stay unused); a file made by `containerd config default` (loses the settings); `setenforce 0` (not related).
Valid: `version = 2` on top and a restart (reference); `version = 3` (1.6.6 only tells version 1 from the rest, measured); the whole file written with `version = 2`; the whole file in the legacy `[plugins.cri]` form of version 1; each followed by a restart.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/configuration/q72879219/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Configuration
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/configuration/q72879219/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "configuration" / "q72879219"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q72879219",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)      # containerd and its shims
    setup_timeout = max(timeout, 600)        # first run downloads containerd (~40 MB)
    pre_timeout = max(timeout, 180)          # a control containerd is started
    solution_timeout = max(timeout, 120)     # a solution may restart containerd
    oracle_timeout = max(timeout, 120)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the running containerd ignores the settings of config.toml, the same file with version = 2 works
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the live containerd uses enable_selinux (and the other settings) of the file
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
