"""
SO-45937714: "How to backup and restore docker containers (without the original docker run command)". The asker has a running container and no record of the `docker run`
that made it; an image (`docker save`/`docker commit`) is the only thing the usual answers keep. The case fixes what a backup of a CONTAINER has to carry (the scope is in
task.txt, the oracle judges all of it): the configuration (command, arguments, environment, working directory, label, restart policy, published port), the named volume and
its data, the file bind-mounted read-only from the host (gone with the machine), a file in the container's writable layer, the user-defined network with its alias, and the
running state. An image alone brings back the environment and the arguments (docker commit even the writable layer) but not the configuration file, the data, the network,
the alias or the restart policy: precondition.sh shows that with a control on a scratch daemon.

Two private docker daemons make the "before" and the "clean target" (own socket, data root, exec root, address pool, no iptables, no default bridge): the engineer's (src) runs
web; the oracle deletes web, volume, network, image, the whole daemon and the bind source, copies the backup directory to another place and runs `bash restore.sh` there as
root with a clean environment (DOCKER_HOST the only pointer) on the new daemon (dst), so the restore cannot lean on the old container, on the old daemon's image store or on a
process left on the port. Then: inspect fields, the process, the real service (nonce, mode, extra, title, workdir, conf, data hash, marker), file hashes, and the same after
`docker restart web`.

Not architecture-specific: docker API, one static C service compiled on the host and a docker archive made for `uname -m`. No note file is needed.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/configuration/q45937714/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Configuration Management
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/configuration/q45937714/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "configuration" / "q45937714"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q45937714",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 300)      # three private docker daemons are stopped, their processes ended
    setup_timeout = max(timeout, 900)        # compiles one tiny program, builds and loads an image, starts a docker daemon, starts the container
    pre_timeout = max(timeout, 600)          # control: a scratch docker daemon, an image of web run on it
    solution_timeout = max(timeout, 300)     # a solution makes the backup (docker save and copies)
    oracle_timeout = max(timeout, 600)       # the accident, a new docker daemon, restore.sh, two judgements and a restart

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: web as recorded; an image of it is not web
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the accident, a clean daemon, restore.sh, the real service and the configuration, as restored and after docker restart
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
