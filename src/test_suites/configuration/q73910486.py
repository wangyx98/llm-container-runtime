"""
SO-73910486: "Why does crictl pull from private registry not need account/password?" (kubeadm v1.25.2 with containerd; the asker wrote /etc/containerd/certs.d/my_registry:5000/hosts.toml (plain HTTP server, pull and
resolve) and `crictl pull my_registry:5000/hello-world:latest` succeeds although `docker pull` from that registry asks for an account; he stored no credential anywhere; crictl.yaml only names the socket; the only
answer says crictl is just a client of the container runtime, so any authentication already configured for containerd works out of the box with crictl, and points at crictl.yaml; the thread has no registry log and
never names the cause).

Reading of the thread (stated in task.txt as the lab's design): the cause is not established by the thread; the lab fixes ONE cause, the commonest one that the answer describes and the asker did not look for: a static
credential in containerd's own configuration (`registry.configs."<host>".auth` in the images plugin), which containerd presents when the registry answers 401, so a pull without --creds still authenticates. The
task is the reverse of the usual one: find which path authorizes the pull (the registry's log tells: containerd, not crictl, answers the 401) and make the node stop presenting credentials on its own, so that the
registry is reached with an account only when the caller supplies it (`crictl pull --creds`, what a kubelet does with a pull secret).

Adaptation: no real private registry product: a stand-in registry (plain HTTP, Basic authentication below one prefix, a log with the authentication of every request) listens on an address of its own, 10.66.73.10
(a /32 alias of lo, so containerd does not treat it as loopback and the hosts.toml of the thread is needed), on port 15000; containerd is a private instance with a version-3 configuration, CRI on; the hosts directory
(config_path) is the case's own, not /etc/containerd/certs.d.

Setup: two images (tags latest and verify, a token each) built offline and pushed to the registry with the account; the node holds only the sandbox image. precondition.sh: daemons and files as recorded, the registry
refuses the anonymous request and serves the account, the hosts.toml and crictl hold no credential, `crictl pull` without --creds succeeds and the log shows containerd answering the 401 with an account (then the image is
removed). Oracle (dynamic): the registry process, files, account and content unchanged, no write, still needs the account, no NAT rule, containerd started from its configuration file; both tags pulled without
--creds are refused and containerd sent no authenticated request; both pulled with --creds are the registry's images (image id, repository digest, manifest and both blobs with the account in the log) and the container
of each runs and prints its token; the credential given on the command line is not kept (anonymous pull refused again).

Taxonomy category: Configuration Management
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/configuration/q73910486/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "configuration" / "q73910486"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q73910486", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 900)        # a first run may install gcc
    pre_timeout = max(timeout, 180)
    solution_timeout = max(timeout, 180)
    oracle_timeout = max(timeout, 240)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the node pulls without credentials although the registry needs an account
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the pulls, pods and containers of the oracle are real objects of the private containerd
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
