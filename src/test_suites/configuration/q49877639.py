"""
SO-49877639: "Running systemd in a docker managed plugin". A Docker managed plugin (a volume driver) is meant to run systemd as its init, with a unit that starts the driver. With the asker's
config.json (entrypoint systemd, /sys/fs/cgroup bind-mounted read-only from the host, the socket in /run/docker/plugins) `docker plugin enable` fails with
`dial unix /run/docker/plugins/<id>/sysd.sock: connect: no such file or directory`: the plugin's container has already exited.
What the question hides (the answer): systemd mounts a tmpfs on /run, which hides /run/docker/plugins, the directory where the plugin's socket must appear (fix: bind it to another path before systemd
starts and create the socket there); and Docker adds its own /sys/fs/cgroup mount AFTER the mounts of config.json, so no option of a mount of /sys/fs/cgroup in the config gives systemd the cgroups
it needs (fix: mount the host's cgroups at another path, /hostcgroup, and `mount --rbind /hostcgroup /sys/fs/cgroup` in an init script that then execs systemd). Both steps need an init script, i.e. a
shell, mount and mkdir in the rootfs.

The case runs this on real components: a private containerd and dockerd (own sockets, roots, exec root; the machine's Docker is not involved; plugins run in the containerd namespace plugins.moby), a plugin
directory (config.json + rootfs/) that setup builds offline from the machine's own systemd (+ systemd-executor, systemctl, the targets), dash, mount, mkdir, their libraries and a tiny static volume driver
(helpers/plugin.c) started by plugin.service, and `docker plugin create bench/sysd:1`. Modern adaptation: the question's Docker 18.03 and its systemd are not pinned (offline); the systemd is the machine's
and its version is recorded; CAP_SYS_RESOURCE is left out of the capabilities (it is not needed, and some sandboxes cannot grant it).

precondition.sh: the lab as recorded (helpers unchanged, daemons of the lab, plugin installed and disabled, plugin directory unchanged); controls: enable fails with the question's error and leaves the plugin
disabled; a repaired COPY of the plugin directory under another name enables and its driver reports PID 1 = systemd (the repair works on this machine's cgroup layout).
The oracle (verify.py): phase A, the plugin as left: enabled, a volume-driver interface, a running task in the lab's containerd whose init is a `systemd` that is a file of the plugin's rootfs, PID 1 of a
PID namespace of its own with PID and mount namespaces different from the host's, the version of the recorded systemd; a volume made through the plugin answers with the driver's pid, the name of PID 1
and its INVOCATION_ID; on the host that pid is a descendant of the task's init (never of the host's PID 1), in a cgroup of a service below the plugin's own cgroup, the MainPID of an active unit of the plugin's
systemd, with that invocation id in its environment. Phase B: `docker plugin disable` + `enable` (a new task from the configuration alone) and the same checks.

Where the samples fail: nothing done; only the cgroups rebound (the socket is hidden by /run's tmpfs); only another option for the cgroup mount in config.json (the question's own attempts); the driver as the
entrypoint (no systemd); the driver binary installed as /usr/lib/systemd/systemd (a stand-in: no unit, no invocation id); the plugin directory repaired but the plugin not re-created. Valid alternatives: the
reference (init keeps the directory, the unit listens there) and an init + a unit that puts the kept directory back on /run/docker/plugins before the driver starts.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/configuration/q49877639/ and converts their exit codes / output into a
structured `cases` dict.

Taxonomy category: Configuration Management
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/configuration/q49877639/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "configuration" / "q49877639"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q49877639",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 240)      # the plugins are disabled, the daemons stopped, mounts and cgroups removed
    setup_timeout = max(timeout, 300)        # builds the plugin directory, starts containerd and dockerd
    pre_timeout = max(timeout, 300)          # controls: a failing enable (waits for the socket) and a repaired copy of the plugin
    solution_timeout = max(timeout, 300)     # a solution re-creates and enables the plugin itself
    oracle_timeout = max(timeout, 600)       # checks, then disable and enable of the plugin, checks again

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: enable fails with the question's error; a repaired copy of the plugin directory runs systemd as PID 1 on this machine
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: systemd is the init of the enabled plugin and its driver works, as left and after disable + enable
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
