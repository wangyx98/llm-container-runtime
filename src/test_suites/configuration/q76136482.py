"""
SO-76136482: "containerd v1.4+ - How to authenticate by config?" (2023; containerd as the runtime of a Kubernetes cluster, shared IP so Docker Hub's anonymous rate limit is used up; the asker wants to give the
node the credentials of his Docker account in containerd's configuration, explicitly without imagePullSecrets and without a mirror registry; the old `[plugins."io.containerd.grpc.v1.cri".registry.configs."docker.io".auth]`
works but is documented as deprecated, and he asks what the new style, `config_path` with a hosts.toml, looks like. The only answer: hosts.toml has no credentials, keep the deprecated syntax, or put a pre-computed
Basic `authorization` header in hosts.toml, "if your registry accepts basic authentication".)

What is measured (and why the version is pinned): Docker Hub is a Bearer-token registry: the registry answers 401 with a challenge, the client asks a token endpoint (another host, auth.docker.io) for a token, and the
token endpoint is where the account's Basic credentials are checked. Measured with a Docker-Hub-like lab (distribution 3.0.0 with token authentication, a token service that accepts Basic credentials at its endpoint):
through the CRI (`crictl pull`, no --creds) a Basic `authorization` header in hosts.toml does NOT authenticate on containerd 1.7.20 and 2.0.0 (the header goes to the registry only; the token request is anonymous, the token
has no access); from containerd 2.1.0 the headers of a host entry are sent with the token request too (also in 2.2.0, 2.3.6) and the pull works; the deprecated registry.configs auth works in all of them. So the
case is built on containerd 2.2.3 (official amd64 and arm64 releases, sha256 pinned): under the question's constraints (current hosts.toml style, no deprecated auth, no mirror, no secret, no CLI credentials) it is the only
mechanism that exists. This is a deliberate move from the question's era (1.x), where nothing of the kind exists; task.txt says what the check does.

Adaptation (stated in task.txt): a private containerd with its own socket, root and state (CRI images plugin on, `version = 3` configuration with `config_path` naming the lab's hosts directory), no kubelet; the registry
hub.registry (HTTP, port 80 of 127.76.13.64) and its token service auth.hub.registry (HTTP, port 5001: another host name, as auth.docker.io is for registry-1.docker.io; Python, signs with openssl; Basic credentials give
access to team/app, none give a token without access, wrong ones 401), both names in /etc/hosts on one marked line; the account is made by setup and readable by root only; "authenticated" stands for "allowed to read"
(the repository is private) in place of Docker Hub's rate limit.

precondition.sh: containerd 2.2.x, the registry and the token service running, config.toml and hosts.toml without credentials; `crictl pull hub.registry/team/app:v1` fails and the token service saw an anonymous
request; control: the same pull with --creds works (the account is valid) and the image is removed again.
The oracle (oracle.sh): the lab untouched (sha256 of config.toml, registry configuration, token service, jwks and account; one file in the hosts directory with one host entry and no other URL than http://hub.registry),
an anonymous reader still gets no access, a NEW image (new tag and digest, pushed with the account, the copy of the push removed, absent from the node) is pulled without credentials, the node holds that digest, the token log
shows a Basic request of the account for the pull granted, the registry log shows the tag, the manifest and the blobs served to the account.

Where the samples fail: nothing done; the deprecated registry.configs auth in config.toml; the header under the host entry of the token host; a second host entry (a mirror) with the header; only `crictl pull --creds`
(a pre-pull; the check pulls a new image); the token service changed to give anonymous readers access; a header with a wrong password; a header without the word Basic.
Valid: the Basic header in the host entry of hosts.toml (reference), the same as an inline table, the same followed by a containerd restart (hosts.toml is read at every pull, no restart needed).

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/configuration/q76136482/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Configuration
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/configuration/q76136482/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "configuration" / "q76136482"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q76136482",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)      # containerd, the registry, the token service
    setup_timeout = max(timeout, 600)        # first run downloads containerd (~35 MB) and the registry (~30 MB)
    pre_timeout = max(timeout, 180)
    solution_timeout = max(timeout, 180)     # a solution may restart containerd and pull
    oracle_timeout = max(timeout, 240)       # a new image is made, pushed and pulled

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)      # setup adds a line to /etc/hosts: always take it out again
        return cases, error_message

    # 2. precondition oracle: the anonymous pull fails, the pull with credentials works
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: a new image is pulled without credentials, authenticated by the node's own configuration
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
