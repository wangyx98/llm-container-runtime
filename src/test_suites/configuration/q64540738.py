"""
SO-64540738: "Faasd - can't pull image from private registry" (faasd on a Raspberry Pi: `faas-cli deploy` of an image of a private registry fails with HTTP 400 "unable to pull image ...:
cannot pull: failed to resolve reference ...: no scope specified for token auth challenge"; the asker tried docker login / registry auth in the stack file; the thread's answer points at faasd's own
docker config file, /var/lib/faasd/.docker/config.json, for the registry's account).

Reading of the thread (stated in task.txt as the lab's design): the error text is that of the containerd client inside the faasd-provider release the asker runs (0.10.0, containerd 1.3.2), which
refuses a Bearer challenge that names no scope; the config file alone does not change that for this registry. The lab keeps both halves: a registry whose token challenge has no scope (the registry of
the thread is not available, so its behaviour is reproduced by a stand-in) and the 0.10.0 provider; the reference fix is a newer provider release (0.13.0, containerd 1.5.4: it derives the scope from the
request and asks the token service for repository:<name>:pull with the account) AND the registry account in /var/lib/faasd/.docker/config.json (the thread's file: without it the token service answers 401).

Adaptation: no Raspberry Pi, no gateway container and no faas-cli: the provider's API (POST /system/functions, port 8081, basic auth admin) is what the gateway forwards a deployment to, and the lab uses it
directly (a wrapper, faas-deploy, sends what faas-cli sends); the two release binaries and the CNI plugins are the real pinned releases (sha256 checked, for this architecture); containerd, the CNI directories
and /run/containerd are private to the case (the daemons run in a mount namespace of their own, started by faasdctl) while /usr/local/bin/faasd and /var/lib/faasd are the machine's own paths, as in a
faasd installation; the registry is a TLS stand-in with token authentication at 10.66.54.40:15064 (a /32 alias of lo), its CA trusted by the provider. The reference fix differs from the thread's answer
(a new release is part of it) and task.txt says so.

Setup: pinned downloads (cached), CA and certificate, registry and the two function images (tags 1.0 and verify, a static server with a token each) pushed with the account, containerd and the provider 0.10.0
started by faasdctl, release 0.13.0 staged. precondition.sh: daemons and files as recorded, the challenge has no scope, the deployment is refused with the thread's message and the registry's log shows no
token request. Oracle (dynamic): the registry process, files and content unchanged and no write, the registry still needs a token of the account and its challenge is unchanged; containerd and the provider
run in the case's namespace from the case's files; both tags are removed from containerd, deployed through the provider's API (with the registry login in the body, as faas-cli sends it), called through
the provider (the token of the image comes back) and the registry's log shows containerd asking the token service with the account for the repository scope and fetching manifests and both blobs with the token.

Taxonomy category: Configuration Management
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/configuration/q64540738/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "configuration" / "q64540738"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q64540738", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 900)        # a first run downloads the releases and may install gcc
    pre_timeout = max(timeout, 180)
    solution_timeout = max(timeout, 180)
    oracle_timeout = max(timeout, 240)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the deployment through faasd's provider fails with the scope error of the thread
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the functions of the oracle are real deployments through the provider
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
