"""
SO-59744000: "Kubernetes 1.17 containerd 1.2.0 with Calico CNI node not joining to master". The title and the error messages point at the network (calico-node
cannot start, there is no CNI configuration, the node stays NotReady), but the cause is a configuration mismatch of two components: containerd runs runc with
the systemd cgroup driver (SystemdCgroup = true), while the kubelet uses the cgroupfs driver (its default) and asks for the cgroup parent /kubepods/burstable/pod<uid>.
runc with the systemd driver wants a slice name and refuses ("expected cgroupsPath to be of format slice:prefix:name for systemd cgroups"), so no pod sandbox starts,
calico-node never runs, the CNI is never configured and the node is NotReady. The answers and the asker's own fix are all the cgroup driver: the kubelet and the
runtime must use the same one (cgroupDriver: systemd in the KubeletConfiguration, or SystemdCgroup = false in containerd).

Category: configuration, by what the case tests (the README rule: a case is placed by what it tests, not by the label of the CSV row). Related: q58429514 (CRI-O: the
cgroup manager and the slice name format of one component); this one is the two-sided version, kubelet and containerd, and the failure is seen from the kubelet.

Local version: no real kubelet and no real cluster. A private containerd (own socket, root and state; real CRI plugin, real runc) is the node's runtime, with runc on the
systemd driver; the kubelet is the program kubelet-sim (helpers/kubelet-sim), which reads a KubeletConfiguration (cgroupDriver, containerRuntimeEndpoint) and static pod
manifests and starts the pods through the CRI with the cgroup parent a kubelet builds for the configured driver (cgroupfs: /kubepods/<qos>/pod<uid>; systemd:
kubepods-<qos>-pod<uid with _>.slice). Two pods, calico-node (burstable) and kube-proxy (besteffort); the node is Ready when calico-node runs. The case needs a systemd host
(the systemd driver talks to systemd over D-Bus); the sandbox of the benchmark authors has none, so the success path is verified on a real VM.

The decision (kubelet side only): containerd keeps SystemdCgroup = true, the host runs systemd (one cgroup manager); switching containerd to cgroupfs is the other
way out in the real world, but here it is a "cheating" sample. precondition.sh proves the bad state (both pods fail with the runc error, the node is NotReady, no pod is
left) and two controls: a pod with the cgroupfs style parent runs on the runc-cgroupfs handler (cgroupfs driver) and a pod with the systemd style parent runs on the default
runtime. The oracle checks containerd's live configuration (default runtime runc, SystemdCgroup true), the kubelet configuration (cgroupDriver systemd, same endpoint), and then
runs a pristine copy of the kubelet program on new manifests (new pod uids) after removing every pod: both pods must run, the node be Ready, the containers give their token
and run in kubepods-<qos>-pod<uid>.slice/cri-containerd-<id>.scope (read in /proc/PID/cgroup), and a second sync changes nothing.

Where the samples fail: no change; containerd switched to cgroupfs and restarted (the kubelet is untouched: the pods do start, but the case is solved on the wrong side);
a driver value the kubelet does not accept (Systemd). The valid alternative writes the value quoted over the whole line.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/configuration/q59744000/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Configuration Management
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/configuration/q59744000/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "configuration" / "q59744000"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q59744000",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 240)   # setup compiles the programs, starts the node and tries the pods; the precondition runs two control pods; the oracle starts the pods twice

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: containerd's runc on the systemd driver, the kubelet on cgroupfs, no pod starts; controls: a pod whose cgroup parent fits its runc's driver does
    pre = run_script(CASE_DIR / "precondition.sh", timeout=long_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: containerd unchanged (systemd driver), kubelet configuration on the systemd driver, the kubelet starts calico-node and kube-proxy (new pod uids) in the slices of the systemd driver, the node is Ready
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
