"""
SO-66642654: "Microk8s ImagePullBackOff cannot be fixed by modifying the config". On a MicroK8s node (arm64) a Pod that uses an image of the local registry
(192.168.0.45:32000, plain HTTP) stays in ImagePullBackOff with `Head "https://192.168.0.45:32000/v2/myapp/manifests/latest": http: server gave HTTP response to HTTPS client`.
The asker wrote the registry entry (a `mirrors` table with an http:// endpoint and `insecure_skip_verify`) into /var/snap/microk8s/current/args/containerd.toml and rebooted: no change.
What the question hides: MicroK8s does not keep containerd.toml. The snap's launcher makes it again from args/containerd-template.toml at every start of containerd, so what is written
into the generated file is gone after the restart; the persistent place is the template (then a restart, since containerd reads its configuration at start). The snippet of the question is
also written for the CRI plugin of containerd 1.x (`plugins.cri.registry`); a 2.x configuration reads the registry table under `io.containerd.cri.v1.images`, either as `mirrors`
(deprecated) or as `config_path` plus a hosts directory with a hosts.toml.

The case models that node on real components: a private containerd (the real binary; own root, state and socket; runc on cgroupfs; a sandbox image imported offline) that
`mk8sctl start|stop|restart` runs through `mk8s-run-containerd`, a launcher written like the snap's: it renders args/containerd-template.toml (stock: containerd's default configuration of the
installed version, with ${SNAP_DATA} and ${SNAP_COMMON} placeholders, no registry setting) into args/containerd.toml at every start and then execs containerd. A registry fixture on plain HTTP
listens at 10.66.64.45:32000 (an alias of `lo`: containerd treats loopback registries as plain HTTP by itself) and holds myapp:latest. This is a modern-containerd adaptation: MicroK8s 1.18
(containerd 1.3, a snap) cannot be pinned offline, and the VM's containerd is 2.x.

precondition.sh: the lab as recorded; no registry entry and no config_path in the template or the generated file; controls: the CRI pull fails with the question's text, the asker's own try
(an entry in the generated file, then `mk8sctl restart`) is undone by the restart and the pull still fails, a throw-away containerd with the same template plus an entry pulls the image.
The oracle (verify.py): the launcher, mk8sctl, the registry process and its address are unchanged and the containerd that answers is the process mk8sctl started (pid file, command line);
phase A, the node as the solution left it: containerd.toml is the rendering of the template, every pod and every image of the registry is removed, a NEW build of myapp:latest is pushed
(new salt, new digests), the CRI pulls it (image id is the build's; manifest and both blobs are requested by containerd in the registry's log), a host-network pod runs a container whose program
prints the nonce of the check and the salt, and /salt in its root is that salt; phase B: `mk8sctl restart` and the same with another new build.

Where the samples fail: nothing done; the entry in the generated file and a restart (the asker's try); the right file without a restart (containerd.toml is not the template's rendering);
the question's snippet in the template (wrong plugin id for 2.x); the image preloaded with `ctr --plain-http` (the check removes it and pulls a new build); containerd stopped and started by
hand with an edited configuration (not the process of mk8sctl); the launcher patched to append the entry after rendering. The valid alternative is `config_path` set in the template plus a hosts directory.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/configuration/q66642654/ and converts their exit codes / output into a
structured `cases` dict.

Taxonomy category: Configuration Management
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/configuration/q66642654/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "configuration" / "q66642654"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q66642654",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # the node is stopped, mounts and cgroups removed
    setup_timeout = max(timeout, 300)        # starts the registry and the node, imports an image
    pre_timeout = max(timeout, 300)          # controls: a restart of the node and a throw-away containerd
    solution_timeout = max(timeout, 300)     # a solution restarts the node itself
    oracle_timeout = max(timeout, 600)       # two builds pulled and run, a restart of the node

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the pull fails with the HTTPS error, the asker's try is undone by a restart, a containerd with the entry pulls
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: a new build is pulled over plain HTTP and runs, as the node was left and after `mk8sctl restart`
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
