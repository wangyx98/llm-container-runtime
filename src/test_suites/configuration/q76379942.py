"""
SO-76379942: "How can I make Kubernetes use a private repository by default with Nexus and Containerd?" (a registry mirror for docker.io written into containerd's configuration, pods that name no registry go to
docker.io anyway, and pods that name the Nexus address and port fail with `Head "https://repo.mm.mm:8082/v2/...": dial tcp ...:8082: connect: connection refused` although the host answers a ping; the only answer shows
a `registry.mirrors."docker.io"` entry with an https endpoint behind a reverse proxy, without explaining the cause).

Reading of the thread (stated in task.txt as the lab's design): both symptoms have one cause: nothing listens at the port of the mirror and of the image names (a ping is no proof of a listening port; Nexus' Docker
connector has a port of its own), and a failing mirror makes containerd fall back to docker.io, which hides the real error for the default names; once the port is right, the scheme is the second problem (the connector
speaks plain HTTP), so `connection refused` is not a TLS configuration error.

Adaptation: no real Nexus or Kubernetes: a stand-in registry (plain HTTP, request log) listens on an address of its own, 10.66.79.42 (a /32 alias of lo, so containerd does not treat it as loopback), on port 18083;
the engineer's mirror and image names use 8082; containerd is a private instance (version-3 configuration like the thread's, CRI on, host-network pods made with crictl); the thread has no Nexus configuration, the
lab's is nexus.properties.

Setup: four images (two repositories, tags 1.0 and verify, a token each) built offline and pushed to the stand-in; the node holds only the sandbox image. precondition.sh: daemons and files as recorded, the connector
answers and nothing listens on 8082, the node holds none of the images, the default name fails without reaching Nexus, the explicit name fails with `connection refused`, a plain pull of the real port says the
server speaks HTTP. Oracle (dynamic): the Nexus process, its files and content unchanged, no write to it, no listener on 8082, no NAT rule, containerd started from its configuration file; each of the two names
pulled through the CRI after removal (image id and repository digest as pushed, Nexus saw the manifest fetched by containerd), a container from each runs and prints its token; the verify tags of both repositories
pulled under the same names with manifest and both blobs seen by Nexus.

Taxonomy category: Configuration Management
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/configuration/q76379942/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "configuration" / "q76379942"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q76379942", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 900)        # a first run may install gcc
    pre_timeout = max(timeout, 180)
    solution_timeout = max(timeout, 180)
    oracle_timeout = max(timeout, 240)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: both names fail: the connector is reachable on its own port only
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the pulls, pods and containers of the oracle are real objects of the private containerd
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
