"""
SO-77602468: "How do I pull a private docker image into crio?" (the image is in a private gcr.io repository that needs gcloud authentication, CRI-O cannot authenticate; the asker has the image in Docker's store and asks
whether it can be copied into CRI-O's storage locally; the thread has no answer: the way is `docker save` / skopeo `docker-daemon:` into `containers-storage:`).

Adaptation (stated in task.txt): no real gcr.io or gcloud: the registry name is private-gcr.invalid (it never resolves, so nothing can be pulled and the "cannot authenticate" is a "cannot pull"); the Docker engine is a
private dockerd (own containerd, socket and data root) holding the image; CRI-O is a private instance with its OWN storage root (not the machine's default one), stub CNI plugins and the sandbox image in its store. The
variant of q59161183 (docker-archive tarball into the default storage): here the source is a running Docker daemon and the target is a non-default CRI-O storage root, which a plain `skopeo copy ... containers-storage:name`
does not reach.

Setup: an image built offline in `docker save` format (one static program with a per-run token, started with an argument it prints the token) and loaded into Docker, the archive deleted (Docker is the only copy);
Docker's image id is checked to be the config digest (classic store); CRI-O's storage root has only the sandbox image. precondition.sh: daemons and files as recorded, Docker holds the image, CRI-O does not know it, its
pull fails (no such host), a container cannot be created from it, the machine's default storage has no copy. Oracle (dynamic): daemons and configuration unchanged and Docker still holds the image with the same id;
CRI-O reports the image under its name with Docker's image id; a pod and a container the oracle creates through the CRI from it run, report that image id, log the token and `exec /app --token` prints it.

Taxonomy category: Configuration Management
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/configuration/q77602468/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "configuration" / "q77602468"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q77602468", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 900)        # a first run may install gcc and skopeo
    pre_timeout = max(timeout, 120)
    solution_timeout = max(timeout, 120)
    oracle_timeout = max(timeout, 240)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the image is in Docker only, CRI-O does not know it and cannot pull it
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the oracle's own pod and container are real objects of the private CRI-O
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
