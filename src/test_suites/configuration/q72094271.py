"""
SO-72094271: "How to restrict core file size in container on k8s cluster with containerd?". On a node with containerd every container has `ulimit -c` unlimited;
the asker's attempts (`ulimit -c 0` in the Dockerfile, a limits.conf mounted into the pod) do nothing, and `LimitCORE=0` in the containerd unit only worked after the right order:
`systemctl daemon-reload`, then `systemctl restart containerd`. What the question hides: containerd puts no RLIMIT_CORE into the OCI spec of a container, so the main process and every
`exec` inherit the core limit of the containerd process itself (the LimitCORE= of its unit, infinity in the upstream unit); the other global route is the runc handler's
`base_runtime_spec` with an RLIMIT_CORE entry (a complete default spec, `ctr oci spec`, plus the rlimit). PAM limits do not apply to container processes, the limit has to be soft AND hard
(a hard limit left at infinity lets a process raise its soft limit again), a unit file edit is not seen before daemon-reload, and a limit put on the running containerd with prlimit
does not survive a restart of the service.

The case keeps the structure on real components: a private containerd (the real binary, its own root, state and socket, runc on cgroupfs with a runtime root of its own) that runs as the
systemd service bench72094271-containerd.service (unit file with LimitCORE=infinity like the upstream containerd.service; on a host without systemd the sandbox's stand-in for systemctl
runs it with the same loaded-snapshot semantics), two images imported offline (a sandbox program and a probe program: serve, limits, abort, abort0), and kernel.core_pattern fixed to a
FILE pattern for the time of the case (a piped handler ignores RLIMIT_CORE; cleanup.sh puts the machine's value back, and the places a solution may use besides the unit are recorded
and restored too).

precondition.sh: the lab as recorded, the unit with LimitCORE=infinity and no drop-in, no rlimit in the configuration; controls: a new container has core=unlimited (main process and
exec), a process that dies of SIGABRT leaves a core file, a process that sets its own limit to 0 and aborts leaves none. The oracle (verify.py): the lab is unchanged (images, core_pattern,
probe) and the containerd that answers is the main process of the service; phase A, the node as the solution left it: three NEW pods, each with a running container and a container that
aborts: /proc/PID/limits of the main process 0/0, `crictl exec` sees 0/0 and its aborting process leaves no core, the container whose main process aborts exits with 134 and leaves no
core; phase B: `systemctl restart` (nothing else first) and two more new pods judged the same way.

Where the samples fail: nothing done; the unit edited and the service restarted without daemon-reload (the asker's order); `LimitCORE=0:infinity` (soft only); prlimit on the running
containerd (phase B); containerd stopped and started by hand with prlimit (not the service's process); kernel.core_pattern changed so that no core appears. The valid alternative is
base_runtime_spec with an RLIMIT_CORE 0/0 entry in a copy of `ctr oci spec` and a restart.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/configuration/q72094271/ and converts their exit codes / output into a
structured `cases` dict.

Taxonomy category: Configuration Management
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/configuration/q72094271/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "configuration" / "q72094271"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q72094271",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # the service and its containers are stopped, mounts and cgroups removed
    setup_timeout = max(timeout, 300)        # starts the service, imports two images
    pre_timeout = max(timeout, 300)          # controls: two pods with an aborting process each
    solution_timeout = max(timeout, 300)     # a solution restarts the service itself
    oracle_timeout = max(timeout, 600)       # five pods, a restart of the service

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the containers have core=unlimited, an aborting process leaves a core file, the unit says LimitCORE=infinity
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: new pods have core 0/0 (main process, exec, aborting processes), as left and after a restart of the service
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
