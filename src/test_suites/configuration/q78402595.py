"""
SO-78402595: "Containerd error loading seccomp filter into kernel in kubernetes" (2024; Ubuntu nodes, kernel 5.15.0-105, containerd 1.5.7, Kubernetes 1.27.5; the liveness probes (exec) of pods
with a seccomp profile fail with `OCI runtime exec failed: ... unable to init seccomp: error loading seccomp filter into kernel: error loading seccomp filter: errno 524: unknown`; restarting the
containers, containerd and kubelet does not help; raising net.core.bpf_jit_limit makes it go away, until the limit is hit again. The root cause was not established in the question.)

What is measured: errno 524 is ENOTSUPP: a kernel with CONFIG_BPF_JIT_ALWAYS_ON has no interpreter to fall back to when a seccomp filter cannot be JIT-compiled, and the JIT memory is accounted in the
global net.core.bpf_jit_limit, which binds only callers without CAP_BPF / CAP_SYS_ADMIN (runc loads the filter after it has dropped its capabilities). Every process that keeps a filter loaded (here: 16 exec
processes of old "probe runs" that were never reaped) holds its JIT memory until it exits. The lab measures the JIT memory with the real exec (the smallest limit under which one more exec loads, a binary search),
and sets the node's limit so that one exec fails and twelve fit when the leftovers are gone. The oracle requires that the leftover processes are gone, puts the lab's limit back for its run (so that a changed number
alone proves nothing), holds twelve execs at once and runs the exec probe six times (seccomp mode 2, the new user namespace refused), and checks the container (image, profile, capabilities, user), the host's
JIT sysctls (the limit not above the default, enable and harden untouched) and containerd.

Adaptation (stated in task.txt): a private containerd (v1.5.7 official amd64 release on x86_64; the oldest official arm64 build, v1.6.0, on aarch64, since 1.5.x has no arm64 release; sha256 pinned) with its
own socket, root, state and namespace, the machine's runc, a one-layer image of a static C program, no Kubernetes; the container is made with `ctr run -d --seccomp`. The kernel is the machine's.
The lab changes a host-wide sysctl while it runs: the original values are recorded in /var/lib/bench78402595 and cleanup.sh puts them back first (setup.sh also does that when it stops early).

precondition.sh: containerd of the pinned version, tgt running with the profile (seccomp mode 2), 16 leftover processes, the limit as calibrated (below the default), the exec fails with errno 524 three times;
control: with the limit at the default the same exec works and prints `seccomp=2 userns_errno=1`.

Where the samples fail: nothing done; only the limit raised (to the default, or far above it); containerd restarted; the container recreated without the profile (works, but no seccomp); the container recreated
privileged (the limit does not bind it, the profile and capabilities changed); the limit raised far above the default together with the leftovers ended; bpf_jit_enable=0; only half of the leftovers ended.
Valid: the leftovers ended and the limit put back to the default (reference); the leftovers ended and the limit left as it is; the container recreated with the same command (its processes end, the profile stays).

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/configuration/q78402595/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Configuration
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/configuration/q78402595/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "configuration" / "q78402595"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q78402595",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)      # the container, containerd, the shims, mounts
    setup_timeout = max(timeout, 600)        # first run downloads containerd (~30 MB); the calibration runs about 50 execs
    pre_timeout = max(timeout, 120)
    solution_timeout = max(timeout, 120)
    oracle_timeout = max(timeout, 180)       # twelve held execs, six probes

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)      # setup lowers a host-wide limit: always put it back
        return cases, error_message

    # 2. precondition oracle: the exec fails with errno 524 under the lowered limit, works under the default one
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the leftovers are gone, the exec works under the lab's limit with the profile in force
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not (puts the host's JIT limit back)
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
