"""
SO-54303822: "Getting runc config.json from docker container" (2019; the asker followed a blog post and extracted the config.json of a running Docker container to start a runc container from it; the
path differs between the references (/run/docker/libcontainerd/<id>, /var/run/docker/libcontainerd/<id>), his host #1 (/var/run/docker/containerd/daemon/io.containerd.runtime.v1.linux/moby/<id>) and a
host #2 where he cannot find it; he asks which versions decide the location. Two answers, both from other hosts: Docker 19.03.4 / containerd 1.2.10 / runc 1.0.0-rc8 keeps it in
/run/containerd/io.containerd.runtime.v1.linux/moby/<id>/config.json; to use it with runc root must be changed and the /etc/hosts, /etc/hostname and /dev/shm mounts and the hooks removed.)

What is measured, and what is NOT: the engine versions of the thread (containerd 1.2 with the v1 runtime) do not exist on a current host (containerd 2.x has no v1 runtime, Docker 19.03 does not run on cgroup v2), so the
case runs on the engine that is installed (measured: Docker 29.8.2, containerd 2.3.6, runc 1.5.1, cgroup v1 and v2 handled): the bundle of a running container is
<containerd state>/io.containerd.runtime.v2.task/moby/<container id>/config.json (the state directory is the `state` of containerd's configuration; Docker's own exec-root keeps only runc's state.json in
runtime-runc/moby/<id>). task.txt says that the paths of the question do not exist on this engine. runc must be 1.2 or newer for Docker 29 (its spec has a time namespace): setup puts the newest runc of the host first in
the PATH of the lab's containerd. This is an observability task (find an artifact), its runtime increment is weak; the part that matters is that the answer depends on the engine's versions and layout.

precondition.sh: the lab is as its record says (dockerd and containerd the processes setup started, both containers running with the same init processes); the target file does not exist; none of the
paths of the question holds a config.json for the container and Docker's exec-root state directory has only state.json; docker inspect is not an OCI spec; control: the real bundle exists in containerd's state
directory and is the spec of bench-api (token, hostname, memory limit).
The oracle (oracle.sh): the lab unchanged (no restart, no recreate); /tmp/bench54303822/config.json is a regular file (no link), JSON with ociVersion/process/linux, not a template (hostname runc, no BENCH_TOKEN),
not the spec of bench-batch, and its hostname, args, read-only /data mount, memory limit, CPU quota, cgroupsPath and the memory limit of the real cgroup of the init process are those of bench-api; finally it is byte for byte
the config.json of the bundle.

Where the samples fail: nothing done; `runc spec` template; `docker inspect` output; the spec of bench-batch; runc's state.json from Docker's exec-root; the path of the answer (v1.linux: the copy fails); the spec edited as
the second answer says (root changed, hooks and mounts removed); a link to the bundle; a spec built by hand from docker inspect. Valid: the reference (state from containerd's configuration + id from docker inspect),
a find, the path from ctr's container info, a copy through cat/tee.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/configuration/q54303822/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Configuration
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/configuration/q54303822/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "configuration" / "q54303822"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q54303822",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)      # dockerd, containerd, the shims
    setup_timeout = max(timeout, 240)        # a static program is compiled, two daemons and two containers start
    pre_timeout = max(timeout, 60)
    solution_timeout = max(timeout, 90)
    oracle_timeout = max(timeout, 90)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the containers run, the paths of the question are empty, the real bundle is elsewhere
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the saved file is the real config.json of bench-api
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
