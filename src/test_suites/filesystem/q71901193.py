"""
SO-71901193: "how to get the dangling images using crictl" (2022)

On a node with containerd and no Docker the asker wants the dangling images from crictl, to know which can be removed; `crictl images` does not say, `-f dangling=true` is not a flag of crictl. The only answer: crictl
cannot list them, use `crictl rmi --prune` for the unused ones. No semantics are given, and the two notions are mixed: dangling (no tag) and unused (no container). Measured here (containerd 1.6.21 CRI, crictl 1.24.2):
`crictl images -f` is refused ("flag provided but not defined"); an image that lost its tag to a newer one is `<none> <none>` in the table with repoTags [] and repoDigests [] (the CRI keeps a record of the image's id,
made when the CRI first sees a new name, so the image does not vanish), but an image known only by a digest (repoTags [], repoDigests [name@sha256:...]) also shows `<none>` as its TAG; the containers of `crictl ps -a
-o json` name their image twice: image.image is the name it was made with (a tag that moved on now names another image), imageRef is the id it really runs; an exited container still holds its image; `crictl rmi --prune`
removes every image without a container, tagged ones too (even the sandbox's pause image), so it cannot answer "only the dangling" and it changes the node.

Setup: a private containerd with the CRI plugin, a Pod "lab" with three containers (one on an image whose tag moved on, one exited on another such image, one on a digest-only image); images: tagged idle, untagged idle,
digest-only idle, replaced ones; all offline, random contents.

Task: write /var/lib/bench71901193/imgclass: JSON with each image's id, tags, digests, class (tagged / digest_only / dangling), the containers (any state, by imageRef) and in_use, plus dangling_ids and removable_ids (dangling
and unused); read-only.

Oracle (nothing is taken from what the solution says): two phases (the node as left; after the oracle moved a tag under a running container, removed the exited container, replaced a tag, removed a tag record): the report
equals the oracle's own reading of the CRI's JSON and what it built; the node (image records, content, containers, Pods, snapshots) is unchanged by the tool.
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/filesystem/q71901193/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "filesystem" / "q71901193"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q71901193",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containers, shims, mounts
    setup_timeout = max(timeout, 300)        # the first run downloads containerd, crictl and runc (60 MB); later runs take 15 s
    pre_timeout = max(timeout, 60)           # reads only
    solution_timeout = max(timeout, 60)      # writes a tool
    oracle_timeout = max(timeout, 240)       # two phases, a few images and a container made by the oracle

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the question's situation (no dangling filter, <none> for dangling and digest-only, containers by imageRef)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: imgclass in two phases against the CRI's own reading; the node unchanged
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
