"""
SO-76627556: "containerd apparently storing multiple copies of the same container - how to test it's not a wasteful duplication?"

Ten pods of one image: `du` of each container's directory below containerd's state shows the whole image, ten times. The directory is the
container's rootfs, an overlay mount: du walks through it into the shared lower layers. What the node really occupies is in the snapshotter's
directory (shared lowers once, plus each container's upper); a container only costs more when it copies a lower file up (opening a file for writing
copies the whole file up; metacopy is off). Measured here (containerd 1.7.20, runc 1.1.12): ten idle containers, du x 10 = ten images, snapshots = one
image + 20 KiB per container; a copy-up adds the full file to that container's upper; an append adds the file plus the new data (not an identical copy).

Setup: a private containerd (no CRI, GC out of reach), an offline two-layer image (one big random layer: /big.bin of 40-72 MiB, one small with a
static app), ten containers in the namespace k8s.io, mkset (more containers, with copy-up, new file, or modifying copy-up).

Task: write /var/lib/bench76627556/dupreport: JSON with the containers (rootfs, upperdir, upper_bytes, copied_up_bytes), shared_lower (dirs,
bytes), naive_du_bytes, physical_bytes, double_counted_bytes, copied_up_bytes_total; allocated bytes, each inode once; read-only.

Oracle (nothing is taken from what the solution says): the report is checked three times, on the node as it is and after two rounds of containers
started by the oracle (random numbers; copy-ups, a writer, a modifier), against the mounts, the real `du`, and what the oracle did; the files of
the snapshotter, the mounts, the containers and the tasks are the same before and after each run; the node's programs are unchanged.
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/filesystem/q76627556/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "filesystem" / "q76627556"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q76627556",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containers, shims, mounts
    setup_timeout = max(timeout, 300)        # the first run downloads containerd and runc (40 MB); later runs take 10 s
    pre_timeout = max(timeout, 60)           # reads only
    solution_timeout = max(timeout, 60)      # writes a tool
    oracle_timeout = max(timeout, 240)       # three reports and two rounds of containers (a few seconds)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: ten containers whose du each shows the whole image, while the snapshotter holds it once
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: dupreport's numbers on the node as it is and after two more rounds of containers, the node unchanged
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
