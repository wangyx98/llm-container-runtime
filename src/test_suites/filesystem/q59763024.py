"""
SO-59763024: "Kubernetes nginx ingress unexpected error storing fake SSL Cert: could not create PEM certificate file" (ingress-nginx 0.27.1 on CentOS 8 with containerd 1.2.0; the controller
exits with `unexpected error storing fake SSL Cert: could not create PEM certificate file /etc/ingress-controller/ssl/default-fake-certificate.pem: ... permission denied`; the
securityContext of the deployment is runAsUser 101, privilege escalation allowed, drop ALL and add NET_BIND_SERVICE; a second error from the edited question is
`bind() to 0.0.0.0:80 failed (13: Permission denied)`; the one answer says the new image runs as 101 and an old deployment with another uid fails; the asker says 101 does not work).

Adaptation (stated in task.txt): not a reproduction of the incident (the real image is not obtainable here and its cause is not established in the thread). A private containerd node (CRI on,
host network) runs one pod whose "controller" is an offline image with two constructed defects, one after the other: the directory /etc/ingress-controller/ssl of the image belongs to uid 33
(mode 775) while the deployment runs as 101, and the image's busybox (the server) has no file capability, so a non-root process gets no NET_BIND_SERVICE from the capability sets alone
(measured: with the file capability the same pod binds port 80 as uid 101 with only that bounding set; no_new_privs is not a cause when the capability is added; containerd 2.x clears
ambient capabilities, so they are not a way out; a net.ipv4.ip_unprivileged_port_start change is a change of the host).

Setup: images built offline, a per-run certificate, private containerd with its own socket, root and a version-3 configuration, the deployment files (pod.json, controller.json), node-ctr,
node-crictl, node-apply, the first failure (the certificate error). precondition.sh: the failure; the image's facts (33:33 775, no file capability); three scratch pods: the group 33 alone ->
certificate stored, then `httpd: bind: Permission denied`; a copy of the program with the file capability alone -> the certificate error; both -> answers. The task: make the controller
run from the deployment files without root, privilege, a wider capability set or a change of the image or the host. Oracle (dynamic): lab unchanged (wrappers, containerd, images, the image's
program still without a file capability, the host's port setting); one pod, one running controller as 101:101 with bounding set NET_BIND_SERVICE only, the image's own busybox as the
process, only allowed mounts, the listener on port 80 is that process, /healthz and the stored certificate (valid PEM) served; then node-apply again and the same checks; lab checked again.

Taxonomy category: Filesystem, Mount & Storage
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/filesystem/q59763024/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "filesystem" / "q59763024"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q59763024", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 300)        # a first run may install busybox-static
    pre_timeout = max(timeout, 120)
    solution_timeout = max(timeout, 180)
    oracle_timeout = max(timeout, 240)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the first failure, the image's facts, the two failures one at a time on scratch pods, a working control
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the controller runs from the deployment files as uid 101 with NET_BIND_SERVICE only, answers on port 80; node, image and host untouched
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
