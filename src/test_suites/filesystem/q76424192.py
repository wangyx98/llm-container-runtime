"""
SO-76424192: "Kubernetes all images are duplicated with same id"

k3s + external containerd 1.6.21: every image is listed twice by nerdctl (same ID, same size, one untagged); the asker fears double storage. The
thread has no proof of a defect; its own answer says the built images are copied between BuildKit's store and containerd's. Measured here
(containerd 1.6.21, nerdctl 1.3.1, BuildKit 0.11.6, crictl 1.24.2): a CRI pull makes THREE image records for one manifest (repo:tag, repo@digest,
the config digest as a name), nerdctl build + load makes two (tag, config digest); nerdctl lists each record as a line, with the manifest digest as
ID. The content store and the snapshotter hold one copy (blobs: manifest, config, layers); a rebuild with another label has another ID and the
same layer (one copy); BuildKit's own root holds the built image's manifest, config and layer again, with its own snapshot: that is the real
second copy, and it is build cache, not containerd's.

Setup: containerd with CRI, a loopback registry seeded by a throwaway containerd (the node's own store stays empty), buildkitd (OCI worker),
nerdctl/crictl wrappers; two images pulled by crictl, one built by nerdctl; the registry also holds app/c and app/d.

Task: write /var/lib/bench76424192/imgreport (read-only JSON): records by target with their kind, image id, blobs, bytes; listed vs real bytes;
what removing alias records would free (nothing); unreferenced blobs; layers shared between images; BuildKit's store compared by digest.

Oracle (nothing is taken from what the solution says): three reports, on the node as it is and after two rounds the oracle makes itself (a pull
under two tags, a rebuild with another label, one more tag, another pull, a build of new data), against its own reading of `ctr`, the blobs and `du`;
the node (records, blobs, snapshots, CRI images, BuildKit's blobs) must be the same before and after each run; the daemons keep running.
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/filesystem/q76424192/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "filesystem" / "q76424192"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q76424192",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # daemons, mounts
    setup_timeout = max(timeout, 300)        # the first run downloads containerd and runc (150 MB); later runs take 15 s
    pre_timeout = max(timeout, 60)           # reads only
    solution_timeout = max(timeout, 60)      # writes a tool
    oracle_timeout = max(timeout, 240)       # three reports and two rounds of pulls and builds (a few seconds)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: eight records of three images, the stores hold each image once, BuildKit holds the built image's blobs again
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: imgreport's numbers on the node as it is and after two more rounds of pulls and builds, the node unchanged
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
