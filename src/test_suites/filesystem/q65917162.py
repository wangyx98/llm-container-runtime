"""
SO-65917162: "How does OCI/runc system path constraining work to prevent remounting such paths?"

In a container (every capability, no seccomp/AppArmor) a child user + mount + PID namespace cannot mount a new proc on /proc;
with Docker's systempaths=unconfined (BOTH maskedPaths and readonlyPaths empty) it can. The thread's own answer: the sub-mounts
that runc puts below /proc are inherited, as locked mounts, by a mount namespace owned by a child user namespace, and the kernel
does not let proc be mounted over them. Measured here (runc 1.1.12): default spec EPERM; only readonlyPaths emptied EPERM (the
asker's belief); only maskedPaths emptied EPERM; both emptied OK (self pid 1, pids [1, 2]); without a user namespace the
mount works in the bad container too (it is not a missing CAP_SYS_ADMIN).

Setup: runc 1.1.12, rootfs with init and probe (the question's unshare -Umpfr + mount proc, with a JSON report), the bad bundle,
newct, the running container closedboxx.

Task: write /var/lib/bench65917162/mkct NAME: a container from the bad bundle in which probe succeeds, otherwise unchanged
(capabilities, mounts, devices, namespaces, rootfs: not privileged).

Oracle (nothing is taken from what the solution says): three random names; the lab's own probe is run in the container (self pid
1, pids [1, 2]); runc's state shows the same configuration as a control container from the untouched bundle except the masked
and read-only paths; the control still refuses; the container has no user namespace of its own; no lab file (the bad bundle
included) changed.
"""



from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/filesystem/q65917162/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "filesystem" / "q65917162"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q65917162",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)      # containers, mounts
    setup_timeout = max(timeout, 300)        # the first run downloads runc (10 MB); later runs take 3 s
    pre_timeout = max(timeout, 60)           # reads only
    solution_timeout = max(timeout, 60)      # writes a tool
    oracle_timeout = max(timeout, 120)       # three containers and three controls (a few seconds)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the bad container refuses (EPERM), the plain probe and a throwaway unconfined container succeed
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: mkct makes containers in which probe mounts proc, otherwise as the control, for three new names
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
