"""
SO-72990088: "containerd pass incorrect hostPath from host"

A deployment mounts a configuration file from the host (hostPath) into its container; on containerd (K8s 1.21, containerd 1.5) the container is not created: `error mounting
"/run/containerd/io.containerd.runtime.v2.task/k8s.io/.../services-config.json" to rootfs at "/app/config/local.json": stat <same path>: no such file or directory`. No answer, no
manifest. Measured here (CRI of containerd 1.6.21 called with crictl, runc 1.1.12; there is no arm64 release of containerd 1.5; no Kubernetes): the path of that shape (the runtime's
task directory, the container's id, then the path) is what runc makes of a RELATIVE source of a bind mount: it joins it to the container's bundle directory; an absolute path of the
file starts the container with the same inode; a symlink to the file, or a symlinked directory in the path, work; a dangling symlink fails earlier ("failed to mkdir ... file exists");
an absent file under an absolute path starts the container with a DIRECTORY at the target; a path with a trailing slash fails at "not a directory".

Setup: a private containerd with the CRI plugin, local sandbox image, one offline image (a static program that stays); the deployment (pod.json, ctr.json, launch.sh, which hands the files
to the CRI as they are) with three mounts: the configuration file (a relative source, as in the failing start), a data directory, a read-only file; an old copy of the configuration elsewhere.

Task: make the Pod svc run with the configuration file mounted from the deployment's own file (not a copy, live), the other mounts unchanged.

Oracle (nothing is taken from what the solution says): the Pod svc exists once and is ready, container main runs; in the container's OCI spec the file is a bind mount of an absolute source whose realpath is
the deployment's file, the other mounts as in ctr.json, no other host mount, same image and arguments; in the container the file has the same device and inode as on the host and the right hash,
a write on the host in place is seen at once, /data and the read-only /etc/extra.conf are right; the lab's files are as setup made them.
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/filesystem/q72990088/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "filesystem" / "q72990088"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q72990088",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containers, shims, mounts
    setup_timeout = max(timeout, 300)        # the first run downloads containerd, crictl and runc (60 MB); later runs take 10 s
    pre_timeout = max(timeout, 120)          # two controls: a Pod each
    solution_timeout = max(timeout, 60)      # edits ctr.json, applies the deployment
    oracle_timeout = max(timeout, 120)       # reads the running container

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the failed start with the question's error (a relative source), controls with an absolute and with an absent path
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the Pod svc runs; the file is the host's own file (spec, inode, hash, live write); the other mounts as before
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
