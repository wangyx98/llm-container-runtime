"""
SO-59812500: "Chroot in Go using syscall is giving error"

The asker's Go "container daemon" (`run` starts itself again in a new UTS namespace, `child` sets the hostname, changes the root with chroot and runs the command) gives a shell that complains
`shell-init: error retrieving current directory: getcwd: cannot access parent directories`. The comments guess that the working directory was not changed after the chroot; the one answer
only says the new root needs /bin, /lib and so on. No rootfs is given, and the code as POSTED already has `syscall.Chdir("/")`. Measured here (Go 1.24.7 in the sandbox; Go 1.13.5, the question's, is
what setup.sh downloads on the VM): the code as posted works with a rootfs of bash, ls, cat and their libraries (`pwd` prints /, no error); the `Chroot` field of `syscall.SysProcAttr` WITHOUT a
`Dir` (the question's other attempt) gives exactly the error: Go does the chroot in the forked child and no chdir, so the working directory stays outside the new root (`/proc/<pid>/cwd` of the
shell is "(unreachable)..." for the host). Other failures differ: a rootfs without the shell gives `fork/exec ...: no such file or directory`, a non-root user `operation not permitted`. This case is an
ADAPTATION (the task says so): the starting daemon is the field variant, the rootfs is below /var/lib/bench59812500, Go is the lab's.

Setup: the Go toolchain (go.dev release, sha256 from go.dev; BENCH_GO_ROOT for a machine without it), a rootfs of this machine's bash, ls, cat + libraries and a random /marker, the daemon's module
(main.go, go.mod) and its binary. Precondition: the daemon as given runs in the rootfs and bash gives the question's error; controls: `cmd.Dir = "/"` and the code as posted both give / without error.

Task: make the command run with the rootfs as root AND as working directory, by the daemon's own Go calls.

Oracle (nothing is taken from what the solution says): the daemon is built again from the module's source, run from two directories with failing shims for chroot, unshare, nsenter and the engines in its
PATH; seen from the host, the shell's exe, root and cwd are the rootfs's bash and the rootfs, its UTS namespace is not the host's; inside: pwd -P = /, the unique marker, no sight of the host's lab,
hostname container; stderr empty, status 0; `run /bin/ls /` lists the rootfs; the rootfs is unchanged and nothing is left in it.
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/filesystem/q59812500/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "filesystem" / "q59812500"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q59812500",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)      # a few processes, two directories
    setup_timeout = max(timeout, 600)        # the first run downloads the Go release (about 100 MB) and unpacks it; later runs take 10 s
    pre_timeout = max(timeout, 300)          # three builds of the daemon (the first fills the Go cache)
    solution_timeout = max(timeout, 180)     # edits main.go, builds it
    oracle_timeout = max(timeout, 300)       # builds the daemon again, three runs

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the daemon as given runs in the rootfs and bash gives the question's getcwd error; controls: `cmd.Dir = "/"` and the code as posted work
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: built again from the source; seen from the host the shell's root and cwd are the rootfs; inside pwd is /, the marker is read, no error
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
