"""
SO-58642878: "k3s ctr images import to different dir"

The asker imports image tars with `k3s ctr images import` (the images are for K3s' Pods) and wants them stored in another directory than K3s' data-dir, because an external disk is mounted and
all the data should be on it. The one answer says there is no native way and offers a symlink; the asker likes it but wants the whole disk used, mounting the disk at the data-dir does not
fit "for some other dependency". Measured here (x86_64, kernel 6.18, cgroup v1, K3s v1.30.5+k3s1 with its embedded containerd 1.7.21-k3s2): `k3s ctr` works in the namespace k8s.io (the CRI's), so
an imported image is usable by a Pod; `ctr images import` has no option for a place; the containerd root is <data-dir>/agent/containerd and K3s passes it on containerd's command line (the generated
agent/etc/containerd/config.toml says "File generated by k3s. DO NOT EDIT" and has no root); K3s has no flag for the containerd root alone, only --data-dir. Moving the root works by a mount, a symlink
or a new data-dir WITH its state (the seed Pod keeps its uid); a new data-dir without it is a new cluster. Pods run offline (hostNetwork, imagePullPolicy Never; the pause image of the lab is imported by
K3s from agent/images). Sandbox adaptations (the task does not need them on a normal machine): without CAP_SYS_RESOURCE runc cannot lower oom_score_adj, so setup adds a config.toml.tmpl that imports
`restrict_oom_score_adj`; the kubelet's eviction thresholds and image GC are set so that the sandbox's full disk and unused imported images do not matter.

Setup: the pinned k3s binary (sha256, amd64 and arm64), `k3sctl` (the unit: fixed arguments + etc/config.yaml with data-dir; stop is what k3s-killall does), a 1 GiB loop ext4 mounted at
/mnt/bench58642878-disk (empty), the seed image (random salt) and the seed Pod. Precondition: the root is on the lab's file system, config.toml has no root, import has no place option, the disk is the lab's
empty loop mount, the seed Pod and image are as recorded; control: an import lands in the old root. Task: put the node's containerd storage on the disk, keep what exists, still true after a restart.

Oracle: the node runs (lab binary); from the host the metadata db the containerd has OPEN, its content store and snapshots are on the disk's device (the lab's loop file); the seed image and Pod (same uid) are
there; a new image (random salt) imported with the lab's `k3s ctr images import` has its layer blob and unpacked layer on the disk and a Pod from it prints its salt; after `k3sctl restart` the same again.
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/filesystem/q58642878/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "filesystem" / "q58642878"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q58642878",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 240)      # the node, its containers, mounts, the loop device
    setup_timeout = max(timeout, 600)        # the first run downloads k3s (66 MB) and unpacks its tools; later runs take 30 s
    pre_timeout = max(timeout, 180)          # one control import
    solution_timeout = max(timeout, 300)     # stops the node, copies its data, starts it again
    oracle_timeout = max(timeout, 600)       # waits for Pods (up to 90 s before and 120 s after the restart), restarts the node

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: containerd's root is on the lab's file system, nothing on the disk; the seed Pod runs; an import lands in the old root
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the open metadata db, content store and snapshots are on the disk; seed and new image + Pod work; the same after the node's restart
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
