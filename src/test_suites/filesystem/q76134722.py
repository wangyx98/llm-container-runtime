"""
SO-76134722: "smart way to delete unused images in containerd except a few in aws eks 1.24" (an EKS node with 139 images carrying the tag prefix dev-, some used by running containers;
the asker wants to prune only the idle images of a registry or with the prefix dev-, as `docker image prune --all` did; `crictl rmi --prune` is said to have crashed the node because it
also deletes the images that paused containers need; no answer; comments: EKS cleans images by itself, a link to an AWS knowledge-center article).

Adaptation (stated in task.txt): the clean-up on a private containerd node (CRI on, the sandbox image pinned), not a reproduction of the EKS incident (on this stack `crictl rmi --prune`
keeps the running containers' images and the pinned sandbox image; it deletes every other idle image, the keep list included). The node has 14 images with 15 names in the CRI's
namespace k8s.io: idle images with a dev- tag (one of them with a second, stable name), two images on the keep list, two images used by a running pod (dev- tags too), the pinned sandbox
image (dev- tag too), idle images without a dev- tag (one whose repository name contains dev-), and an image with a dev- tag in the namespace bench-other. Every image has blobs of its own.

Setup: images built offline (OCI layout), private containerd with its own socket, root and a version-3 configuration, one pod with two containers, the keep list, node-ctr and
node-crictl, state (hashes, the containerd process, ids of the pod and containers, image ids and own blobs). precondition.sh: the images, which are used and which idle, the pinned image,
the blobs; control: a scratch name of the shared image is added and removed with ctr (the image and its other name stay). The task: remove the idle dev- images except the keep list.
Oracle (dynamic): node unchanged (files, containerd process, pod, containers); through the CRI every idle dev- image is gone (no untagged leftover) and its own blobs are
reclaimed (up to 45 s); the shared image only lost its dev- name; every other image has the same names and blobs; the image of bench-other stays; a new pod and a new container from
every image that stays run; the node is unchanged afterwards. `crictl rmi --prune`, `ctr images rm` of every name with dev-, removal by image id, `ctr images rm` that leaves untagged images,
names matched in the repository path and all-namespace loops fail.

Taxonomy category: Filesystem, Mount & Storage
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/filesystem/q76134722/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "filesystem" / "q76134722"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q76134722", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 300)        # a first run may install busybox-static
    pre_timeout = max(timeout, 120)
    solution_timeout = max(timeout, 180)
    oracle_timeout = max(timeout, 240)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the images, what is in use, what is idle, what is pinned, a control of the tools
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: idle dev- images gone with their blobs, everything else untouched, the node still makes pods and containers
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
