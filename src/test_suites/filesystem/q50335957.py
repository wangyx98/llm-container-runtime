"""
SO-50335957: "Bind mount /proc or /dev in container got operation not permitted error"

A runc container with user, PID and mount namespaces gets the host's /proc as a read-only recursive bind mount (rbind,ro) at /test-proc; on Ubuntu 16.04 `runc run` stops with EPERM while mounting,
other distributions are fine. Cause (measured here with runc 1.1.12 and strace): a bind mount copied into a mount namespace owned by a child user namespace has its nosuid/nodev/noexec/atime flags LOCKED;
the read-only remount (MS_REMOUNT|MS_BIND|MS_REC|MS_RDONLY) that does not repeat them counts as clearing them and gets EPERM. Where the host's /proc is plain `rw,relatime` the remount is accepted; where systemd
mounts it `rw,nosuid,nodev,noexec,relatime` (Ubuntu) it is not. The failure needs no old runc or kernel; what decides is the flags of the host's /proc. This case is an ADAPTATION (the task says so): runc 1.1.12
(pinned, sha256) with a launcher that runs it in a private mount namespace where /proc is remounted with nosuid,nodev,noexec (on an Ubuntu host that is no change; the machine's own mounts are never touched).
Measured options (with those flags on /proc): rbind,ro,nosuid,nodev,noexec ok; rbind,rro ok; rbind,ro,nosuid / ,nodev only / bind,ro / rbind,ro: EPERM; rbind without ro: starts but writable.

Setup: the pinned runc, the launcher, a rootfs with one static program (probe), a bundle whose config.json is runc's default spec reduced for a user namespace (no /sys, no cgroup mounts, no limits) with namespaces
pid, mount, user, uts, ipc, uid/gid 0->100000/65536 and the mount {/test-proc, bind, /proc, [rbind, ro]}; the original config is kept in the root-only state dir.

Task: make the bundle start with /test-proc the host's /proc, rbind and read-only, all namespaces and the rest of config.json unchanged.

Oracle (nothing is taken from what the solution says; the oracle starts its own container from the solver's config.json): runc, the launcher and the rootfs unchanged; config.json equal to the original except the /test-proc
mount, which is still a bind of /proc with rbind and not rw; the container starts and runs, pid 1 in its namespace; from the host its user, PID and mount namespaces differ from the host's, uid_map is the bundle's;
the /test-proc mount in its mountinfo is procfs, root "/", read-only; through it the container reads the command line of a host process the oracle started (a fresh procfs would not show it); a write-open of a file
there is refused with "Read-only file system".
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/filesystem/q50335957/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "filesystem" / "q50335957"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q50335957",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)      # containers, mounts, cgroups
    setup_timeout = max(timeout, 300)        # the first run downloads runc (10 MB); later runs take a few seconds
    pre_timeout = max(timeout, 120)          # two short containers
    solution_timeout = max(timeout, 60)      # edits config.json
    oracle_timeout = max(timeout, 120)       # one container

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the bundle as it is fails with the question's mount error; the same with nosuid,nodev,noexec added starts
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the container starts from the solver's config.json; /test-proc is the host's /proc, rbind, read-only; namespaces and the rest unchanged
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
