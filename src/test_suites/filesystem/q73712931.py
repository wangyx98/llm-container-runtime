"""
SO-73712931: "containerd - image might be filtered out message"

A docker-save archive (made elsewhere, pulled from quay there) is imported offline: containerd 1.6.8 says "image might be filtered out", 1.5.13 says a content
digest is not found; the answers guess platform filter / incomplete archive / version difference, and --all-platforms does not bring back blobs that are not in
the file. Measured here (containerd 1.6.8 and 1.5.13 amd64; arm64 is not run): ONE cause explains both messages for a docker save of the other architecture: the
plain import of a classic archive whose config is for another platform says "image might be filtered out" on 1.6.8 and "failed to resolve rootfs: content digest
...: not found" on 1.5.13; --all-platforms imports it (an image that cannot run here: exec format error). An archive of this platform with a blob left out is
another matter: "not found" on both (a layer: "failed to get reader from content store"); a blob whose content does not fit its name is dropped by the importer and
is missing in the same way; an OCI index without this platform: "no match for platform in manifest"; an index with the host platform complete imports plainly even if
the other platforms' blobs are not in the file, --all-platforms needs every listed manifest (not the other platforms' configs and layers).

Setup: a private containerd 1.6.8 (no CRI) with runc, two archives of one image app (a static program printing "marker <token>"): app-foreign.tar (docker save, the other
architecture) and app-multi.tar (OCI layout, both architectures), offline.

Task: (1) write /var/lib/bench73712931/archreport ARCHIVE: JSON of format, name, platforms (manifest, config, layers, missing blobs, a blob counts only if it hashes to its
name), verdict (importable / no_host_platform / incomplete), and what plain import, --all-platforms import and a run would do; (2) the image in the namespace default for this
host's platform, from the archives, blobs verifiable, running its marker.

Oracle (nothing is taken from what the solution says): 15 archives made by the oracle with random contents (the two of the lab, a docker save of each platform, an OCI layout
with every kind of gap, a corrupt blob, a path with spaces): the report equals what the oracle knows and what the node really does (plain import, --all-platforms, run), and the node
is unchanged by the tool; the image is the host manifest of app-multi.tar, its blobs are hashed, and a container prints the host layer's marker.
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/filesystem/q73712931/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "filesystem" / "q73712931"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q73712931",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containers, shims, mounts
    setup_timeout = max(timeout, 300)        # the first run downloads containerd and runc (50 MB); later runs take 10 s
    pre_timeout = max(timeout, 120)          # three imports and two runs
    solution_timeout = max(timeout, 60)      # writes a tool, imports an image
    oracle_timeout = max(timeout, 480)       # 15 archives: the tool, two imports and a run of each

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the question's situation measured on the node (filtered out / --all-platforms cannot run / missing blob / complete archive runs)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: archreport against the node's real imports and runs; the image for the host platform, blobs hashed, marker printed
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
