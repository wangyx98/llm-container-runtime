"""
SO-65298023: "Mysql container errors, socket creation erros"

`ctr run` of the official mysql image (8.0.22): the entrypoint switches to the user mysql, initialises the data directory, then the server cannot make the lock files of /var/run/mysqld/mysqlx.sock and mysqld.sock
("Unable to start server"). No real answer (a sql_mode comment; a later answer mounts a host directory and needs `chmod 777`). Measured here (containerd 1.6.21, runc 1.1.12): `ctr run` builds the container
from containerd's DEFAULT OCI spec, which has an empty root-owned tmpfs on /run (Docker's has none); the Debian image's /var/run is a symlink to /run, so the image's /run/mysqld (owned by mysql, uid 999) is hidden
and the server, as 999, cannot create anything in /run. The /context bind mount of the question is not involved. A host directory needs the CONTAINER's numbers (999:999), not the host's mysql user (hence the
777 of the answer); a tmpfs mount with uid=999,gid=999 does the same without the host. The runtime keeps the state of a `ctr run` container under /run/containerd/runc/<namespace>/<name> (the machine's, not the
node's): the node's ctr uses a namespace of the case and cleanup removes that directory.

ADAPTATION: the real image is not available offline (Docker Hub's token host is refused in the sandbox; 8.0.22 has no arm64 build). The image is a stand-in with the official layout (/var/run -> ../run, /run/mysqld and
/var/lib/mysql owned by mysql 999:999, entrypoint dropping root to mysql); its "mysqld" makes the same lock files and sockets with the same error lines and serves a small line protocol (AUTH, INSERT, SELECT, COUNT)
on the Unix socket, rows persisted in /var/lib/mysql; mysqlx is not served. A stale lock of a killed process is replaced, as mysqld does.

Task: the container sql1 running again as the asker ran it (-d, same image, password, /context), the server as mysql, not privileged, /run/mysqld in it owned by 999:999 and not world-writable, the socket usable
also after kill and start.

Oracle (nothing is taken from what the solution says): a NEW container sql1 of the lab's image (digest), the asker's password and /context mount kept, bounding capabilities without CAP_SYS_ADMIN (not privileged);
its task runs as uid 999; /run/mysqld is a bind or tmpfs mount, 999:999, not world-writable; through the real Unix socket a wrong password is refused, the right one accepted, random rows are written and read
back; after the task is killed and started again the rows are there, the socket answers and new rows work; the node's programs and containerd process are those of setup.
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/filesystem/q65298023/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "filesystem" / "q65298023"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q65298023",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containers, shims, mounts
    setup_timeout = max(timeout, 300)        # the first run downloads containerd, crictl and runc (60 MB); later runs take 10 s
    pre_timeout = max(timeout, 120)          # a control container (starts, answers, removed)
    solution_timeout = max(timeout, 60)      # removes the old container, runs the new one
    oracle_timeout = max(timeout, 120)       # socket calls, kill and start

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the first run's errors, the tmpfs on /run in the spec; the control with a 999:999 directory starts and answers
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: a new sql1 as mysql, not privileged, /run/mysqld mounted 999:999 and not world-writable; rows through the Unix socket, also after kill and start
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
