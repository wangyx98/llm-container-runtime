"""
SO-65357072: "Kubernetes: Increase the size of OverlayFS / containerd runtime volumes in K3s"

A K3s node runs into disk pressure; `df` shows the same `overlay` row (6 GB, 70% to 90%) for the rootfs of every container; the asker wants a bigger overlay or to delete the task directories by hand. The
answer (the asker's own): `crictl rmi --prune` for the unused images, kubelet image-gc thresholds, or a bigger /var. Measured here (containerd 1.6.21, crictl 1.24.2, runc 1.1.12, no Kubernetes; a loop-backed
ext4 under containerd's root): the overlay row reports the file system of the upper directory (the loop file system), the same numbers for every container, they are not to be added; a write in a
container's root file system gets ENOSPC when that file system is full; `crictl rmi ID` frees the layers (content and unpacked snapshot, twice the size of an image) once containerd's garbage collection
has run; `ctr images rm NAME` leaves the id record and frees nothing; `crictl rmi --prune` also removes the unused image that must stay; removing blobs or snapshot files by hand frees space and leaves
images incomplete (`ctr images check`). Growing the file system online (truncate, losetup -c, resize2fs) is refused in the sandbox (EPERM), so only the freeing route is verified; the oracle judges the
result and would accept a grown file system too.

Setup: a private containerd whose root is a 200 MB ext4 loop file system, offline images with random layers (app/web in use, keep/tools protected, old/a to old/d unused), Pod web with 15 MB of its own data.

Task: at least 90 MB free and 60 MB writable by the workload, with the workload, its data, the protected, sandbox and in-use images intact and every remaining image complete and startable; same containerd, same file system.

Oracle (nothing is taken from what the solution says): the programs and the containerd process are those of setup; the root is still the loop mount of setup (device, backing file); the workload's container is the same, running since
the same moment, its data hash unchanged; app/web, pause and keep/tools are there with their ids; `ctr images check` shows every image complete and a container can be made from each; the file system has 90 MB free
(polled for the garbage collection) and the workload writes and reads back 60 MB.
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/filesystem/q65357072/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "filesystem" / "q65357072"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q65357072",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containers, shims, mounts
    setup_timeout = max(timeout, 300)        # the first run downloads containerd, crictl and runc (60 MB); later runs take 10 s
    pre_timeout = max(timeout, 120)          # one exec call
    solution_timeout = max(timeout, 60)      # removes images
    oracle_timeout = max(timeout, 120)       # a container per image

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the loop file system is nearly full, the overlay root reports its numbers, the workload gets ENOSPC at 60 MB
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: free space, a 60 MB write by the workload, the workload, its data and the kept images intact, every image complete
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
