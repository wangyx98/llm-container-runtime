"""
SO-63752123: "joined process cannot write ns_last_pid of the container"

A host process that joins the namespaces of a runc container and writes /proc/sys/kernel/ns_last_pid gets "Read-only file
system"; the thread has no explanation (the answer: run the container --privileged). Measured here: runc mounts /proc/sys
read-only in the MOUNT namespace of the container, so a writer that joined that namespace gets EROFS; ns_last_pid acts on the
PID namespace of the writing process, so a process that joined only the PID namespace (nsenter -p) and keeps the host's
mount namespace writes it (the host's /proc/sys is read-write) - no --privileged and no change of the container.

Setup: runc 1.1.12, a static rootfs (init, wr, cat, ls, id), two containers from runc's default spec, `newct`.

Task: write /var/lib/bench63752123/nsfork CONTAINER VALUE: write VALUE into that container's ns_last_pid, start a child in its PID
namespace (pid VALUE+1 there) that stays 2+ seconds, print JSON with the container, the value, the child's pid in the
container and on the host.

Oracle (nothing is taken from what the solution says): three NEW containers and random values; the host's /proc shows the child
with NSpid [host pid, VALUE+1] in the container's PID namespace; the host's own ns_last_pid is not written; the container's
init and mounts are as before; nothing is left in the containers after the children ended; the host-side files are unchanged.
"""



from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/filesystem/q63752123/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "filesystem" / "q63752123"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q63752123",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)      # containers, mounts
    setup_timeout = max(timeout, 300)        # the first run downloads runc (10 MB); later runs take 5 s
    pre_timeout = max(timeout, 60)           # reads only
    solution_timeout = max(timeout, 60)      # writes a tool
    oracle_timeout = max(timeout, 180)       # three new containers, three runs of the tool, a wait of 5 s

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: /proc/sys is read-only in the containers; joining the mount namespace gives EROFS
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: nsfork writes the container's ns_last_pid and forks a child of pid VALUE+1 in its PID namespace, for three new containers
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
