"""
SO-75697723: "How to build an image of a running container with ContainerD runtime"

A container of a GKE node (containerd, kubelet/CRI) has been changed from inside; the asker wants a new image from it, as `docker commit` would. The
thread's own answer: nerdctl (create, commit, push). Measured here (containerd 1.6.21, runc 1.1.12, nerdctl 1.3.1, crictl 1.24.2): `nerdctl --namespace
k8s.io commit <CRI container id> REF` works on a CRI container and keeps it running (it pauses and unpauses it); the new image is the base layers plus one
gzip layer with the container's added and changed files, a whiteout for the removed file, and the CRI's mount points (not the volume's data); BUT the new
image's Entrypoint and Cmd are the BASE image's, not what the container really runs (the pod spec's args replaced Cmd): the image only keeps them in its
history; `-c ENTRYPOINT` / `-c CMD` fixes it (the container's process.args from `crictl inspect`).

Setup: containerd with the CRI plugin, a local sandbox image, an offline one-layer image (static app), two Pods on the host network, each with its own pod-spec
args and a volume at /data; each program writes its data once (random out.bin, an app.conf line, vol.bin on the volume, stale.txt deleted) and stays quiet.

Task: write /var/lib/bench75697723/commitctr CONTAINER_ID NEW_REF: a new image in k8s.io from the running CRI container (base layers + one layer, volume left
out, entrypoint = the container's args), source untouched.

Oracle (nothing is taken from what the solution says): run for the lab's src1 and for a Pod the oracle starts with random arguments and data: the image
exists and is new; base layers unchanged + one layer with out.bin (same hash) and the whiteout, no vol.bin; Entrypoint + Cmd = the source's process.args; no
container or Pod made or removed; the source is the same process with the same files; a NEW Pod from the image (no args given) runs the same argv, holds the
same files (hashes), not stale.txt, an empty /data, and shares no writable layer with the source; the decoy Pod is unchanged.
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/filesystem/q75697723/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "filesystem" / "q75697723"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q75697723",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containers, shims, mounts
    setup_timeout = max(timeout, 300)        # the first run downloads containerd and runc (70 MB); later runs take 10 s
    pre_timeout = max(timeout, 60)           # reads only
    solution_timeout = max(timeout, 60)      # writes a tool
    oracle_timeout = max(timeout, 240)       # two commits and two new Pods (a few seconds)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: two CRI containers with pod-spec args, nerdctl sees them, a plain commit keeps the base Cmd
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: commitctr for the lab's container and for one made by the oracle; image, new Pod, source untouched
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
