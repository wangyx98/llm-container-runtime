"""
SO-70570825: "How to create a CriCtl pod with a volume mount?"

The asker puts an OCI-style `mounts` list (destination, type, source, options) into the pod-config.json of `crictl runp`; `crictl inspectp` shows no mount. No answer. Measured here (CRI of
containerd 1.6.21 called with crictl 1.24.2, runc 1.1.12): `runp` exits 0 and ignores the unknown field (OCI-style or with the CRI's own key names): the sandbox's OCI spec has only /proc, /dev,
/dev/shm, /etc/resolv.conf and `inspectp`'s config shows no mounts. The CRI's PodSandboxConfig has no mount field at all; mounts are the `mounts` of the container's ContainerConfig
(`host_path`, `container_path`, `readonly`) and are real bind mounts (same inode, read-only refuses writes). The original "mount in the sandbox" therefore cannot be met: this case is an ADAPTATION
(the task says so) that asks for the mounts in the Pod's workload container.

Setup: a private containerd with the CRI plugin, local sandbox image, one offline image (a static program that stays); the deployment (pod.json with the asker's `mounts`, ctr.json without mounts,
launch.sh: runp, create, start as given) applied: Pod svc runs without the mounts; two host directories with random files (share, data).

Task: make the Pod svc's container main have the share directory at /docker read-only and the data directory at /data read-write, as real bind mounts; one Pod, one running container.

Oracle (nothing is taken from what the solution says): the Pod svc exists once and is ready, one container main runs (same image and arguments); in its OCI spec /docker and /data are bind mounts of
the lab's directories (ro / rw), no other host mount; in the container both are the host's directories (device and inode), /docker shows the files with the right hashes, a file made later on the
host is seen at once and a write in /docker is refused; in /data a file made on the host is seen in the container and one made in the container is on the host; the lab's files are as setup made them.
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/filesystem/q70570825/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "filesystem" / "q70570825"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q70570825",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containers, shims, mounts
    setup_timeout = max(timeout, 300)        # the first run downloads containerd, crictl and runc (60 MB); later runs take 10 s
    pre_timeout = max(timeout, 120)          # two controls: a Pod each
    solution_timeout = max(timeout, 60)      # edits ctr.json, applies the deployment
    oracle_timeout = max(timeout, 120)       # reads the running container

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: runp accepted the `mounts` of pod.json and ignored them; controls: ContainerConfig mounts are real bind mounts, CRI-style mounts in pod.json are ignored too
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the Pod svc runs; /docker (ro) and /data (rw) are the host's own directories (spec, inode, hashes, live changes, both ways)
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
