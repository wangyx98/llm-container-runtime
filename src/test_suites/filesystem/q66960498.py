"""
SO-66960498: "Purge Kubernetes Image Cache on containerd runtime with daemonSet"

A DaemonSet that mounts containerd's socket should purge the node's image cache on a cadence; inside it `ctr image ls` and `nerdctl` show nothing and no error. The only answer (from the comments):
the tools use containerd's `default` namespace, Kubernetes' images are in another one (`k8s.io`), crictl is already bound to it. Measured here (CRI of containerd 1.6.21, crictl 1.24.2, runc 1.1.12; no
Kubernetes): in a container with the node's socket bind-mounted `ctr -a <socket> images ls` answers with nothing and exit status 0 in `default`, `-n k8s.io` and crictl list the images; `ctr -a unix://...`
is refused (a path, not a URL); `ctr images rm NAME` removes one record and leaves the image in the CRI as `<none>` (its id record stays), `crictl rmi ID` removes the image with all its names;
`crictl rmi` of a name that is gone fails (a job must not depend on its status); `crictl rmi --prune` removes every image without a container, also outside any scope. The garbage collection of the node is
left at containerd's default (an image removal waits for it).

Setup: a private containerd with the CRI plugin, local sandbox image, offline images (scratch/busy in use, scratch/old:1 and :2 unused, keep/data unused, app/web in use, the tools image with ctr, crictl and
the libraries ctr needs); Pods web, jobs and purger (the node's socket mounted in the purger's container). The "DaemonSet" is a CRI Pod: an ADAPTATION, said so in task.txt.

Task: the executable job /var/lib/bench66960498/job/purge-images.sh, run once: the unused images of the scope scratch/ gone completely, everything else kept, work done through the purger's container, harmless
and exit 0 when run again.

Oracle (nothing is taken from what the solution says): same containerd process, same Pods and containers all running; the images are exactly the expected set (ids and tags, no untagged leftover, k8s.io
records too); the oracle brings scratch/old:3 and keep/other:1 and runs the job twice with the node's ctr and crictl replaced by logging shims: the first run purges old:3 only, the second changes nothing and
exits 0; the shim log shows only looking-around calls of the node's crictl (no ctr, no image calls) and at least one exec into the purger's container.
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/filesystem/q66960498/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "filesystem" / "q66960498"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q66960498",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # containers, shims, mounts
    setup_timeout = max(timeout, 300)        # the first run downloads containerd, crictl and runc (60 MB); later runs take 10 s
    pre_timeout = max(timeout, 120)          # three exec calls
    solution_timeout = max(timeout, 60)      # writes and runs the job
    oracle_timeout = max(timeout, 120)       # three runs of the job, a few seconds each

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: ctr in the purger's container shows nothing in `default`; the node's images and containers are those of setup
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the images after the job, two more runs with new images (shims log the calls), the workloads untouched
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
