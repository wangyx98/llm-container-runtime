"""
SO-75294704: "Kubernetes 1.24 | Containerd | Allow to run devices inside the container without
the --privileged flag?" -- a job gets an attached volume as a raw block device (volumeDevices,
/dev/xvdf) and runs `lsblk -fnr -o NAME,FSTYPE /dev/xvdf`; the file system types come out empty
and strace shows `open("/dev/nvme1n1") = -1 ENOENT`. Only `privileged: true` unmasks /dev and
/sys; the asker wants the least privilege, like docker's --device.

The cause: lsblk takes the major:minor of the node it was given, finds the KERNEL device through
/sys/dev/block/MAJ:MIN and opens it by its kernel name in /dev (nvme1n1, here loopN); the
container has the node under the other name only. The fix is to give the container that one
device under its kernel name (docker --device; here ctr run --device), not privileged and
without extra capabilities.

Modern adaptation: containerd with ctr, a loop device with an ext4 file system instead of an EBS
volume, a static program /scan that behaves like lsblk's probing (so the case needs no lsblk or udev
in the image). Nothing is simulated: the three controls of precondition.sh are real containers.

Case design: setup.sh makes the volume and a decoy disk (loop devices), the administrator's alias
node /dev/bench75294704-vol (the kernel name is not in the task), imports the image into the
namespace bench75294704. precondition.sh: three throw-away containers report ERROR stat (no
device), ERROR open /dev/loopN (alias only) and OK loopN ext4 LABEL (privileged). The solution
starts the container bench75294704-scan. oracle.sh runs helpers/verify.py: running task of the
lab's image and program (sha of /proc/PID/exe), CapEff within a plain container's, no block node for
another device in the container's /dev, and /scan reads two NEW labels (tune2fs on the host +
SIGUSR1) through the container's own view.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/isolation/q75294704/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Identity, Privilege & Isolation
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/isolation/q75294704/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "isolation" / "q75294704"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q75294704",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup (a compile), solution and oracle (a few containers)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: three real containers: no device -> ERROR stat, the alias alone
    #    -> ERROR open /dev/loopN, privileged -> OK
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=long_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the container bench75294704-scan runs, is not privileged, has only
    #    the volume among its device nodes, and /scan reads two new labels of the volume
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
