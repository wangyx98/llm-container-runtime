"""
SO-56996594: "Running OCI Containers as regular users" -- a shared machine where users
must pull, manage and run OCI images without being handed a rootful daemon (access to
the system Docker/containerd socket is root on the host). The accepted answer is
"use a rootless runtime with subuid/subgid" (podman); the case asks for the same
thing on the containerd stack: rootlesskit + containerd as a systemd USER service,
an image pulled by digest from a registry, a script that runs it, and the same
again after the service is restarted and the registry is gone.

Case design: setup.sh makes the user bench56996594 (no sudo, a subuid/subgid
range, lingering systemd user manager), builds two OCI images (they differ by a
random salt: "v1" is the pinned one, "latest" the decoy) from one static program
(/marker NONCE prints sha256(salt + NONCE), its uid/gid/pid, and stays alive 4 s)
and serves them from a small registry on 127.0.0.1:35996. precondition.sh proves
the state (nothing of the user's runs; the user cannot open any rootful socket;
rootlesskit gives it maps 0 -> user and 1.. -> its range). The solution has to
produce the user service bench56996594-containerd.service, the pull of the pinned
digest, and /home/bench56996594/bin/run-marker.sh NONCE OUTFILE. oracle.sh
(helpers/verify.py) checks, from /proc, the registry's log and the user's files:
no group/sudo/socket shortcut into a rootful daemon; the service is active and
not root; the pinned (not the latest) image was pulled; while the script runs the
program is a process of the host that is not root, in a user namespace whose
maps send root to the user and use the user's subordinate range, under a
non-root shim; its output has the fresh nonce and the right hash; then the
registry is stopped, the service restarted, and a second run passes again.

Sandbox note: this sandbox has no systemd, rootlesskit or uidmap; the case was
verified with sandbox-only stand-ins (outside the repo) for loginctl,
`systemctl --user`, rootlesskit and newuidmap. The real tools run on the VM.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/isolation/q56996594/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Identity, Privilege & Isolation
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/isolation/q56996594/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "isolation" / "q56996594"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q56996594",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup makes a user, two images and a registry; the oracle runs the script twice and restarts the service

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: prove the state -- the registry serves the pinned
    #    image, the user exists without any way into a rootful daemon, nothing of the
    #    solution exists, and rootlesskit gives the user the maps 0 -> user, 1.. -> its range
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=long_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the rootless chain from the host: service,
    #    pinned image pulled, program not root and in a user namespace on the user's
    #    subordinate range, right hash for a fresh nonce, and again offline after a restart
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
