"""
SO-76608572: "/sys/fs/cgroup/cpuset.cpus Not Found After Enabling Privileged Mode In
Kubernetes" -- on a cgroup v2 node (Kubernetes 1.26.2, containerd 1.6.20, kernel 5.15)
a pod with a CPU constraint reads its CPUs in /sys/fs/cgroup/cpuset.cpus; the same pod with
`privileged: true` has no such file. The asker needs the CPUs of the pod (DPDK).

The cause: a normal pod has a PRIVATE cgroup namespace, so the root of its /sys/fs/cgroup is its
own cgroup (which has cpuset.cpus); a privileged pod shares the HOST's cgroup namespace and
sees the host's root cgroup, which has no cpuset.cpus (only cpuset.cpus.effective, all CPUs of
the machine). The pod's real cgroup is a directory below it, named by the `0::` line of
/proc/PID/cgroup; its cpuset.cpus.effective is the allocation.

Modern adaptation (the original combination cannot be pinned in a harness): bare runc
containers on the host's own cgroup v2 kernel. "Normal" = a spec with a cgroup namespace
entry, "privileged-style" = no cgroup namespace entry and a read-write cgroup mount; both with
a real cpuset constraint (linux.resources.cpu.cpus). Nothing is simulated by an empty file.

Case design: setup.sh checks cgroup v2 with the cpuset controller and >= 2 CPUs, builds the
rootfs (one static program) and the base runc spec. precondition.sh runs the control: two real
containers with the SAME constraint, prints cgroup ns inodes, the host's /proc/PID/cgroup, the
mountinfo root of the container's /sys/fs/cgroup, cpuset.cpus.effective and Cpus_allowed_list, and
requires cpuset.cpus at the root of the private view and none in the host-namespace one. The
solution writes /tmp/bench76608572/cpu-report.sh TARGET OUTPUT_FILE (TARGET = host PID or runc
container ID). oracle.sh runs helpers/verify.py: four NEW containers (random CPU sets, cgroup
paths, IDs; private/host namespace; PID/ID; two pinned so Cpus_allowed_list is smaller than the
cgroup's CPUs) and compares each report with what the lab knows: the cgroup directory (and the
cgroupsPath it gave), the cpuset of the cgroup, the directory the container sees as
/sys/fs/cgroup, and whether cpuset.cpus is there; afterwards the containers must be untouched.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/isolation/q76608572/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Identity, Privilege & Isolation
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/isolation/q76608572/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "isolation" / "q76608572"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q76608572",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup (a compile), solution and oracle (four containers)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the same real CPU constraint in a private and in a host cgroup
    #    namespace; cpuset.cpus is at the root of the first view and missing in the second
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=long_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the script's report for four new containers against what the
    #    lab knows (cgroup directory, real CPU set, both views); the containers untouched
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
