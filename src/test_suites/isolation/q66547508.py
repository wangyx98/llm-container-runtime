"""
SO-66547508: "How to properly run a container with containerd's ctr using
--uidmap/--gidmap and --net-host option" -- the asker wants root of the
container to be an unprivileged host user AND the host's network namespace
(to reach services on the host's loopback). `ctr run --uidmap .. --gidmap ..
--net-host` fails with "operation not permitted" at the sysfs mount. The cause is
in the kernel: sysfs may only be mounted by a user namespace that owns the
network namespace it describes; with the host's network namespace the mount at
/sys is refused. The fix is to not mount sysfs: leave /sys out, or bind the
host's /sys read-only (a bind mount is allowed; ctr's flags cannot express
this, so the case is built on a bare runc bundle).

Case design: setup.sh builds the bundle (a static program /app, rootfs owned
numerically by host 5000:5000 -- a mapped root cannot create /proc in a rootfs
owned by host root), a host service on 127.0.0.1 that sends a nonce, and a
data dir owned by 5000. config.json is the asker's: user namespace 0 -> 5000
(4999 ids), no network namespace, default mounts. precondition.sh proves the
symptom with three controls (private network + mapping starts; host network +
no mapping starts; host network + mapping fails with the sysfs error).
oracle.sh checks, in order: the container runs; its program and arguments are
the bundle's; maps start with 0 5000, a user namespace of its own, the process
belongs to 5000:5000 on the host; its network namespace is the host's; /sys is
absent or a real read-only sysfs; and after the lab changes the nonce the
container's program writes it to /data/state as uid=0 gid=0 (no replay, no
fake file).

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/isolation/q66547508/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Identity, Privilege & Isolation
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/isolation/q66547508/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "isolation" / "q66547508"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q66547508",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: prove the state -- the bundle and the host service are
    #    in place, nothing runs, and the three controls behave as described
    #    (the asker's combination fails with the sysfs error)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the container runs with the user namespace
    #    (0 -> 5000) AND the host's network namespace, /sys is absent or the host's
    #    read-only sysfs, and its own program writes the new nonce to /data/state
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
