"""
SO-72968351: "How to run ctr or crictl commands when k3s in rootless mode" -- K3s runs rootless
and its Pods run, but `ctr`/`crictl` of the host time out on /run/k3s/containerd/containerd.sock
and the asker wants to import and export images by hand. The cause: in rootless mode the K3s
containerd runs in the mount namespace that rootlesskit makes (user namespace + a /run of its
own), so its socket does not exist on the file system of a normal session; the images of the
Pods are in the containerd namespace k8s.io, not in `default`. The way in is to run the client
inside rootlesskit's child namespaces (nsenter -U --preserve-credentials -m -t CHILD_PID ...),
with the PID and the socket address looked up at every call (the PID changes at every restart).

Modern adaptation (reported as such): no K3s binary. The runner is containerd 2.x with the CRI
plugin on, started by rootlesskit as a systemd USER service of the user bench72968351, with the
socket at /run/k3s-TOKEN/containerd/containerd.sock (TOKEN random per setup, only inside the
child's mount namespace), a stub CNI plugin (the Pods only need a network namespace) and the
delegation of cpu/cpuset/io/memory/pids to the user manager that rootless K3s documents.

Case design (increment on isolation/q56996594, whose user/rootlesskit/uidmap setup it reuses):
setup.sh makes the user and the runner and, through helpers/lab.py, imports a pause image and a
SEED image (random salt) into k8s.io and a DECOY with the same name and another salt into
`default`. precondition.sh shows the symptom (host ctr: no socket / refused), that nothing named
k3s exists on the host, and a CONTROL: through the lab's own nsenter an image is imported and a
Pod really runs. The solution leaves two wrappers, /home/bench72968351/bin/ctr-k3s and
crictl-k3s. oracle.sh runs helpers/verify.py: no group/sudo/rootful-socket shortcut, runner
files unchanged, nothing named k3s on the host; then (before and after `systemctl --user
restart`) the seed is exported without naming a namespace (digest, blob hashes and layer content
must be the seed's, not the decoy's), a NEW image is imported, seen by the CRI with the id the lab
computed (and in no rootful containerd), and a Pod runs from it as the user (host uid, user
namespace, non-root shim).

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/isolation/q72968351/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Identity, Privilege & Isolation
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/isolation/q72968351/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "isolation" / "q72968351"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q72968351",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup (a compile, the runner), solution and oracle (images, Pods, a restart)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the symptom (host ctr gets no socket) and a control (a Pod runs
    #    in the runner through the lab's own nsenter)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=long_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: ctr-k3s / crictl-k3s export the seed, import new images, the CRI
    #    knows them and Pods run from them, before and after a restart of the user service
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
