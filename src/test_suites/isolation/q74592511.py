"""
SO-74592511: "crictl with containerd permission denied" -- crictl is pointed at
containerd's CRI socket (/run/containerd/containerd.sock, root:root 0660) but a regular
user still gets "permission denied" and the asker wants to run crictl without sudo.
This is the harder variant of SO-70714501 (same mechanism): there are two users, and
only one of them may get the socket.

The fix is the same as there: a dedicated group that holds only the first user, and
containerd's own `[grpc] gid = <gid>` in /etc/containerd/config.toml, then a restart
(`[grpc] uid = <the user's uid>` is a second valid way). A chgrp/chmod of the live
socket is lost when containerd restarts. Whoever can use the CRI socket can fully manage
containers and images, so this is a management grant, not a read-only one.

Case design: setup.sh keeps the host's containerd and crictl configs (cleanup gives them
back), writes the default config, restarts containerd, points /etc/crictl.yaml at the
socket and creates bench74592511-dev and bench74592511-other. precondition.sh proves the
symptom: root's CRI answers, both users are denied by the socket permissions and have
no sudo rights. oracle.sh runs helpers/verify.py as root: no world bit on the socket;
/etc/crictl.yaml still names the socket; neither user is in root/sudo/wheel or has sudo rights;
the other user is refused with "permission denied"; the lab imports a new image with a random
name into the namespace of the CRI (helpers/mkimg.py) and the dev user's `crictl images`
must list it with its image id; then the lab restarts containerd and repeats everything
with a second new image.

This module does NOT reimplement the test logic in Python. It just
orchestrates the existing bash scripts under
cases/isolation/q74592511/ and converts their exit codes / output
into a structured `cases` dict.

Taxonomy category: Identity, Privilege & Isolation
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/isolation/q74592511/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "isolation" / "q74592511"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q74592511",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    long_timeout = max(timeout, 180)   # setup, solution and oracle restart containerd and wait for the CRI

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=long_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: prove the state -- the CRI works for root and both
    #    users are denied by the socket's permissions
    pre = run_script(CASE_DIR / "precondition.sh", timeout=timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=long_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: no world bit, no root/sudo/wheel or sudo rights, the other
    #    user refused, the dev user served with a fresh image, and all of it after a restart
    #    of containerd
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=long_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=timeout)

    return cases, error_message
