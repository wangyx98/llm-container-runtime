"""
SO-79297389: "Can I access a container in a pod in an AKS cluster as root?"

On an AKS node the asker opens a debug container (`kubectl debug node/...`), does `chroot /host` and wants a root shell in a workload that runs as an ordinary user. Two commands fail there:
`ctr -n k8s.io task exec --user 0 ...` ("failed to mount /tmp/containerd-mount...") and `runc --root /run/containerd/runc/k8s.io exec --user 0 ...` ("failed to open /proc/PID/ns/ipc: Permission denied"). The answer: `--user 0:0` (ctr).
Measured here (containerd 1.7.20 ctr, runc 1.1.12): ctr resolves a user given by a bare uid or a name through the container's /etc/passwd, which it reads by mounting the container's snapshot; the debug container has the runtime's default
capabilities (no CAP_SYS_ADMIN), so the mount is refused; uid:gid in numbers needs no lookup. runc exec has to open the namespace files of a non-root process and setns into them (CAP_SYS_PTRACE and CAP_SYS_ADMIN, both needed): `0:0` does not help there.
(A ctr 2.x client resolves the user differently and works with `--user 0`, which is why the case pins the node's ctr.)

Setup: a workload `bench79297389-app` in containerd's namespace k8s.io (random non-root uid:gid, `/usr/bin/idle`, /data from the host); the program `maintain` refuses unless uid AND gid are 0 and then writes /data/done (ids, namespaces, a per-run token). A
"node debug container" = a runc bundle (rootfs: one `enter` program that does `chroot /host`; the host's / at /host, host PID/net/IPC namespaces, default capabilities); `/tmp/bench79297389/node-debug COMMAND...` runs a command in it and logs start/end/exit code. The node's ctr (pinned, sha256) is first on its PATH.

Task: run /usr/bin/maintain once in the running workload as root:root, started from the debug container. Not allowed: restarting the workload, making it root/privileged, changing the debug container, the wrapper or its ctr.

Oracle: workload task/pid/start time/user/capabilities/namespaces unchanged; wrapper, node ctr, debug spec hashes and the debug container's CapEff unchanged; /data/done is root:root, uid=0 gid=0, the image's token, the five namespaces of the workload's init, and it was
written inside a run of the wrapper (mtime inside a logged window), so a run from the node's own shell does not count.
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/isolation/q79297389/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "isolation" / "q79297389"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q79297389", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)
    setup_timeout = max(timeout, 300)        # the first run downloads the pinned ctr (48 MB)
    pre_timeout = max(timeout, 120)          # about ten short commands
    solution_timeout = max(timeout, 90)
    oracle_timeout = max(timeout, 120)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: non-root workload; from the debug container ctr --user 0 and runc exec fail, ctr --user 0:0 works
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: /data/done written as 0:0 by a new process of the untouched workload, inside a debug-container run
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
