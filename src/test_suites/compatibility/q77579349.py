"""
SO-77579349: "Migrating from docker & docker-compose to containerd and nerdctl" (no accepted answer). A Compose file with Traefik (reverse proxy) and Apache works with Docker, because Traefik's DOCKER provider
reads the containers' labels from the Docker API. Ported to nerdctl compose, the asker swaps the provider for `--providers.docker=false` and `--providers.containerd.endpoint=unix:///var/run/containerd/containerd.sock`
(the containerd socket mounted into Traefik); both containers "run", the site is not reachable ("page can't be reached").
Measured (Traefik v3.0.4 release binary, nerdctl 1.3.1, containerd 1.7.20): Traefik has NO containerd provider. With the asker's flags (and with `--providers.containerd=true`) the Traefik container exits at once with
`failed to decode configuration from flags: field not found, node: containerd`; nothing listens on 80 (so the browser reports a connection failure, not a 404) while the Apache container is fine. `--providers.docker=true` with the
containerd socket as endpoint starts Traefik but its provider fails (`malformed HTTP response`: gRPC socket, not a Docker API) and no router is created. What works: Traefik's file provider (routes written down) -- the label based
discovery of the Docker provider does not exist for containerd.

Adaptation (stated in task.txt): Docker Hub and apt are not used; 'traefik:v3.0' is the real Traefik v3.0.4 in an offline FROM-scratch image, 'httpd:latest' is a minimal static HTTP server standing in for Apache (per-run
nonce, echoes the Host header); the containerd socket mounted is the lab's. The case does not require dynamic discovery (Traefik cannot do it on containerd); the reference is not from the thread (it has no answer).

Setup: a private containerd 1.7.20 + nerdctl 1.3.1 + CNI plugins 1.5.1 (pinned, sha256, cached in /var/cache/bench77579349), the two images, the question's compose file in /tmp/bench77579349/compose, the node's
nerdctl wrapper, ports 80/443 checked free, firewall and link baselines in a root-only state dir. precondition.sh: the question's compose started as asked (apache running, traefik exited with the unknown-field error, no answer on
80, the backend answers on its own address), then a repaired COPY (file provider) as the control (routes example.com to the nonce, other Host -> 404), both removed. The oracle: containers `traefik` and `apache` running with
nerdctl compose labels from the loaded images (the processes are the pinned binaries), Traefik publishes 80/443 and the backend nothing, no host process listens on 80/443, Traefik's API has an enabled non-Docker router for
example.com and an UP service, and from the host's own non-loopback address Host example.com returns the backend's nonce and another Host Traefik's 404.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q77579349/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q77579349"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q77579349", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 600)        # a first run downloads four pinned releases (about 130 MB per architecture)
    pre_timeout = max(timeout, 180)          # two compose projects are started and removed
    solution_timeout = max(timeout, 180)
    oracle_timeout = max(timeout, 120)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the question's compose leaves Traefik exited (unknown field), no answer on 80; a file-provider copy works
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: compose containers running, Traefik's API router (non-Docker provider), from outside Host example.com -> the nonce, other Host -> 404
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
