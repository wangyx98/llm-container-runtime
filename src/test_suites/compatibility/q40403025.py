"""
SO-40403025: "runc: "start" requires a minimum of 1 argument" -- following a runc tutorial the asker runs `sudo runc start` in a directory with config.json and rootfs;
the command fails with the argument error. The only answer (cyphar, runc maintainer): the container needs a name; use `runc run container-name`, or the split commands
`runc create container-name` and `runc start container-name`.

Measured (sandbox, runc 1.5.2): `runc start` without an id prints "Incorrect Usage." and `runc start <container-id>`, exits non-zero; the thread's own wording
("requires a minimum of 1 argument") is from a runc of 2016 and does not appear any more (stated in task.txt). This is the smallest faithful setup on a modern runc, a BASIC
lifecycle sanity variant (the thread has no config, no version, no environment): setup.sh makes a bundle (config.json by `runc spec`, one static program /app that prints
nonce + tick), and creates the container `bench40403025` with `runc create` (state created, stdout/stderr to a log file). The solution starts that container. The oracle checks the
bundle is unchanged, `runc state` is running, the init pid and start time are the ones of the created container (not deleted and recreated, not another id), the process is /app with the
bundle's bytes and this run's nonce, the tick counter in the log moves, and exactly one runc container exists for the bundle.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q40403025/ and converts their exit
codes / output into a structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q40403025/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q40403025"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q40403025",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)
    setup_timeout = max(timeout, 300)        # a first run may install gcc
    solution_timeout = max(timeout, 120)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stderr.strip()[-500:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: prove the symptom -- the container is 'created' (init pid recorded),
    #    and `runc start` without an id fails and starts nothing
    pre = run_script(CASE_DIR / "precondition.sh", timeout=max(timeout, 120))
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the same container (same init pid and start time) is running the
    #    bundle's /app with this run's nonce, the tick counter in the log moves, one container for the bundle
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=max(timeout, 120))
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
