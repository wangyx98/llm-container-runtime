"""
SO-76534717: "How to invoke containerd API using grpcurl" (Windows; no accepted answer). The asker calls containerd's Containers service with grpcurl against localhost:8080 (the TCP address of containerd's config)
and gets `unknown service containerd.services.containers.v1.Containers`, while `ctr.exe` lists the containers of the same containerd without trouble.
Measured (containerd 1.7.20 Linux release, grpcurl v1.9.1): with `[grpc] address = <sock>` and `tcp_address = "127.0.0.1:8080"` containerd logs the same three `serving...` lines as the thread (the socket, the ttrpc socket and
`address="127.0.0.1:8080"`), so 8080 is containerd's TCP listener. That listener serves only a few services (containerd does not plan its native APIs over TCP; CRI can be), and the question's call gets exactly
`Code: Unimplemented / Message: unknown service containerd.services.containers.v1.Containers`. The same proto through containerd's MAIN socket (`grpcurl -plaintext -unix ... SOCK`) answers; the API is per namespace, so
without the header `containerd-namespace: k8s.io` containerd answers `FailedPrecondition: namespace is required` (ctr's default namespace is `default`, Kubernetes' is `k8s.io`). The server has no gRPC reflection (grpcurl needs the proto).

Adaptation (stated in task.txt): the question is on Windows (containerd listens on a named pipe there); the case is a LINUX stand-in with the unix socket instead of the pipe: the pipe, and whether grpcurl can use it,
is NOT claimed solved or tested. The proto is a hand-written minimal copy (Get/List, the fields id, labels, image, snapshotter, snapshot_key; package, service and field numbers as in containerd's
api/services/containers/v1) because the real proto tree could not be fetched. The symptom, the log lines and the 8080 reply are those of the real containerd. The thread has no answer; the reference is from the measurement.

Setup: a private containerd 1.7.20 (pinned, sha256, cached in /var/cache/bench76534717) with the socket and tcp_address 127.0.0.1:8080 (port checked free), the pinned grpcurl v1.9.1 (a copy behind a logging wrapper is the
solution's tool), the minimal proto, an offline image and two never-started containers made with containerd's ctr: the target in namespace k8s.io, a decoy in `default` (both with a random id and a nonce label), all in a
root-only state dir. precondition.sh: containerd and the tools are as recorded; port 8080 belongs to containerd's process; the question's call gets `unknown service`; no reflection; the objects exist; the control (socket +
namespace header) returns the container and not the decoy, no header gives `namespace is required`, namespace default lists just the decoy. The task: write /tmp/bench76534717/list.sh. The oracle (dynamic): containerd (same
process and config), tools, proto and objects unchanged; 8080 still `unknown service`; the script has no ctr/nerdctl/crictl/docker words or paths of containerd's files; then a NEW container (new id and nonce) is created and
the script is run with traps for the container clients on the PATH: its output must hold both containers of k8s.io with their nonces, no id or nonce of the decoy, exactly those ids; the wrapper's log must show a
successful call of the Containers service on containerd's socket made during that run (fixed or remembered output cannot pass).

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q76534717/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q76534717"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q76534717", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)
    setup_timeout = max(timeout, 600)        # a first run downloads two pinned releases (about 45 MB per architecture)
    pre_timeout = max(timeout, 120)
    solution_timeout = max(timeout, 120)
    oracle_timeout = max(timeout, 150)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the question's call on 8080 gets "unknown service"; the objects exist; the control call on the main socket works
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: a new container is made, list.sh is run; its output must show the containers of k8s.io from a real grpcurl call to the main socket
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
