"""
SO-68845002: "Ehcache 0B of physical memory when using containerd" (Ehcache 3.9.3, containerd 1.3.7, RHEL 7, Spring Boot on a JDK 11; the same image works with Docker and with
Docker as the Kubernetes runtime, and fails with containerd: "Attempting to allocate 50.0MB of memory when the host only contains 0B of physical memory"). The question has no
verified answer (the asker switched the JVM's container support off; an answer says a newer JDK 11 fixes it; the Ehcache issue 2934 only suspects the JDK change JDK-8226575).
The cause is locked by evidence: Ehcache reads OperatingSystemMXBean.getTotalPhysicalMemorySize(); the JDK 11.0.9 to 11.0.12 container code splits every line of
/proc/self/cgroup with split(":") and cuts a cgroup path at its first colon (JDK-8272124, fixed in 11.0.13); containerd's CRI plugin names the cgroup <pod parent>.slice:cri-
containerd:<id> when the kubelet's parent is a systemd-style slice, and runc on cgroupfs (SystemdCgroup = false, the default) takes that as a literal directory name WITH
colons; the JDK then finds no memory.limit_in_bytes, reads 0 and returns it. Docker's path has no colon, so Docker works.

The suspects are told apart by controls that change one thing (precondition.sh): the JDK (same pod and path on 11.0.13 works), the cgroup path (same JDK 11.0.9 with a cgroupfs-
style parent works), the runtime (a private Docker daemon with runc works), and the asker's workaround (-XX:-UseContainerSupport starts the cache but the JVM sees the memory of
the host, not the limit: the oracle does not accept it). The failure itself is the real one: the unmodified Ehcache 3.9.3 and JDK 11.0.9 in a real CRI pod.

Adaptation, said so in task.txt: no kubelet: run-workload applies pod.json and container.json through the node's CRI (crictl) like a kubelet does; the node is a private containerd
of the host (any version: the colon form comes from the CRI plugin's naming of slice parents; containerd 1.3.7 has no arm64 release); the JDKs are Temurin 11.0.9 and 11.0.13
(pinned sha256, downloaded once into /var/cache/bench68845002), made into small jlink runtimes inside two offline docker archives with a 50 MB off-heap Ehcache program.

CGROUP V1 ONLY: the JDK code that fails is the cgroup v1 parser; on a cgroup v2 host JDK 11.0.9 does not read container limits at all, so setup.sh prints NOT APPLICABLE and
exits 1 (see docs/case-notes/q68845002-cgroup-v1-only.md). Not architecture-specific (x86_64 and aarch64 JDKs, pure Java).

Where the samples fail: nothing done; the JVM's container support switched off in the container's environment; another slice for the pod (still a colon); an image the node does
not have; run-workload edited to print the good result. Valid: the pod's cgroup parent made a cgroupfs one; the image with JDK 11.0.13.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q68845002/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q68845002/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q68845002"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q68845002",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 300)      # the node, its pods and a control docker daemon are stopped, their processes ended
    setup_timeout = max(timeout, 1800)        # first run: downloads two JDKs (about 380 MB) and two jars, builds two images, starts the node
    pre_timeout = max(timeout, 600)          # controls: four more pods, a private docker daemon
    solution_timeout = max(timeout, 300)     # a solution changes the workload files or the node and runs the workload
    oracle_timeout = max(timeout, 600)       # two restarts of the node and two runs of the workload

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the node as recorded; the cause told apart from the other suspects by controls
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the cache really starts in the node's CRI pod with the container's own memory limit, twice, after restarts of the node
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
