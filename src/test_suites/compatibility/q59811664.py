"""
SO-59811664: "What are good workflows for deploying podman/buildah created container images to minikube?" (kvm2 driver, CRI-O). An image built on the workstation with Podman is not known to
the CRI-O inside the Minikube VM: the two keep their images in separate containers/storage stores (and the VM is a separate machine). The ways are to push it to a registry that the VM can reach
(Minikube's registry addon, a plain-HTTP registry, which CRI-O and Podman treat as insecure only when told so) or to move it as an archive (`podman save` ... load/import into the VM's store).
Extension variant of q59161183 (the same two ways for an image of a Docker engine); it adds the registry way and the trust setting that way needs.

Adaptation (stated in task.txt): there is no Minikube VM / kvm2 driver here. The VM boundary is replaced by two stores on this host: the workstation's own podman store
(`podman --root /tmp/bench59811664/workstation/root`) and CRI-O's (the default root store); the changing VM IP is replaced by a fixed registry address on this host's default-route IP (the
loopback addresses would hide the problem: containers/image tries plain HTTP for 127.0.0.0/8 by itself).

Measured (CRI-O 1.34.0, podman 4.9.5): a plain-HTTP registry on a non-loopback address makes `podman push` and `crictl pull` fail with "server gave HTTP response to HTTPS client". `podman push --tls-verify=false`
works. CRI-O needs `[[registry]] location=HOST:5000 insecure=true` in /etc/containers/registries.conf.d/ AND a reload (SIGHUP to crio, or a restart): with the file alone the pull still fails. The image id
(config digest) survives push/pull and save/load unchanged; export/import creates a new image (new id).

Setup: CRI-O as in q59161183 (pinned v1.34 stream, crictl v1.34.0); an image built into the workstation store from scratch (a static program that prints /etc/unique.txt, a per-run random token, once a second);
a small plain-HTTP registry (python, started by setup.sh, writes a request log with the User-Agent), empty. precondition.sh: the stores are separate, the registry answers and is empty, a TLS-verified push
and a CRI-O pull both fail with the HTTPS error, no registry setting exists, no pod/container. The oracle: pod SANDBOX_READY and container CONTAINER_RUNNING by crictl; the container's image id equals
the workstation image's id and has its layer; entrypoint /app, live process; /etc/unique.txt read through /proc/PID/root and printed in the log; workstation image unchanged; if the image is named by
the registry, the registry's log shows successful GETs of the manifest and the config blob and its stored manifest holds the config digest (offline route: imported artifact, proven by id and layer).
cleanup.sh also removes registry settings and reloads CRI-O (the next run's controls need CRI-O without them).

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q59811664/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q59811664"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q59811664", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)
    setup_timeout = max(timeout, 600)        # a first run may install CRI-O, crictl and podman
    pre_timeout = max(timeout, 120)
    solution_timeout = max(timeout, 120)
    oracle_timeout = max(timeout, 120)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: image only in the workstation store, plain-HTTP registry empty, push and CRI-O pull fail with the HTTPS error
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: CRI-O runs the workstation's image (same id), unique file read out, registry really served it when named by it
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
