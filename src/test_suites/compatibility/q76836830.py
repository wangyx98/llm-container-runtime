"""
SO-76836830: "Cant pull image from nexus repository when i upgrade kubernetes cluster to v1.24" (no error message and no configuration in the question; the asker's own answer: nginx in front of Nexus routes
"docker" requests to the Docker repository by `$http_user_agent`; after the move from Docker to containerd (1.24) the pull requests carry containerd's User-Agent, which did not match; a second rule for
containerd in nginx.conf fixed it; the same trouble on Fargate is not part of the case). The fix is on the SERVER side (the reverse proxy in front of the registry), not in the node's containerd.

Adaptation (stated in task.txt): no Kubernetes, Fargate or Nexus. "Nexus" is two stand-ins (a minimal registry with a request log for the Docker repository connector, a page server for the web application whose /v2/ is
404), real nginx 1.24+ (apt) in front with the rule of the answer (reconstructed, the thread has not the file); the node is a private containerd (minimal version-2 configuration, CRI plugin on) and the kubelet's pull is
`crictl pull` (CRI PullImage) of 127.0.0.1:18076/bench76836830/app:1.0. The original error is not known: the lab's is "failed to resolve image ... not found" (the stand-in web application answers 404). A Docker
engine is represented by a request with its User-Agent (no dockerd runs).

Setup: nginx installed only when missing (service not started); a static image built here and pushed to the stand-in registry, then removed from the node (images and content); the stand-ins, containerd and nginx
started detached; pids + start ticks + hashes of the programs, the node's configuration and the wrappers in a root-only state dir. precondition.sh: daemons and files as recorded, a cold node, the front is the case's
nginx, a Docker UA reaches the registry, a browser the web page, a containerd UA is not routed to the registry, the node's pull fails with "not found" and the registry saw nothing of it. Oracle (dynamic): daemons and
files unchanged, nginx still the front with the case's configuration which passes `nginx -t`, a Docker UA still gets the registry's manifest and a browser the Nexus page, then on a node emptied of images and content the
job's pull succeeds, the registry's log shows containerd's 200 for the manifest and both blobs, and the node holds the registry's image (id and repo digest).

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q76836830/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q76836830"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q76836830", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 900)        # a first run may install nginx, gcc and crictl
    pre_timeout = max(timeout, 120)
    solution_timeout = max(timeout, 120)
    oracle_timeout = max(timeout, 240)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the node has containerd only; the node's pull fails with "not found"
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the test's container is a real container of the node's containerd
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
