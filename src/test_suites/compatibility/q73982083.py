"""
SO-73982083: "How to run container in container with rancher-desktop" (one answer, no error output). The asker wants a container that starts containers; with Docker one mounts
/var/run/docker.sock, Rancher Desktop (containerd) has no such socket on the host. The answer: the containerd socket is inside the Rancher Desktop VM, `~/.rd/bin/nerdctl` only forwards
into the VM through `rdctl`, and a client container has to be given the VM-side socket (alternatives: a socket in a shared dir, containerd on TCP, the moby engine's ~/.rd/docker.sock; changes are
lost on upgrade).

Measured (nerdctl 1.3.1 with containerd 1.7.20, containerd 2.4.2 as the host's): (1) nerdctl and ctr cannot dial a containerd TCP address (`--address 127.0.0.1:8080`: "cannot access containerd socket ...",
`tcp://...`: "invalid address"; `ctr -a tcp://...`: "invalid (non-empty) authority"), so the answer's TCP route is not usable with these clients; (2) a client that has the VM's socket but is not privileged fails to mount the
snapshots ("operation not permitted"); (3) without the containerd store mounted at the same path the client's `nerdctl run` fails ("failed to mount ... no such file or directory"); (4) the socket has to be mounted at the SAME path it has in the
VM, not at nerdctl's default /run/containerd/containerd.sock: nerdctl's OCI hook runs in the VM and looks the client's --address up there ("lstat ... no such file or directory"); (5) the `-d` log helper is `binary:///usr/local/bin/nerdctl`
resolved in the VM, so the VM has nerdctl at that path; (6) with these four things `nerdctl run -d` from the client works with no other flag and the client's own default cgroup manager (cgroupfs).

Adaptation (stated in task.txt): no Rancher Desktop, no hypervisor: the "VM" is a private mount namespace (/run, /var/lib, /usr/local are tmpfs in it) with a pinned containerd 1.7.20 listening on Rancher Desktop's path
/run/k3s/containerd/containerd.sock with its store in /var/lib/rancher/k3s/agent/containerd, a nerdctl 1.3.1 (config in /usr/local/etc/nerdctl) and a marker container; the host has an `rdctl shell` wrapper (nsenter into the VM) and a
nerdctl wrapper that forwards into the VM, like ~/.rd/bin/nerdctl. The VM is a Linux boundary, not a hypervisor: the host and the VM share the kernel, /tmp and the process table. The case is the "VM socket is not on the host"
side of q78289599 and the "client in a container" side of q75845783, with a VM boundary (instead of a Pod) and nerdctl; the thread has no error text, the reference is from the measurement.

Setup: pinned containerd + nerdctl (sha256, amd64/arm64) in /var/cache/bench73982083 (kept), a static `/sleeper` and the client image (the VM's own nerdctl at /usr/local/bin/nerdctl) written as a docker-archive, the VM booted by
`unshare -m` + a boot script (tmpfs mounts, config, `exec containerd`), the two wrappers, the image loaded, a marker container with a per-run token label, all pids/ns/hashes/ids in a root-only state dir. precondition.sh: the VM's
daemon is the recorded process in its own mount namespace with its recorded config, the socket exists in the VM and its path not on the host, the marker runs, the image is there, a plain client container has no socket
('cannot access containerd socket'). The oracle (dynamic): the daemon is the same process (pid, start time, mount namespace, config), the host has no socket/store of it, no other containerd/dockerd was started, the marker
still runs; ONE container `bench73982083-client` runs in the VM's daemon from the image with the image's entrypoint and a live process; `nerdctl container inspect` of the marker INSIDE the client shows the per-run token (so the
client reaches the VM's daemon, not an empty mounted file nor another daemon); the task's own command, run inside the client with no daemon flags, starts a container with a fresh nonce on the VM's daemon whose process is alive and
whose command line has the nonce.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q73982083/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q73982083"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q73982083", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 300)        # a first run downloads the pinned containerd and nerdctl (about 40 MB)
    pre_timeout = max(timeout, 120)
    solution_timeout = max(timeout, 120)
    oracle_timeout = max(timeout, 180)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the VM's daemon is up behind its boundary, a plain client has no socket
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the client runs in the VM's daemon and starts a nonce container there
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
