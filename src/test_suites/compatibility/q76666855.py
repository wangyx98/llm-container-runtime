"""
SO-76666855: "Jmeter keeps running in containerd-shim everytime docker is started. how to completely remove it?" (Ubuntu 22.04: a JMeter load test, started once and forgotten, runs below a containerd-shim and keeps
calling the staging API; kill -9 is useless, stopping containerd stops it but starting Docker brings it back, and without sudo `docker ps -a` shows nothing; the answer: the container has a restart policy, take it
away (`docker update --restart no`) and stop it; the asker's comment: with sudo `docker ps -a` lists the container).

Adaptation (stated in task.txt): no JMeter, Java or /jmeter scripts: the load generator is a static program (the entrypoint of an image made with `docker import`) that calls a local staging API stand-in once
per second, tagged with its name, in a container with restart policy `always`; a healthy neighbour (policy `unless-stopped`, other tag) runs next to it. The services are a containerd and a dockerd of the lab
(own sockets, roots, exec root, cgroup parent; `bin/stack start|stop|restart|status` stands for `systemctl ... containerd docker`). The asker's sudo confusion is not part of the lab. The cause (restart
policy of dockerd, namespace moby) is taken from the answer and the comment of the thread.

Setup: gcc only when missing; the program, the endpoint, the lab's configuration and wrappers; both containers started; pid/start tick of the endpoint, hashes of the scripts and configuration and the two
containers (id, image, command, creation time, policy) recorded in a root-only state dir. precondition.sh: lab as recorded, both containers run with their policies, the process hangs below a shim of namespace
moby (default ctr namespace empty), both call the API, kill -9 of the process: it is back, docker stop + restart of the services: it is back. Oracle (dynamic): lab unchanged and running; as left: no process and no
request of the load generator during 5 s, no other container runs or keeps a restart policy, the neighbour is the recorded container (not re-created, policy unchanged, running); then the oracle restarts the services twice
and repeats the window and the checks.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q76666855/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q76666855"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q76666855", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 900)        # a first run may install gcc
    pre_timeout = max(timeout, 120)
    solution_timeout = max(timeout, 120)
    oracle_timeout = max(timeout, 300)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the load generator runs below a shim of namespace moby, kill -9 and stop do not get rid of it
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the load generator is gone for good (also after two restarts of the services), the neighbour is untouched
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
