"""
SO-75845783: "nerdctl run `no such file or directory` when running inside a pod" (no accepted answer; the linked nerdctl issue is about another file). A privileged Pod with the
host's containerd socket can `nerdctl ps` and `nerdctl pull`, but `nerdctl run -d` ends with `FATA ... no such file or directory`; on the host the same command works.
The mechanism: a privileged Pod shares the kernel, not the file system. Everything `nerdctl run -d` hands over is a PATH that containerd, runc or the log process then open ON THE HOST,
and the client itself mounts the image's snapshot in the Pod: the first failure is the snapshot directory of containerd's root, which the Pod does not have; fixing it shows the next one.
The full chain for a Pod whose nerdctl was brew-installed at /home/linuxbrew/.linuxbrew/bin: (1) containerd's root, (2)+(3) the CNI plugin and configuration directories, (4) nerdctl's data root
/var/lib/nerdctl, (5) a nerdctl binary at a path that exists on the host (containerd starts it as log process and OCI hook), (6) a containerd address that is valid on the host too (the log
process connects to the address stored with the container; CONTAINERD_ADDRESS reaches the hook too). With (6) missing the container runs but its log stays empty.

The case runs real k3s on a private containerd (as q69088569), nerdctl 2.1.3 and the CNI plugins v1.5.1 pinned by sha256 and cached in /var/cache/bench75845783 (kept by cleanup.sh), a default bridge
network (bridge + host-local, no iptables rules), an app image and the Pod's image built offline by setup.sh (static programs, a shell toolset taken from the machine). No helper files: every
stage is one script; the oracle's logic is a python block inside oracle.sh.

precondition.sh: the machine as recorded; control 1: ps and images work in the Pod; control 2: `nerdctl run -d` in the Pod fails with `failed to mount ... no such file or directory`, the path is a
snapshot of containerd's root (on the host, not in the Pod), nothing is created; control 3: `nerdctl run -d` works on the host (address of the bridge, the log shows the nonce).
The oracle: the machine and the files nobody may change; the Pod is still the engineer's (privileged, root, image, two original mounts, no host root or system directory, no host PID/network/IPC,
pinned nerdctl); then the oracle itself runs `nerdctl run -d --name NAME app NONCE` in the Pod twice with new names and nonces and judges each container on the host (labels and arguments of the command,
task RUNNING, process, address of the bridge, the log process is the Pod's nerdctl, the stored containerd address reaches the case's containerd, the state directory belongs to it) and in the Pod
(`nerdctl ps`, `nerdctl logs` with the nonce); the host control (host-web, a new host run, all addresses different). Containers made by the oracle are removed at the end.

Where the samples fail: nothing done; only the root of containerd mounted (next: CNI); everything but a host path for the nerdctl binary (fork/exec of the log process); everything but the shared containerd
address (the container runs, its log process cannot reach containerd: caught by the stored address and the empty log); privileged replaced by capabilities; the host's root mounted in the Pod.
The two valid solutions put the host's nerdctl in PATH (hostPath directory) or copy it to the brew path on the host.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q75845783/ and converts their exit codes / output into a
structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q75845783/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q75845783"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q75845783",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 300)      # k3s, containerd and every container are stopped and removed
    setup_timeout = max(timeout, 600)        # may download k3s, nerdctl and the CNI plugins; starts containerd and k3s
    pre_timeout = max(timeout, 300)          # controls: a failing run in the Pod, a working run on the host
    solution_timeout = max(timeout, 300)     # a solution recreates the Pod and may test it
    oracle_timeout = max(timeout, 600)       # two runs in the Pod and one on the host, each judged

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the machine as recorded; the bad state is real (run fails in the Pod, works on the host)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: fresh containers are started from inside the Pod and judged on the node and in the Pod
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
