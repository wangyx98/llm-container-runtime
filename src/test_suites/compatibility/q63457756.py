"""
SO-63457756: "docker: Error response from daemon: ttrpc: closed: unknown. after upgrading containerd to 1.4.0" (Arch Linux; after `pacman -Syu` brought
containerd 1.4.0-1, every `docker run` ends with that error). The cause is in the Arch bug tracker (FS#67621) and containerd issue 4483: the PKGBUILD of
1.4.0-1 builds with `make EXTRA_LDFLAGS="-linkmode external"` on top of GOFLAGS="-buildmode=pie"; the shims (containerd-shim-runc-v2, built static with
CGO_ENABLED=0) come out as a broken ELF that dies by SIGTRAP when it starts, so containerd cannot create the task of any container. 1.4.0-2 is the same
source (tag v1.4.0) built without that flag. The answer: the package 1.4.0-2 (or the downgrade); docker and runc are not the cause.

x86_64 ONLY: the defect exists only there (the Arch packages are x86_64 only; with the same recipe on aarch64 the shim starts and docker run works), so setup.sh
exits at once with "NOT APPLICABLE" on any other architecture: exclude this case from runs on aarch64 (see docs/case-notes/q63457756-x86_64-only.md).

The packages are real builds of the pinned source (commit 09814d48 of the tag v1.4.0) with Go 1.15 and the two recipes of the Arch PKGBUILDs, compiled once
here (the Arch packages are x86_64 only) and cached in /var/cache/bench63457756, Go 1.15 fetched from go.dev with a checked sha256. They are used by a stack
below /var/lib/bench63457756 that the engineer's scripts start: containerd of the installed package (the link opt/containerd) on its own socket, and the
dockerd and docker client of the host on top of it (its own sockets, data and containerd namespace; the docker of the host is not touched; runc is the
host's). The workload is a static program in an offline image: it prints nonce=<argument> and exits.

setup.sh: the two packages, the stack, the image, the failing `docker run`, the shim of 1.4.0-1 dying by a signal while the one of 1.4.0-2 runs, the record
(hashes, versions). precondition.sh: the record is intact; control 1: `docker run` fails twice (the text differs with the versions); control 2: the shim of
the installed package dies at start; control 3: with the link on 1.4.0-2 and a restart the same `docker run` prints its nonce, and back on 1.4.0-1 it fails
again. The oracle: scripts, packages, runc, dockerd and image are as recorded; containerd runs from the installed package, which has to be 1.4.0-2; five
`docker run --rm` with fresh nonces print exactly nonce=<nonce> and exit 0; a probe container that waits has a parent that is the shim of the installed
package (read from /proc, same bytes as the recorded file, started with the case's containerd socket), runc's state of the container (runtime-runc/<namespace> below dockerd's exec root),
and containerd lists it with the runtime io.containerd.runc.v2; the daemons did not change during the oracle.

Where the samples fail: nothing done; a restart only; the link changed without a restart; a container run with `runc run` on a rootfs exported from docker
(never reaches the case's containerd); the shims of 1.4.0-2 copied over the files of 1.4.0-1 (the packages are no longer as recorded). The two valid
solutions put the link opt/containerd on containerd-1.4.0-2 and restart the stack.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q63457756/ and converts
their exit codes into the structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q63457756/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q63457756"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q63457756",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 300)      # the stack of the engineer is stopped, its processes ended
    setup_timeout = max(timeout, 3600)       # first run: fetches Go 1.15 and compiles the two containerd packages from the pinned commit (cached afterwards)
    pre_timeout = max(timeout, 600)          # controls: failing runs, two restarts of the stack with the other package and back
    solution_timeout = max(timeout, 300)     # a solution changes the installed package and restarts the stack
    oracle_timeout = max(timeout, 600)       # six docker runs and an identity probe

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the machine as recorded; the bad state is real (docker run fails with the installed package, works with the other)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: fresh containers of the same image, judged by docker, /proc and containerd
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
