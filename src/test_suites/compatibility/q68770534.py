"""
SO-68770534: "How to start containerd node local container images in kubernetes?" -- `ctr images list` on the node shows the image under the short name
`cuda` and under the full name `docker.io/nvidia/cuda:11.0-base`; a pod with `image: "cuda"` and imagePullPolicy: Never ends in ErrImageNeverPull ("Container
image "cuda" is not present with pull policy of Never"); without Never it works (the kubelet pulls). The only answer (not accepted): the pod's `cuda` is not the
name the image has on the node; write the whole name (`docker.io/nvidia/cuda:11.0-base`, or `nvidia/cuda:11.0-base`). The GPU limit of the pod is commented out, so
the failing pod does not use a GPU; the case uses a small static-program image of the same mechanism (stated in task.txt). The thread does not say which containerd
namespace `ctr` was using; the case fixes it to k8s.io (the CRI's), so the namespace of q73420677 is not the cause here.

Measured (sandbox, containerd 2.4.2, crictl 1.34): in k8s.io the image under `docker.io/nvidia/cuda:11.0-base` and under the bare name `cuda` (`ctr images tag`
stores the name as written, without docker.io/library/ and :latest); `crictl images` lists only the full name; `crictl inspecti cuda` -> "no such image";
creating a container from "cuda" -> `NotFound ... failed to resolve image "cuda": not found`. The CRI normalizes a short name (cuda -> docker.io/library/cuda:latest)
before the lookup, so the bare ref is invisible to it; `inspecti nvidia/cuda:11.0-base` and the full name work, and after
`ctr -n k8s.io images tag <ref> docker.io/library/cuda:latest` the name `cuda` resolves too. Not measured: containerd 1.x, a real kubelet.

Case design (CRI level, like q75568311 with ONE node): a private containerd on its own socket/store; setup.sh imports a generated application image (per-run token
in its entrypoint program) into k8s.io under the full name, adds the bare name `cuda`, starts a pod sandbox, and shows that creating the container from `cuda`
fails (the CRI-level ErrImageNeverPull). The solution makes the container run in the EXISTING sandbox: either the manifest gets the full name, or the image
gets the normalized name. The oracle checks that the node's containerd is the recorded process, the image of the node is untouched (CRI id = config digest recorded
at setup, ctr digest, no other image in the store), the original sandbox, one container RUNNING from that image, the image's own entrypoint as a live process and
the token in the log.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q68770534/ and converts their exit
codes / output into a structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q68770534/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q68770534"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q68770534",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)
    setup_timeout = max(timeout, 300)        # a first run may install crictl
    solution_timeout = max(timeout, 120)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stderr.strip()[-500:]}"
        # a long-lived daemon may be running: do not leave it behind
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: prove the symptom -- ctr lists the image as `cuda`
    #    and as docker.io/nvidia/cuda:11.0-base, the CRI knows only the full name,
    #    the pod sandbox is Ready, and creating the container from `cuda` fails
    pre = run_script(CASE_DIR / "precondition.sh", timeout=max(timeout, 120))
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the node's image is untouched (same image ID and
    #    digest, no other image), the ORIGINAL pod sandbox is still Ready, the
    #    container runs in it from that image with its own entrypoint, the
    #    process is alive and the log shows the image's per-run token (see
    #    oracle.sh)
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=max(timeout, 120))
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
