"""
SO-76466526: "Why does `docker image ls` not show the same result as `ctr image ls`?" (Docker with its own daemon next to containerd; accepted-style answer: Docker does not use containerd
as its image store unless the daemon runs with `"features": {"containerd-snapshotter": true}`; then the images are in the containerd namespace moby). The asker checks the namespaces default and
k8s.io, finds nothing, and `docker image load` does not help either.
This case is the STORE-BOUNDARY VARIANT (the storage-boundary cases 77663923 and 63478550 were named in the task list; their files were not visible, the skeleton is q63457756's private
containerd + dockerd stack): the question is not a wrong namespace but two image stores, so no namespace can list Docker's image. The storage mode is fixed (classic store), and the task
is to DELIVER the same image to the agreed entry (ctr, namespace default); a copy through export/import is the intended route, a shared store is not required.
What was measured (Docker 29.8.2 with `"containerd-snapshotter": false`, containerd 2.3.6): the image sits only in Docker's own database (data-root/image/overlay2/imagedb); containerd has no blob of it,
`ctr -n default|k8s.io|moby images ls` and `content ls` are empty (the namespace moby does not even exist until Docker runs a container), `ctr run` says "not found". `docker save` (Docker 25 and newer) writes
an OCI archive; `ctr images import` names it docker.io/bench76466526/app:v1 with an OCI manifest whose config digest is Docker's image id and whose layer is Docker's diff_id (uncompressed layer).
`ctr -n default run --rm` of that name prints the nonce baked into the image.

The lab (setup.sh): a private containerd (config version 2, CRI and NRI off) and a private dockerd on their own sockets below /run/bench76466526, state below /var/lib/bench76466526 (scripts
stack, docker, ctr in bin/), a one-layer docker archive of a static program that prints a per-setup nonce, loaded with `docker load`; the record (image id, layers, nonce, driver, sha256 of the
scripts and the configuration) in a state dir.

The check (oracle.sh): the files of the stack unchanged, Docker on the classic store, Docker's image the recorded one and still there (the image is delivered, not moved); containerd's
namespace default lists docker.io/bench76466526/app:v1, its manifest names the config of Docker's image id, the config's diff_ids are Docker's layers, the layer blobs are in containerd's content
store; `ctr run --rm` of the name, twice, prints exactly the nonce.

Where the samples fail: nothing done; every namespace listed; the image imported into k8s.io or moby (not the agreed entry); a decoy image tagged with the name (other config digest); the image removed
from Docker after the import; Docker switched to the containerd store (configuration changed). Valid: `docker save` to a file + `ctr images import` (reference); `docker save | ctr import -`; import with
`--all-platforms`.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q76466526/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q76466526/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q76466526"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q76466526",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 300)      # two daemons, shims, mounts
    setup_timeout = max(timeout, 600)        # compiles one program, starts containerd and dockerd, docker load
    pre_timeout = max(timeout, 300)          # the stack checks, the symptom and the oracle control
    solution_timeout = max(timeout, 300)     # a docker save, an import, a stack restart
    oracle_timeout = max(timeout, 300)       # a few ctr and docker queries and two container runs

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the image only in docker's store, nothing in any containerd namespace, the oracle fails while unfixed
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: containerd's default namespace holds Docker's image (same config and layers, runs, prints the nonce), Docker unchanged
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
