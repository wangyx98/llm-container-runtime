"""
SO-72120811: "ctr run equality mapping for docker run" (containerd; the asker has `docker run -d --hostname my-rabbit --name some-rabbit -p 8080:15672 rabbitmq:3-management` and
`ctr run -d --net-host docker.io/library/rabbitmq:3-management some-rabbit`, and cannot find how to give ctr the --hostname and -p of Docker). The question has no answer.
What ctr can and cannot do was measured (ctr 2.3.6 and 2.2.1 both have --hostname and --cni; neither has an option for a published port; --cni reads only /etc/cni/net.d and
passes no portMappings to the portmap plugin, so a portmap entry in the configuration maps nothing): the host name is set when the container is created (a running container is
made again), the port is published by the kernel's NAT (DNAT in iptables or nft) for the traffic that arrives through a bridge (PREROUTING) AND for the host's own clients (OUTPUT).

The lab (setup.sh): a private containerd; an offline image with a static program that stands in for RabbitMQ's management service (port 15672, answers
"mgmt hostname=<host name> nonce=<token of the image>"); the container some-rabbit in a network namespace of its own (CNI bridge plugin, 10.172.12.0/24, with a default route so that
replies can come back); a second namespace on another bridge (10.172.13.0/24) that stands in for another machine, so that "reachable from outside" is tested on the PREROUTING path.
Adaptation, said so in task.txt: RabbitMQ itself is not used (the question is about ctr's mapping of two docker options, not about the broker); the program is built from C at setup.

The check is behavioural (oracle.sh): a NEW container some-rabbit from the same image and program with the host name my-rabbit in its spec and UTS namespace, in a network namespace that is
not the host's, listening on 15672 (not on 8080), and the primary address of the host answering on 8080 with the container's line from the host and from the other machine, while no socket
of the host listens on 8080 (a user-space forwarder or a fake server is not a published port; Docker itself publishes with iptables rules).

Where the samples fail: nothing done; --net-host; the host name without a mapping; a mapping without making the container again; a mapping only for the host's own traffic; the container's
port changed to 8080; a user-space forwarder on port 8080. Valid: iptables DNAT (reference); nft DNAT.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q72120811/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q72120811/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q72120811"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q72120811",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 300)      # containers, processes, firewall rules, namespaces, bridges
    setup_timeout = max(timeout, 900)        # first run: downloads the CNI plugins (about 50 MB), builds the image, starts the containerd
    pre_timeout = max(timeout, 300)          # the lab checks and two controls
    solution_timeout = max(timeout, 300)     # a solution makes the container again and adds firewall rules
    oracle_timeout = max(timeout, 300)       # six requests, up to ten seconds of waiting each

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the lab as recorded, the failure of the question, a mapping and --hostname both possible here
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: a new container with the host name my-rabbit in its own network namespace, port 8080 of the host's primary address published by the kernel
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
