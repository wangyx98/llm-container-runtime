"""
SO-73029815: "not showing kubernetes pods in podman" (Ubuntu 20.04, Kubernetes 1.24 with CRI-O, podman 3.4.2; no answer on the page). `crictl ps -a` lists the nginx, calico and dashboard containers,
`podman ps -a` lists nothing, and the asker wants to manage them with Podman or `podman commit` them.
What was measured (real CRI-O 1.34.0 and Podman, both on /var/lib/containers/storage): Podman only knows the containers of its own database; `podman commit` (4.9.5 and 3.4.4), and with 4.9.5 `podman inspect`, `podman stop`,
`podman cp` and `podman export`, on a CRI-O container say "no such container" (or fail); with Podman 3.4.4 (the version of Ubuntu 22.04) even `podman ps -a --external` is empty, because CRI-O 1.34 keeps its
containers in volatile-containers.json, which the older containers/storage library does not read (Podman 4.9.5 lists them as "Storage" and can `podman mount` them). So the original constraint
(Podman-native list and commit of a CRI-O container) cannot be met on this stack; this case is the VARIANT with the tool left free: the goal of the commit is reached by another route.

The lab (setup.sh): CRI-O 1.34 + crictl 1.34 as in q65650082, Podman from apt; two CRI-O pods from busybox:1.36 (bench73029815-shop, bench73029815-blog), each with a container "app" whose
workload writes, after it started, two files of random content and one appended line of /etc/passwd; a container of Podman (bench73029815-native). setup.sh records container ids, start times,
pod count and the sha256 of the changed files (and of /bin/busybox) in a root-only truth.env.

The check (oracle.sh): the source is untouched (same containers, running, not restarted, same files, same pod count, Podman container running); the image localhost/bench73029815/shop:snap exists in
root's Podman store, runs /bin/sh, and holds the recorded files of the SHOP container (not the blog's, not the base image's) and the base system.

Where the samples fail: nothing done; podman commit of the CRI-O container (the asker's attempt); the blog pod exported; the container of Podman committed; the base image tagged; only the changed
files (writable layer) imported, not runnable; the source pod removed after a correct export. Valid: tar of the container's root directory + podman import (reference); tar through crictl exec + import;
base image + the writable layer (ADD) with podman build.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q73029815/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q73029815/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q73029815"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q73029815",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 300)      # pods, containers, images
    setup_timeout = max(timeout, 900)        # first run: installs CRI-O, crictl and Podman, pulls busybox, starts two pods
    pre_timeout = max(timeout, 300)          # the lab checks, the symptom and three oracle controls
    solution_timeout = max(timeout, 300)     # a solution tars a root file system and imports or builds an image
    oracle_timeout = max(timeout, 300)       # CRI-O and Podman queries and two runs of the image

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the lab as recorded, the symptom of the question, the oracle against wrong and right images
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the image in root's Podman store holds the current files of the shop container; the source still runs
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
