"""
SO-76980610: "How can I configure SpringBoot TestContainers to use containerd instead of docker" (Spring Boot integration tests with Testcontainers fail with "Status 502: Bad response from Docker engine /
Could not find a valid Docker environment" after a node moved from Docker to containerd; an answer says Testcontainers needs a Docker API, a comment says the same tests run on a desktop Docker). The same mechanism
as q72518766 (Jenkins on GKE) and q71379578; this case is the Spring Boot variant: the job's test is a @SpringBootTest + @Testcontainers class (Spring Boot 3.1.2, Testcontainers 1.21.4, JUnit 5 console
launcher), and the failure is the thread's 502 instead of "Docker must be present".

Adaptation (stated in task.txt): no GKE/Docker Desktop; the "node" is a private mount namespace (as in q72518766) with the node's containerd and the dockerd binary. The docker.sock of the node is held by an
"engine proxy" that forwards to /run/docker.raw.sock and answers 502 "Bad response from Docker engine" while nothing listens there: a stand-in for the desktop-Docker layout of the thread (the real cause of the asker's 502
is not known; the case does not claim one). The allowed backend is stated: a dockerd started in the node on top of the node's containerd; a bare containerd socket, dockerd's own containerd, the host's Docker and a
replaced/killed proxy are not accepted.

Setup: pinned jars (27, sha256) from Maven Central in /var/cache/bench76980610 (kept); JDK >= 17 (and gcc) installed when missing; the test classes compiled from fixed sources; a static app image (docker archive,
per-run nonce); the node booted by `unshare -m` + boot script (tmpfs mounts, containerd config, node daemon.json, the engine proxy in the background, `exec containerd`); wrappers node-run / run-test; pids, start ticks,
namespace, config and file hashes in a root-only state dir. precondition.sh: containerd and proxy are the recorded processes, no dockerd, no /run/docker.raw.sock, the test fails with both messages (502 text and
"Could not find a valid Docker environment"). Oracle (dynamic): containerd and proxy not restarted/replaced, files unchanged, exactly one containerd and at least one dockerd in the node; the test is run again with a hold
file: its container (id, fresh nonce) must be in the node's containerd with the nonce in its spec/environment and a RUNNING task; the JUnit summary must say 1 test successful, 0 failed, with the Spring context line
and the nonce in the container log; the container must be gone afterwards.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q76980610/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q76980610"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q76980610", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 900)        # a first run downloads the jars (about 25 MB) and may install a JDK
    pre_timeout = max(timeout, 120)
    solution_timeout = max(timeout, 120)
    oracle_timeout = max(timeout, 240)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the node has containerd only; the test fails with the 502 of the question
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the test's container is a real container of the node's containerd
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
