"""
SO-66512464: "If docker-ce and containerd are installed on Ubuntu 20.04, what CRI does K8s use?" (2021; Kubernetes 1.20 on Ubuntu 20.04 with docker-ce, whose package also installs containerd.io;
the asker wants to know which of the two the kubelet talks to; the answers: in that era the kubelet's default runtime is Docker, through dockershim, the shim that is built into the kubelet and
sits between the kubelet and dockerd; containerd is used by Docker underneath, it is not what the kubelet uses until it is told: --container-runtime=remote and the CRI socket of containerd).
What is measured: the node's kubelet creates the pods' containers through containerd's CRI, not through Docker. The kubelet reads its runtime flags only when it starts, so a flag file that was
edited, a kubelet that was not restarted, or a socket that is not a CRI endpoint are all caught by what the kubelet then does with a pod.

Adaptation (stated in task.txt): the node is the era's software on the current host, in private paths: kubelet v1.23.17 (the last release with dockershim, sha256 pinned per architecture), the
static Docker 20.10.24 package (dockerd, containerd 1.6.20 with its CRI plugin on, runc 1.1.5; sha256 pinned per architecture) with dockerd running on the containerd of the node (its containers
are in the containerd namespace bench66512464-docker, the kubelet's CRI uses k8s.io). There is no API server: the kubelet runs standalone with a static pod (web, a static program, imagePullPolicy
Never, images built offline by setup.sh), and kubeadm is not used: setup.sh writes the file kubeadm would have written for a Docker node (kubelet/kubeadm-flags.env). kubeletctl starts and stops
the kubelet the way the package's unit does (the config file plus kubeadm-flags.env and kubelet-extra.env). The original's Ubuntu 20.04 userland is not reproduced.

precondition.sh: the lab as recorded (hashes of the programs, the dockerd and containerd processes), the kubelet runs with the default docker runtime and serves a dockershim socket, the pod web's
containers are in Docker, containerd's CRI is empty; controls: containerd's CRI runs a pod sandbox on this host, Docker runs a container.
The oracle (oracle.sh): dockerd and containerd are the processes of setup (not restarted), the kubelet is the node's binary, it was restarted, it has --container-runtime=remote and containerd's
socket; the pod web runs in containerd's CRI (and the process is under a shim of the namespace k8s.io); a new static pod (probe) is created by the kubelet in containerd and never in Docker; Docker
still runs a container.

Where the samples fail: nothing done; the flag file edited but the kubelet not restarted; only the endpoint pointed at containerd (the runtime stays docker: dockershim would take that socket
over); the endpoint set to Docker's API socket; Docker stopped; containerd restarted; the old flag left last in the extra-args file (the later flag wins).
Valid: kubeadm-flags.env edited; the flags put in kubelet-extra.env; the flags put at the end of the list; the old Docker containers of the kubelet left in place.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q66512464/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q66512464/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q66512464"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q66512464",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # the kubelet, two daemons, mounts and cgroups
    setup_timeout = max(timeout, 900)        # first run downloads the kubelet (~115 MB) and Docker (~65 MB)
    pre_timeout = max(timeout, 300)
    solution_timeout = max(timeout, 300)     # a solution restarts the kubelet itself
    oracle_timeout = max(timeout, 600)       # the kubelet needs time to start its pods

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the kubelet runs on Docker (dockershim), containerd runs next to it; the two controls (a sandbox in containerd, a container in Docker) pass
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the kubelet runs its pods through containerd's CRI, Docker is untouched and usable
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
