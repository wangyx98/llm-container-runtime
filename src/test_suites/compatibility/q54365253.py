"""
SO-54365253: "Convert docker-compose.yml to runc config.json" (2019; the only answer, by the asker: no tool exists, so a YAML parser and a mapping of read_only, command, working_dir, environment,
tty, capabilities, memory limits, hostname, cgroup_parent, pid, ipc and volumes). The question has NO compose file; this case supplies one and limits the scope, as the screening condition asks:
ONE service and six keys (command as a list, working_dir, environment as a map, hostname, read_only, volumes with SRC:DST[:ro]); every other key (image, ports, restart, depends_on, build,
networks) is out of scope and ignored, and the task says that this is not a full Compose converter and that OCI/runc has no services, ports or networks.
What is measured (runc 1.1.12; runc 1.3.4 on the VM): `runc spec` gives a config that is read-only, has a terminal and runs `sh`, so a converter has to turn those three; compose environment
values are not always strings (RETRIES: 3); a relative volume source is relative to the directory of the COMPOSE file; the container's env also gets HOME from runc itself.

The lab (setup.sh): a static probe (prints argv, cwd, env, hostname, sha256 of the files named by --hash, the result of the writes named by --write, exits with --exit) in a minimal root file
system; /var/lib/bench54365253/demo with the compose file, its data, an out directory (mode 777: the root of a container has no CAP_DAC_OVERRIDE), a bundle that is a plain `runc spec`, and
the converter compose2oci as a STUB that exits 1. The deliverable is the converter (any language; python3 + PyYAML and runc are on the machine).

The check (oracle.sh): the converter is run, as the current user from another directory, on TWO NEW compose files with other values (names, argv words, exit status, working directory, environment,
hostname, volumes: a read-only file and a read-write directory; a writable root with a read-only directory and a read-write file; ports and restart present). For each: exit 0 and a config.json; the
files it must not touch are unchanged; the config says what the compose file says, keeps the five namespaces (new, no path), has no capability from a deny list, and has exactly the compose
volumes as bind mounts (absolute sources, ro as ro); then runc (as root, its own --root) runs the bundle and the probe's report is compared item by item: argv, cwd, env (only the declared
ones plus PATH, TERM, HOME), hostname (and the host's hostname is unchanged), sha256 of mounted files and of /probe, ok or EROFS(30) of each write, what arrived on the host, the exit status.
BENCH54365253_CONVERTER replaces the converter (a hook for the controls of precondition.sh).

Where the samples fail: nothing done (stub); only the command converted; a relative volume source kept; read_only ignored; :ro ignored (all mounts rw); a bind mount without the bind option (the only
failure that appears when runc starts the bundle); environment ignored; the demo values hard-coded; namespaces dropped (the oracle refuses to run it: it would rename the host); an extra bind mount
of the host's /etc. Valid: the default `runc spec` edited (reference); a config written by hand without `runc spec`.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q54365253/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q54365253/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q54365253"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q54365253",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)      # containers and the state of runc
    setup_timeout = max(timeout, 600)        # first run may install python3-yaml
    pre_timeout = max(timeout, 300)          # the control runs and the two oracle controls
    solution_timeout = max(timeout, 300)     # a converter and a run
    oracle_timeout = max(timeout, 600)       # two new compose files, two conversions and two runs

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: runc has no compose file, the bundle that exists is not made from it, the converter is a stub, the oracle fails while unfixed
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the converter makes bundles from two new compose files that runc runs as the files say
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
