"""
SO-66733729: "How to create a container with containerd instead of pulling it" (2021; the only answer: BuildKit). The asker works with containerd's Go client, whose documentation only shows
`client.Pull(...)` + `NewContainer` + `NewTask`, and wants to create the container from a Dockerfile, like `docker build`, without the ctr tool.
This case is the BUILD-SERVICE variant (the division of labour between a build service and the runtime was named as covered by 71709053, whose files were not visible; the skeleton is
q70231694's BuildKit with a containerd worker and q76466526's private containerd): containerd itself has no Dockerfile build, so the task states that the build goes through the BuildKit
Go API (github.com/moby/buildkit/client) to a buildkitd that is already there, and no non-existent containerd build API is used.
What was measured (BuildKit v0.23.2 with a containerd worker, containerd 2.3.6, containerd client v2.1.3, Go 1.24): `bkclient.New` + `Solve` with the dockerfile.v0 frontend and the context
directory as `fsutil` local mounts builds the Dockerfile; the worker keeps `type=image` results in ITS namespace (buildkit), so a program that uses another namespace has to move the image:
`type=oci` (or `type=docker`) into a pipe or a file and `client.Import` into the program's namespace, then Unpack and run (cio.WithStdio); the cache (`buildctl du --verbose`) names the steps
(`COPY payload-<nonce>.bin`), which proves that this buildkitd did the build.

The lab (setup.sh): a private containerd and a buildkitd (containerd worker, namespace buildkit) on their own sockets below /run/bench66733729, control scripts in /var/lib/bench66733729/bin,
a Dockerfile `FROM scratch` + COPY + `RUN ["/hasher", "make", ...]` + ENTRYPOINT with a static sha256 program and a random payload (nothing is pulled), and the engineer's Go program
(/var/lib/bench66733729/app: main.go = the pull example with the flags -context and -tag, go.mod pinning buildkit v0.23.2 and containerd v2.1.3); the module and build caches of the user are warmed.
The machine's own go is not used (a VM with Go 1.18 cannot fetch a newer toolchain): setup installs Go 1.24.7 into /var/cache/bench66733729 (sha256 from dl.google.com, kept by cleanup) and writes the wrapper /var/lib/bench66733729/bin/go.

The check (oracle.sh): the files of the machine unchanged; the program builds and its binary links github.com/moby/buildkit; TWICE a fresh context (new payload file name, new image name) is
built and run by the program: exit 0, the output holds the sha256 of the payload, buildctl du has `COPY <that file>`; the image is in the containerd namespace bench66733729 and ctr runs it
there with the same output; no container or task is left.

Where the samples fail: nothing done; a pull with the BuildKit client only imported; the image left in BuildKit's namespace (type=image); buildctl executed from Go (the client is not linked); the
hash computed in Go (nothing is built); the worker's namespace switched in buildkitd.toml. Valid: OCI export into a pipe + Import (reference); OCI export into a file + Import; Docker-format export + Import.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q66733729/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q66733729/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q66733729"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q66733729",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 300)      # two daemons, shims, mounts
    setup_timeout = max(timeout, 1800)       # first run: downloads BuildKit and the Go modules and compiles the BuildKit and containerd clients
    pre_timeout = max(timeout, 900)          # the control build, the engineer's program and the oracle control
    solution_timeout = max(timeout, 900)     # a go build, a build by BuildKit, an import and a container run
    oracle_timeout = max(timeout, 1200)      # a go build and two builds with runs

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the program only pulls, BuildKit works but is not used, the oracle fails while unfixed
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the program builds through BuildKit's Go client, the image is in the program's namespace and runs
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
