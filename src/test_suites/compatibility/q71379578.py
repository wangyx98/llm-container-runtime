"""
SO-71379578: "How to run Testcontainers in Containerd without any error (from Kubernetes 1.20)?" (Jenkins on Kubernetes; the build pods used the node's Docker socket through a hostPath volume; the cluster
moves to containerd, Kubernetes 1.20 deprecates dockershim). The asker sets up Docker on the node and runs Testcontainers in a pod; the error is `Could not start container ... Timed out waiting for container
port to open (localhost ports: [N] should be listening)` (Ryuk is the second problem of the thread; the second answer suggests host.docker.internal). Close to q72518766 and q76980610 (a Docker API on a containerd
node); THIS case is the variant with a different mechanism: the Docker API exists, but Testcontainers (in the pod) looks for the mapped port at `localhost`, which is the pod's own loopback, not the node where
the port is published. Fix: TESTCONTAINERS_HOST_OVERRIDE=<node IP> (status.hostIP) in the environment of the job.

Measured (sandbox, Docker 29.9.3, containerd 2.4.2, Testcontainers 1.21.4 / docker-java 3.4.2): from a separate network namespace the test starts the container and then fails with the message of the thread
(`Timed out waiting for container port to open (localhost ports: [32768] should be listening)`); with `TESTCONTAINERS_HOST_OVERRIDE=<node IP>` (environment variable only: `host.override` and `tc.host` in
~/.testcontainers.properties do not work) the same test gets the node IP from getHost() and an answer over the published port; an iptables DNAT of the pod's 127.0.0.1 to the node makes the test pass at host=localhost,
which the oracle rejects (the address has to be an address of the node). Not measured: a real Kubernetes pod and kubelet, Ryuk (its image cannot be pulled offline: switched off, as in the thread's second step),
Docker 27, the VM's firewall between pod and node.

Adaptation (stated in task.txt): the thread does not say where the Docker API of the pod's tests comes from after the move, so the node's dockerd on the node's containerd is the stated stand-in (the same as in
q72518766, here already provided by setup); the "pod" is a network namespace (veth pair to the node, the node IP is its default gateway); `pod-run`/`run-test` run in it (the node's mount namespace, so the node's
Docker socket is visible as through a hostPath); the job's environment is `home/job.env` (the env: of the pod). The original requirement (run Testcontainers on containerd without the error) is kept.

Setup: pinned Testcontainers jars (12, sha256, Maven Central, kept in /var/cache/bench71379578), JDK/gcc/iproute2 if missing, Probe + static HTTP app image (docker archive, per-run nonce), the Docker bridge
bench71br made by setup, the node (mount namespace: tmpfs /run, /etc/docker, /etc/containerd; containerd + dockerd with the userland proxy), the pod (network namespace holder + veth vb71h/vb71p), three wrappers,
the state (pids, start times, namespaces, hashes) in a root-only dir. precondition.sh: node and pod are the recorded ones, the pod's default gateway is the node, job.env/properties are empty, and the test fails
with exit 5 and the message of the thread. The oracle (dynamic): containerd and dockerd unchanged, the pod namespace unchanged, files unchanged; the test is run again with a hold file: its container (id and nonce
from its output) is in the node's containerd with the nonce in its spec and in /proc/PID/environ and a RUNNING task; the address it used is an address of the node (not 127.*), a docker-proxy of the node holds
the port; the test gets the container's answer with the nonce; its container is gone afterwards.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q71379578/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q71379578"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q71379578", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 900)        # a first run downloads the jars (about 25 MB) and may install a JDK
    pre_timeout = max(timeout, 120)
    solution_timeout = max(timeout, 120)
    oracle_timeout = max(timeout, 240)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: node and pod as recorded; the test fails with the port timeout of the question
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the test reaches the published port of its container at an address of the node
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
