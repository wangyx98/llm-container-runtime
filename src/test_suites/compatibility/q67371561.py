"""
SO-67371561: "snap.microk8s.daemon-kubelet is not working due to containerd on centos 8" (MicroK8s on CentOS 8.3; the kubelet dies at start with
"Version from runtime service failed: ... unknown service runtime.v1alpha2.RuntimeService"; the asker regenerated the containerd configuration with `containerd config
default` and restarted, nothing changed). The question has no answer; the cause is locked by evidence, not chosen: the asker's own source (the containerd CRI documentation
and containerd issue 4581) names the CRI plugin that is DISABLED in the configuration of the containerd on the endpoint (Docker's containerd.io ships `disabled_plugins =
["cri"]`); containerd answers on the socket, but it never registers the CRI service, so every CRI call is Unimplemented. The asker's try changes the GENERATED
containerd.toml, which the MicroK8s launcher makes again from args/containerd-template.toml at every start (as in q66642654), so nothing changes.

The three suspects of the question are told apart by direct calls (precondition.sh): the ENDPOINT is the node's own containerd (its own API answers there; the socket is
served by the pid-file process), the PLUGIN is disabled (no io.containerd.grpc.v1.cri in the plugin list; the template and containerd.toml name it in disabled_plugins), the
API VERSION is not it (a scratch containerd of the same binary with the same template and disabled_plugins = [] answers Version, RuntimeApiVersion v1).

A modern adaptation, said so in task.txt: the original is MicroK8s on CentOS 8 (snap, containerd 1.4, kubelet 1.20/1.21, API v1alpha2); this is a private containerd of the host
(2.x) started through a MicroK8s-like launcher (`mk8s-run-containerd`, `mk8sctl`), the kubelet's first call (RuntimeService.Version on the endpoint of args/kubelet) made by
`mk8sctl status` with crictl (the current crictl speaks runtime.v1, so the message names runtime.v1.RuntimeService). containerd 2.x refuses the short name "cri" in
disabled_plugins (invalid disabled plugin URI), so the template has the full URI io.containerd.grpc.v1.cri. No architecture dependence: containerd, crictl (downloaded for
the architecture) and runc are native on x86_64 and aarch64.

setup.sh: two static images (sandbox, workload) as docker archives, the node (template with the plugin disabled, launcher, mk8sctl, kubelet arguments), the node started, images
imported into k8s.io, the failing first call, hashes. precondition.sh: node as left; control 1 Version and RunPodSandbox fail with unknown service; control 2 the endpoint is
the node's containerd; control 3 the plugin is disabled; control 4 the scratch containerd answers; control 5 the asker's try is undone by the restart. The oracle: the node is
the node (hashes, endpoint, pid-file process listening on the socket, containerd.toml = rendering of the template); phase A: CRI plugin ok, Version answers, mk8sctl status
ready, a pod (host network) and a container with a fresh nonce run (process and log); phase B: the same after `mk8sctl restart`.

Where the samples fail: nothing done; the generated file regenerated; the template fixed but the node not restarted; the kubelet's endpoint moved to the host's containerd; a
containerd with the plugin started by hand on the socket. The two valid solutions empty disabled_plugins in the template and restart (or stop and start).

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q67371561/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q67371561/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q67371561"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q67371561",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 300)      # the node's containerd and its shims are stopped, its processes ended
    setup_timeout = max(timeout, 900)        # compiles one tiny program, imports two images, starts the node (first run: may fetch crictl)
    pre_timeout = max(timeout, 600)          # controls: failing calls, a scratch containerd, a restart of the node
    solution_timeout = max(timeout, 300)     # a solution fixes the configuration and restarts the node
    oracle_timeout = max(timeout, 600)       # two phases: CRI calls, a pod and a container, a restart of the node

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the node as recorded; the bad state is real and its cause is told apart from the other suspects
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: a real pod and container through the CRI of the kubelet's endpoint, as left and after a restart of the node
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
