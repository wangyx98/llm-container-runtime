"""
SO-74685092: "Use the k3s and ctr commands to import the image, but the image cannot be found by using crictl" (no answer, no comments). On the master node of a k3s cluster the asker runs
`ctr -n k8s.io images import alpine-3.15.tar --platform linux/amd64`; `ctr -n k8s.io images ls` shows the image, `crictl images` does not; on the slave node the same commands work. How to make the master behave like the slave?
Measured (containerd 1.7.20 and 2.4.2, crictl 1.30/1.34): on ONE daemon every image that `ctr` has in `k8s.io` is listed by `crictl` -- also a foreign-architecture image, an index whose host-platform content is missing from the
tar, an image imported with --no-unpack (an untagged tar imports nothing at all). So a "CRI metadata / platform / unpack" cause could not be reproduced; the one cause that gives exactly the symptom is that `ctr` and `crictl`
talk to DIFFERENT daemons (k3s's embedded containerd sits on its own socket, a separately installed containerd on /run/containerd/containerd.sock) -- the thread does not say which of the two it was.

Adaptation (stated in task.txt): k3s itself is not run; a private containerd stands in for "the containerd of k3s" next to a second private containerd for "the host's own", plus a worker with one daemon (the good node). The case
is therefore a VARIANT of q75568311 (image on the wrong daemon: there across nodes, here on the same node with ctr's default socket) and of q73420677/q78814823 (the namespace is NOT the cause: it is k8s.io in the command).
The thread has no answer; the reference is from the measurement.

Setup: three private containerd daemons (the installed containerd, root/state/socket and the sandbox image patched into containerd's own default config; the pinned crictl in /var/cache/bench74685092), a static app image
(per-run token) and a pause image written as docker-archives, wrappers `master/{ctr,crictl}` (ctr -> the system daemon, crictl -> the k3s daemon) and `worker/{ctr,crictl}` (both the worker), the asker's import done on the
master through its ctr and on the worker, a running container on the worker, a ready pod sandbox on the k3s daemon, all hashes/pids/ids in a root-only state dir. precondition.sh: daemons as recorded; the master's ctr lists the
image and its crictl does not; the system daemon's CRI lists it with the tar's id; the worker runs it; creating the container on the k3s daemon fails 'not found'. The oracle (dynamic, against the daemons' own sockets): the
k3s daemon's CRI lists the image with the tar's id, the system daemon still has it, the worker is as it was, the original pod sandbox is the only one, one container 'bench74685092' in it is RUNNING from that image with the image's
own entrypoint, its process is alive and its log has the image's token; no daemon restarted or reconfigured, wrappers and app.tar unchanged.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q74685092/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q74685092"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {"case_id": "q74685092", "code": "<shell commands generated by the LLM>", "model": "optional model name"}
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)
    setup_timeout = max(timeout, 300)        # a first run downloads the pinned crictl (about 20 MB)
    pre_timeout = max(timeout, 120)
    solution_timeout = max(timeout, 120)
    oracle_timeout = max(timeout, 120)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the master's ctr lists the image, its crictl does not; the worker works; creating the container on the k3s daemon fails
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = f"precondition failed: environment not in expected initial state: {pre.stdout.strip()[-400:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty, which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the k3s daemon's CRI lists the tar's image and runs the container in the original pod; the other daemons are untouched
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
