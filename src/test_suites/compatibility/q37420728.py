"""
SO-37420728: "runc container start go-lang deattached mode" (2016; a Go program starts a container with `exec.Command("runc", "start", "-d", id).CombinedOutput()` (today: `runc run -d`); the call
never returns, although runc is gone and the container runs; the asker wants the container to run detached while the Go program goes on; the answers: the container inherits the stdout/stderr
that runc was given; with CombinedOutput (or any io.Writer that is not an *os.File) Go makes a pipe and waits for it to be closed, and the detached container holds its write end; give the
command files (or /dev/null) as stdout and stderr instead, so that Go makes no pipe, and read runc's messages from the file).
What is measured: the program built as bin/runner starts the container and returns at once (the first line it prints is the duration of the start), has no zombie or runc child while it goes on,
exits with 0; the container goes on running after the program has exited (it answers its nonce on its socket, its output keeps growing in service.log: a pipe of the program would break when the
program exits and kill the service at its next write); no runc process is left; a container that cannot start (args[0] missing) is reported with runc's own message and a non-zero status.

Adaptation (stated in task.txt): `runc run -d` for the 2016 `runc start -d`; the program takes the runc, the state directory, the bundle, the id and an optional hold time as arguments (the
rest of a bigger program), and the contract of the output is spelled out (service.log, the printed duration and error, status 1). runc is 1.1.5 from the static Docker 20.10.24 package
(sha256 pinned per architecture), the service is a static C program (socket /ctl/sock, a line on stdout every second), the Go toolchain is the case's own 1.24.7 (bin/build; the go of the
machine is not used), all below /var/lib/bench37420728; the oracle builds its own bundles, with random nonces.

precondition.sh: the lab as recorded (runc, service, program source and binary, build wrapper), the program of the question does not return in 4 s while its container runs and answers
(and runc is gone); controls: `runc run -d` with its output in a file returns at once and the container runs; bin/build builds the program.
The oracle (oracle.sh): bin/runner is a Go program of the module that is not the one of the question; run 1 (hold 6 s): the first line comes within 8 s and is the duration, no child process
while it holds, status 0, the container then runs and answers and service.log grows, no runc left; run 2 (no hold): ends by itself, the same checks for a second container, the first still
runs; run 3 (args[0] missing): ends with a non-zero status within 8 s and prints "no such file or directory", nothing left.

Where the samples fail: nothing done / only rebuilt (CombinedOutput: never returns); Start without Wait (zombie runc); StdoutPipe closed by Wait (the service dies of SIGPIPE); giving up
the wait after 2 s (the pipe breaks when the program ends); no -d (the foreground runc stays); output to /dev/null (no service.log); the container deleted at the end; errors not reported.
Valid: output of the command in a file (reference); the redirection done by a shell; runc create + start with the file.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q37420728/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q37420728/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q37420728"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q37420728",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)
    setup_timeout = max(timeout, 900)        # first run downloads the Docker package (~65 MB, for runc) and Go (~75 MB)
    pre_timeout = max(timeout, 180)
    solution_timeout = max(timeout, 300)     # a solution builds the program (a cold Go build cache takes a while)
    oracle_timeout = max(timeout, 180)       # three runs of the program, a hold of 6 s and the checks of the containers

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the program of the question does not return while its container runs; the controls (runc with a file as output, the build) pass
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the program starts the container and returns, the container runs on after it, a failing start is reported
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
