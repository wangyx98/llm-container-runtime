"""
SO-77044676: "Using Docker image in containerd" (single-node Kubernetes on containerd; no accepted answer relied on). The engineer saves a Docker image (`docker save`), imports it with
`ctr images import flaskapp.tar`, `ctr images ls` shows docker.io/library/flaskapp:v1, but the Deployment that names that image (imagePullPolicy IfNotPresent) stays in ErrImagePull/ImagePullBackOff.
This is the INTEGRATION VARIANT of the namespace/image-delivery cases (78814823, 63478550 as named in the task list; their files were not visible, the skeleton comes from q75845783/q66642654):
the failing entrance is the Kubernetes Pod, so the original Pod has to be kept and has to come up on the local image.
What was measured (k3s v1.30.5+k3s1 on a private containerd): the CRI plugin (and so the kubelet) reads only the containerd namespace k8s.io; `ctr images import` without -n writes to "default", so
`crictl images` and `ctr -n k8s.io images ls` lack the image, the kubelet's ImageStatus finds nothing and, with IfNotPresent, it pulls from docker.io. With docker.io made unreachable (the registry
configuration of the private containerd answers "connection refused"), the Pod waits in ErrImagePull. After `ctr -n k8s.io images import flaskapp.tar` the kubelet's next retry (back-off, 7-19 s seen,
300 s at most) finds the image locally, the SAME Pod starts ("already present on machine"), nothing is deleted. The imageID the CRI reports is the image's config digest.

The lab (setup.sh): a private containerd (own socket, root and state; CRI registry config_path pointing at a hosts.toml for docker.io that refuses), stub CNI plugins, real k3s (pinned per arch, cached in
/var/cache/bench77044676) with only the kubelet/API server/scheduler/controllers, control scripts (containerdctl, k3sctl, kubectl, ctr, crictl) in /var/lib/bench77044676/bin, a docker-save tar of a small
static app (prints a per-setup nonce every 5 s; the image digest changes per setup), the image imported into "default", the Deployment of the question applied. setup.sh records node, Pod and Deployment
identities, both digests and the sha256 of the files nobody may change in a root-only state directory.

The check (oracle.sh): node same, Ready, schedulable and the protected files unchanged; Deployment same uid and generation with image/IfNotPresent/1 replica; the CRI lists the image under the name with the
config digest and k8s.io holds the manifest; the ORIGINAL Pod (same name and uid) is Running and Ready, restartCount 0, imageID of the engineer's image; its log carries the nonce, same container later; events say
"already present on machine" and never "Successfully pulled".

Where the samples fail: nothing done; `ctr run` of the image in the default namespace (works for ctr, not for the CRI); the Pod deleted after a correct import (a new Pod, not the original); the pull policy changed to
Never (new generation); the sandbox image retagged as flaskapp (wrong image id); the registry unblocked plus import (protected file changed). Valid: import into k8s.io (reference); export from default to a temporary file and import it
into k8s.io; CONTAINERD_NAMESPACE=k8s.io for the import. (`ctr images export -` piped into `ctr images import -` is not a sample: in 3 of 6 runs the import failed with
"short read" / "unrecognized image format" on containerd 2.3.6, so it cannot be judged.)

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q77044676/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q77044676/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q77044676"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q77044676",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 300)      # k3s, containerd, shims, mounts
    setup_timeout = max(timeout, 900)        # first run: downloads k3s, builds the image, starts containerd and k3s
    pre_timeout = max(timeout, 300)          # the three views, the Pod's symptom and the oracle control
    solution_timeout = max(timeout, 300)     # an import, an export piped into an import, a kubectl call
    oracle_timeout = max(timeout, 450)       # the original Pod needs the kubelet's next pull retry (up to 5 minutes)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the image only in "default", the Pod cannot start, the oracle fails while unfixed
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the original Pod runs the engineer's image, the CRI lists it, nothing protected changed
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
