"""
SO-59759658: "Building images using docker-compose and containerd?" -- docker-compose builds through the Docker Engine API; on a machine with containerd and no Docker
it ends in "Cannot connect to the Docker daemon". The thread (a question only, no answer, no allowed-tools statement) gives no contract, so the contract is ours and is
stated in task.txt: the containerd-native compose front end is `nerdctl compose` + BuildKit with the containerd worker (a compatible front end, NOT the docker-compose binary
talking to containerd, which has no such API), docker/dockerd/podman/buildah/CRI-O and any Docker API on the node are forbidden, nothing is pulled (FROM scratch).

Measured (sandbox, containerd 2.4.2, runc 1.5.2, nerdctl 2.1.6, BuildKit v0.23.2, CNI plugins v1.6.2, docker-compose v2.35.1): `docker-compose build` -> "Cannot connect to the
Docker daemon at unix:///run/bench59759658/docker.sock"; `nerdctl compose up -d --build` -> "failed to create default network: needs CNI plugin "bridge" to be installed in
CNI_PATH" (nerdctl creates its default network first, even for a build; BuildKit's bundled CNI lacks portmap, hence the plugins v1.6.2 in the case); with the plugins but no
BuildKit -> the build fails; with buildkitd (containerd worker, on the node's socket, at /run/bench59759658/buildkitd.sock) the build puts its snapshots in the node's `buildkit`
namespace, the image in `default` (docker.io/library/bench59759658-web:local, label from the compose build arg), and `up` starts the container with the labels
com.docker.compose.project/service. Not measured: the VM's arm64 binaries (URLs and sha256 are pinned for amd64 and arm64), cgroup v2.

Case design: setup.sh downloads (once, cached, sha256 checked) the pinned tools for the architecture, starts a private containerd and writes the compose project (a nonce per
run baked into nonce.txt and into the build argument) and the two wrappers; the oracle checks the node's containerd is the recorded process, the files are unchanged, BuildKit
built on THIS node (namespace `buildkit`), the image has the label/entrypoint/layers of this run, exactly one compose-labelled container runs from it (process /app alive) and its log
has the nonce. Known limit: an image built by hand with the right build argument and then started with `compose up` (no --build) cannot be told from a compose build.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q59759658/ and converts their exit
codes / output into a structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q59759658/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q59759658"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q59759658",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)
    setup_timeout = max(timeout, 900)        # a first run downloads ~215 MB of pinned tools
    solution_timeout = max(timeout, 180)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stderr.strip()[-500:]}"
        # a long-lived daemon may be running: do not leave it behind
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: prove the symptom -- docker-compose cannot reach a Docker API, nerdctl compose lacks CNI plugins and BuildKit,
    #    and nothing is built or running
    pre = run_script(CASE_DIR / "precondition.sh", timeout=max(timeout, 120))
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the node's containerd is the recorded process, BuildKit built on it, the image has this run's label/layers, one
    #    compose-labelled container runs from it, /app is alive and the log shows the nonce (see oracle.sh)
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=max(timeout, 120))
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
