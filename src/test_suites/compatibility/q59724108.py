"""
SO-59724108: "Cannot start an existing container with Podman" (Podman 1.6.2, Ubuntu 18.04, Project Atomic PPA; `podman run -d` works, after `podman stop` the `podman start` ends with
"container create failed (no logs from conmon): EOF"). The cause is in the thread: conmon 2.0.3 makes a FIFO `winsz` in the container's userdata directory at every start and does not remove an
existing one, and podman 1.6.2 does not clean it up (libpod issue 4522, fixed in podman 1.6.4); a newer conmon removes the old file itself. The answers: conmon 2.0.0, or a newer podman.
It is a state error that stays: the file is made again at every start, so removing it helps for one start only, and a new container fails at its second start.

The programs are the real ones, compiled once from pinned commits (conmon v2.0.3 and v2.0.0, podman v1.6.2 and v1.7.0; cached in /var/cache/bench59724108, sources by `git clone` and a checked commit),
used through a wrapper with their own storage, runroot and tmp dir (the podman of the host stays untouched). The host is Ubuntu 22.04 on cgroup v2: the original command gets `--network host` (stated in task.txt; no CNI),
the container runs with the host's runc (reached through a small script that first deletes a runc container of the same id left by an earlier failed start), which makes its cgroup (`--cgroups disabled` is a crun-only option for podman 1.6.2). The workload is a static program (a docker archive loaded with `podman load`, nothing
pulled) that appends a line to /data/boots at every start and answers HTTP on port 8081 with its token and the number of lines.

setup.sh: the four programs, the wrapper and etc/podman.env (which programs it runs), the image, the container web (run, answer, stop, start fails). precondition.sh: the programs are 1.6.2 and 2.0.3, web is
stopped with its data intact; control 1: `start` fails twice with the question's error and a leftover `winsz` FIFO is there; control 2: a new container runs at its first start; control 3: its second start
fails too, with `winsz` removed the start works once, after the next stop it fails again. The oracle: web is the same container (id, creation time, image) and the only one, wrapper, keep.bin and the first
line of boots unchanged; the real service answers with its token and boots = lines of the file; the version of podman and of the conmon process of web (read through /proc/PID/exe) are not the broken pair;
five rounds on the same container (stop + start, restart in the third), each start gives boots + 1.

Where the samples fail: nothing done; the same start again; the leftover file removed once (the second round fails); a loop in the background that removes the file (the programs are still the broken pair);
conmon 2.0.0 but the container made again (another id). The two valid solutions point CONMON at packages/conmon-2.0.0 or PODMAN at packages/podman-1.7.0.

Status: scripts verified in the sandbox against a stand-in (a fake podman and fake conmon that follow this mechanism); the real compile and the real failure are checked on the VM only.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q59724108/ and converts their exit codes / output into a
structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q59724108/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q59724108"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q59724108",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 300)      # the containers of the engineer's podman are removed, its processes ended
    setup_timeout = max(timeout, 3600)       # first run: compiles podman 1.6.2 and 1.7.0 and conmon 2.0.3 and 2.0.0 from the pinned commits (cached afterwards)
    pre_timeout = max(timeout, 300)          # controls: a failing start, a first start that works, a second start that fails again
    solution_timeout = max(timeout, 300)     # a solution swaps a program and starts the container
    oracle_timeout = max(timeout, 600)       # five rounds of stop/start, each with the service asked

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the machine as recorded; the bad state is real (run fails in the Pod, works on the host)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: fresh containers are started from inside the Pod and judged on the node and in the Pod
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
