"""
SO-70231694: "can I use nerdctl to build Image from inside the cluster" (replace a build that mounts the Docker socket into a Pod by `nerdctl build`). Compatibility of the build chain:
nerdctl does not build, it runs the program buildctl against a BuildKit daemon, and the daemon (buildkitd with a containerd worker here) builds and stores the image in containerd.
Reuses the environment of q75845783 (k3s with the case's own containerd, an engineer's Pod with nerdctl and the containerd socket) and adds BuildKit v0.23.2 on the host.

Three things are wrong, in the order the engineer meets them (all measured): the Pod has no buildctl and no BuildKit socket (nerdctl tries unix:///run/buildkit-default/buildkitd.sock and
unix:///run/buildkit/buildkitd.sock and says "no buildkit host is available"); once both are there, the worker of buildkitd works in the containerd namespace "buildkit", so the base image
of the Dockerfile (in "default") is not found, and a build that did work would put its image in the wrong store. The Pod is not privileged: the build context travels over the BuildKit connection,
so unlike `nerdctl run` (q75845783) no path has to be shared; only the client and the socket are needed.

setup.sh: the case's containerd and k3s (as q75845783: stub network plugins, no add-ons), buildkitd with a containerd worker (namespace buildkit) started by buildkitctl, the base image and
the Pod image built offline, the build context (a Dockerfile with COPY and RUN, 1 MiB random payload.bin), the Pod `builder` (unprivileged root, /workspace read-only, the containerd socket).
precondition.sh: the machine as recorded; control 1: nerdctl ps/images work in the Pod; control 2: no buildctl, no /run/buildkit, `nerdctl build` fails with "no buildkit host is available";
control 3: buildkitd has one containerd worker in the namespace buildkit and a build made directly against it fails on the base image.
The oracle: the machine unchanged (programs, context, a buildkitd of the pinned binary); the Pod still unprivileged, root, its image, no host root/PID/network/IPC, the pinned nerdctl, a buildctl that is
the machine's own, no BuildKit daemon inside; buildkitd has ONE worker, containerd, v0.23.2, namespace default, on the case's containerd; payload:1 is in the namespace default and a container from it
has /payload.bin and /payload.sha256 (written by the build's RUN step) with the hash of the random file; then the oracle sends two fresh random contexts into the Pod, `nerdctl build`s them there, and
each image must be in the namespace default with the right hash, with the COPY step of the file's name in the build cache of the case's buildkitd (so a pre-built image cannot pass).

Where the samples fail: nothing done; buildctl copied into the Pod without a socket; socket and buildctl mounted but the worker still in the namespace buildkit (the base image is not found); the
worker left in buildkit with the base image copied there and the Pod told to use that namespace (the build works, the image is in the wrong store); the image built on the host (the Pod still cannot
build); a privileged Pod (everything works, the Pod is not allowed). The two valid solutions mount the socket directory at /run/buildkit and the machine's buildctl into the recreated Pod, or give
the socket directory another path with BUILDKIT_HOST and copy buildctl in with kubectl cp; both set the worker's namespace to default and restart buildkitd.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q70231694/ and converts their exit codes / output into a
structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q70231694/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q70231694"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q70231694",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 300)      # k3s, buildkitd, containerd and every container are stopped and removed
    setup_timeout = max(timeout, 600)        # may download k3s, nerdctl and BuildKit; starts containerd, k3s and buildkitd
    pre_timeout = max(timeout, 300)          # controls: a failing build in the Pod, a failing build against BuildKit
    solution_timeout = max(timeout, 300)     # a solution restarts buildkitd, recreates the Pod and builds in it
    oracle_timeout = max(timeout, 600)       # two fresh builds in the Pod and one run of each image, each judged

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the machine as recorded; the bad state is real (run fails in the Pod, works on the host)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: fresh containers are started from inside the Pod and judged on the node and in the Pod
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
