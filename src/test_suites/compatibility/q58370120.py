"""
SO-58370120: "How to stop Undertow triggering warnings from gVisor in Cloud Run" -- Cloud Run (gVisor) logs `Container Sandbox Limitation: Unsupported syscall setsockopt(0x13,0x1,0xa,...)`
for the socket option SO_OOBINLINE that Undertow sends (the asker set it to false, the default, and it is still sent). The only answer: not a gVisor problem; the front end never sends
out-of-band data; do not call setSocketOption(); there is no method to disable gVisor's warnings (a comment: subclass and make it a no-op).

Measured (sandbox x86_64, runsc 20260105.0): SO_OOBINLINE (0 and 1) is supported by the current runsc and logs nothing; many other options (SO_PRIORITY 0xc, SO_MARK, SO_PEEK_OFF, SO_BUSY_POLL,
SO_INCOMING_CPU, TCP_THIN_*, TCP_FASTOPEN, TCP_NOTSENT_LOWAT, IP_FREEBIND, IP_TRANSPARENT ...) return 0 and are logged in runsc's debug log as `Unsupported syscall setsockopt(fd,level,opt,...)` (the very
format of the thread; once per distinct call). 2019 runsc releases are x86_64 only and did not run in the sandbox (network setup), so the thread's own version was not reproduced.

Case design (stated adaptation in task.txt): a static HTTP server stands in for Undertow; it sends SO_PRIORITY (0xc) with its default value 0, like Undertow sends SO_OOBINLINE=false, on the listener
and on every connection, for every option present in /tmp/bench58370120/conf/server.conf. The service runs as a runsc sandbox (pinned release, per-arch sha512, network none = the sandbox's loopback);
the wrapper `svc` fixes runsc's flags and its debug log. Fix: remove the option from the config and start the service. The oracle checks that the program, wrapper, config.json and runsc are unchanged, the
config keeps port/tcp_nodelay and has no so_priority, the sandbox runs, 20 requests are answered correctly (nonce, growing counter, TCP_NODELAY on the connection), the server's own list of setsockopt calls
has no so_priority, the debug log of this run has no warning for it, and a deliberate unsupported call made by the oracle shows up (the log is live and not filtered).

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q58370120/ and converts their exit
codes / output into a structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q58370120/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q58370120"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q58370120",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)
    setup_timeout = max(timeout, 600)        # a first run downloads runsc (~64 MB) and may install gcc
    solution_timeout = max(timeout, 120)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stderr.strip()[-500:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: prove the symptom -- with the shipped config the service answers and runsc's
    #    debug log shows 'Unsupported syscall setsockopt' for SO_PRIORITY; a control call shows the log is live
    pre = run_script(CASE_DIR / "precondition.sh", timeout=max(timeout, 180))
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: files unchanged, config without so_priority, the sandbox running, 20 correct answers,
    #    the server's own list of calls without so_priority, no warning in the log, a control call visible in it (see oracle.sh)
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=max(timeout, 180))
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
