"""
SO-57214133: "Google Cloud Run gVisor syscall error on node application" -- Cloud Run (gVisor, 2019) logged `Container Sandbox Limitation: Unsupported syscall statx(...)` for a Node app that served
pre-gzipped assets; harmless (the runtime falls back), and there is no way to silence it: the call must not be made.

Adaptation (stated in task.txt): the current runsc (20260105.0) implements statx, so the stand-in keeps the mechanism with copy_file_range, which Node's fs.copyFileSync issues and runsc still reports
(once per run, the copy works through the fallback). The application is a small Node 22.23.4 server (pinned by sha512 for x86_64 and aarch64) that publishes app/public/* into /data/www with
fs.copyFileSync at start and at POST /refresh and serves them (.gz with Content-Encoding gzip when accepted), inside a runsc sandbox whose debug log is the "platform log". Fix: copy by read/write.
The oracle checks the unchanged files, the served bodies (gzip and plain), /data/www against app/public, that /refresh restores deleted/changed files, no copy_file_range line in the log, a control call
that is reported, and a replay of the application in a fresh sandbox with a log of the oracle's own.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q57214133/ and converts their exit
codes / output into a structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q57214133/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q57214133"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q57214133",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)
    setup_timeout = max(timeout, 600)        # a first run downloads runsc (~64 MB) and node (~52 MB)
    solution_timeout = max(timeout, 120)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stderr.strip()[-500:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: prove the symptom -- the service starts and serves the site, and runsc's debug log shows
    #    'Unsupported syscall copy_file_range' made by server.js's fs.copyFileSync
    pre = run_script(CASE_DIR / "precondition.sh", timeout=max(timeout, 180))
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: files unchanged, sandbox running, gzip/plain bodies, /data/www and /refresh, no warning in the log,
    #    a control call reported, and the replay in a fresh sandbox (see oracle.sh)
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=max(timeout, 180))
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
