"""
SO-71499683: "How to export image in CRI-O?" (2022; the only answer: CRI-O has no such call, use podman/skopeo). The asker has Go clients for Docker and containerd that list, tag and export
images and wants the same for CRI-O. Measured with CRI-O 1.34: crictl has no export/save, the CRI has no call for it; the images of CRI-O are containers/storage (/var/lib/containers/storage,
also read by Podman), and the Go libraries CRI-O is made of read them: containers/image copies from the transport "containers-storage:" to "docker-archive:" (or "oci-archive:") in-process,
layer by layer with the config, no registry. The image ID in CRI-O is the sha256 of the config blob, and it stays the same in the archive.
Decision (flagged, to be confirmed): the original constraint is the Go API, so the contract is a Go program that links the containers libraries (containers/storage, alone or below containers/image) and starts
no other program (strace on execve); a skopeo/podman CLI export is a TOOL SUBSTITUTION (an adaptation) and fails the contract; the same oracle would take it if that were allowed. Nothing new about
the storage mechanism is covered by q59161183 (the opposite direction: an archive INTO the store with skopeo/podman).

The lab (setup.sh): CRI-O 1.34 as in q73029815 (pinned, cgroupfs, CNI); an image registry.bench71499683.invalid/shop/app:1.0 of two layers (/hasher static program; /data/unique.bin random)
generated in Python and put into the store with `podman load`; the archive is deleted at once, so only the store holds the bytes; the registry is blocked in registries.conf.d (and .invalid
never resolves); the engineer's program /var/lib/bench71499683/app (main.go finds the image through containers/image and exports nothing); the Go of the lab (1.24.7, wrapper bin/go with the
build tags containers_image_openpgp, exclude_graphdriver_btrfs, exclude_graphdriver_devicemapper) in /var/cache/bench71499683, the module and build caches warmed.

The check (oracle.sh): files of the lab unchanged and the image still in the store; the program builds and links containers/image and containers/storage; a NEW image (another name, another
random file) is put into the store; the program runs as root on both images under strace: exit 0, no execve of another program, an archive; the archive's config says what the image's config says (the same bytes in a docker-archive; an OCI archive has a converted config with another digest) and its
layers (gunzipped when needed) hash to the recorded diff IDs and hold the unique file; each archive loads into a clean podman store (vfs, own --root) and runs, printing the unique file's
sha256; both images are still in CRI-O's store and CRI-O runs a container from the first one.

Where the samples fail: nothing done; `podman save` as a CLI (not a Go program); a Go program that executes podman save; a pull from the registry; the image of the task hard-coded (run 2 fails);
the layer tar instead of an image archive; the source image deleted after the export. Valid: docker-archive through alltransports (reference); oci-archive; the explicit storage API
(storage.GetStore + the containers-storage transport) with a docker-archive.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q71499683/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q71499683/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q71499683"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q71499683",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 300)      # pods, images and stores
    setup_timeout = max(timeout, 1800)       # first run: installs CRI-O and Podman, downloads Go and the Go modules and compiles the containers libraries
    pre_timeout = max(timeout, 900)          # the engineer's program and the oracle control
    solution_timeout = max(timeout, 900)     # a go build and an export
    oracle_timeout = max(timeout, 1200)      # a go build, a new image, two exports, loads and runs

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: CRI-O has no export, the image is only in its store, the program exports nothing, the oracle fails while unfixed
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the program exports image archives from the store of CRI-O with the Go libraries; they load and run in a clean store
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
