"""
SO-62874903: "CRIO runtime spec for OCI v1alpha1 compliance" -- the asker wants the command line CRI-O uses towards an OCI runtime, found that it runs commands the OCI runtime CLI 1.0.1 does not define
(exec) and that a LXC runtime therefore lacked it; the only answer: an LXC issue, OCI relies on commands matching runc's way. No spec exists to look up.

Variant (stated in task.txt): no LXC adapter is obtainable for both architectures, so the case measures the contract on the real CRI-O 1.34 instead: two runtime handlers (benchrt for the job, benchrt-verify
for the oracle) are thin recording programs (hash-chained log of every command line and of an exec's process spec) that run the host's default OCI runtime with the same arguments. The job runs one
crictl lifecycle (runp, create, start, exec of a token, stop, rm, stopp, rmp) and writes contract.json (commands, flags per command, global flags, command per operation, keys of the exec's process
spec, evidence). The oracle checks the files, the log's hash chain and the evidence, runs three lifecycles of its own through its handler and compares.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q62874903/ and converts their exit
codes / output into a structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q62874903/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q62874903"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q62874903",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 120)
    setup_timeout = max(timeout, 600)        # a first run may install CRI-O, crictl, skopeo and gcc
    solution_timeout = max(timeout, 120)

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stderr.strip()[-500:]}"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 2. precondition oracle: the handlers are registered, the log is empty, and a lifecycle through the oracle's handler shows CRI-O
    #    running 'exec' towards the runtime (a command the OCI CLI does not define)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=max(timeout, 180))
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: files unchanged, contract.json well-formed, the job's log chain and evidence, then three lifecycles
    #    through the oracle's own handler compared with contract.json (see oracle.sh)
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=max(timeout, 180))
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
