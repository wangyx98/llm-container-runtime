"""
SO-77040211: "Local Registry for Kubernetes cluster running with containerd" (2023; a 4-node kubeadm cluster on containerd, Docker cannot be installed next to containerd, the asker wants a
local registry to push to and the cluster to pull from; the answers are `docker save | ctr -n k8s.io images import`, which the asker already did: `ctr images ls` shows the image, the Pod
still fails with "failed to resolve reference docker.io/library/...: pull access denied"). The question is a scale variant of q69088569 (registry reachability for a containerd node); the
screening condition asks for the original four-node scope, a real registry and a cold pull of a pinned digest on EVERY node, so this case is that variant and not a new topic.
What is measured: a node pulls through the CRI (what the kubelet does) only if ITS containerd is configured for the registry: `config_path` in the node's config.toml (read when containerd
starts) naming a directory with <host:port>/hosts.toml (read at every pull). An image put into the node by hand does not help (the check removes it and pulls the digest again).

Adaptation (stated in task.txt): the four machines are four private containerd instances on one host (own root, state, socket, configuration, runc state; nodectl starts and stops them), and
the registry is the real distribution registry v3.0.0 (release binary, sha256 pinned per architecture) on HTTPS at 10.77.40.11:5000 (a /32 alias of lo), with a certificate of a lab CA made
by setup.sh. The failure of the question's setting is replaced by the one a self-hosted TLS registry gives every runtime: "x509: certificate signed by unknown authority". The image
(one static program, random salt) is pushed the way docker push does and pinned by its manifest digest, which is written to /var/lib/bench77040211/argus.ref.

precondition.sh: the lab as recorded (registry process, certificate, nodectl, four node processes, sandbox images), no node has a config_path or a registry directory; control 1: ctr, told the
CA, pulls the image on every node (the name, the digest and the network are right); control 2: the CRI pull fails on every node with "signed by unknown authority"; control 3: the host's own
roots refuse the registry certificate and the lab CA accepts it.
The oracle (oracle.sh): the registry is the same process with the same configuration and certificate and still HTTPS, the host's certificate store does not trust the lab CA, every node is the
containerd of nodectl; then for node1 to node4 in turn: pods and the image removed (and the manifest, config and layer blobs from the content store), the CRI pulls the digest, the image id is the
image's config digest, the registry log shows containerd's GET of the manifest and of both blobs during that pull, a host-network pod runs the image with a fresh nonce and its log has the nonce
and the salt, and /salt in the running container's root is that salt.

Where the samples fail: nothing done; only node1 configured; hosts.toml without config_path; config_path set but the nodes not restarted; the directory named without the port; the table
appended a second time to config.toml (containerd refuses it, the nodes do not come back); the accepted answer (ctr pull into k8s.io by hand); the lab CA put into the host's certificate store.
Valid: one hosts directory shared by the four nodes; the CA copied next to hosts.toml and named relatively; skip_verify.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q77040211/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q77040211/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q77040211"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q77040211",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # four nodes, the registry, mounts and cgroups
    setup_timeout = max(timeout, 600)        # first run downloads the registry release
    pre_timeout = max(timeout, 300)          # the controls pull on four nodes
    solution_timeout = max(timeout, 300)     # a solution restarts the four nodes itself
    oracle_timeout = max(timeout, 600)       # four cold pulls and four pods

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the lab as recorded, no node configured for the registry; every CRI pull fails with an unknown certificate authority while ctr, told the CA, pulls
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: each of the four nodes pulls the pinned digest cold through the CRI from the registry and runs it
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
