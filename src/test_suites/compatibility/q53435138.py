"""
SO-53435138: "Running docker inside Kubernetes with containerd" (2018; Jenkins on Kubernetes builds images with Docker-outside-of-Docker, the node's runtime became containerd, the asker mapped
containerd's socket as /var/run/docker.sock and the docker client answers `malformed HTTP response "\\x00\\x00\\x00\\x04..."`: containerd's socket speaks gRPC, not the Docker API; the answers: the client
only talks to a dockerd, a node that has none needs one installed next to Kubernetes, and the pod then mounts /var/run/docker.sock of the node). The screening asks for the other way, a REAL Docker in
Docker: a dockerd inside the pod, a cold build and run of a nonce image through the inner API, the inner daemon and process ownership checked; an outer ctr success or a mounted host socket (sibling
mode) is not the inner run.
What is measured: the pod jenkins ends up with its own dockerd (a privileged DinD container next to the agent, or one container that is both), the agent's plain `docker` reaches it (a shared socket
directory or tcp://127.0.0.1:2375 with DOCKER_HOST), and the job's containers are processes below that dockerd below a container's own command.

Adaptation (stated in task.txt): the node is a standalone kubelet v1.23.17 (static pods, no API server) on the containerd 1.6.20 / runc 1.1.5 of the Docker 20.10.24 static package (sha256 pinned per
architecture, cached in /var/cache/bench53435138); same skeleton as q66512464 (kubeletctl, kubeadm-flags.env, runc wrapper only on a host that cannot lower oom_score_adj). The three images are built
offline: the agent (docker CLI and a shell), the DinD image (dockerd, containerd, runc, docker CLI and an entry point with the logic of docker:dind's: cgroup v2 nesting, unix socket, tcp on 127.0.0.1:2375
when DOCKER_TLS_CERTDIR is empty; no bridge network, no iptables) and the sandbox image. The job is `FROM scratch` + a static program and a salt file from the Jenkins workspace (a hostPath), so no registry is needed.

precondition.sh: the lab as recorded (hashes, containerd process, the three images, the kubelet), the agent's docker ps fails with `malformed HTTP response`, no dockerd runs on the node; control: a copy of
the repaired pod under another name (ctl) starts, its dockerd answers and a job builds and runs (so a failure of a sample is the sample's, not the host's), then it is removed.
The oracle (oracle.sh): the pod's sandbox is not on the host's PID/IPC namespace; every container uses one of the node's images and mounts nothing of the host except the workspace and the kubelet's own
files; plain `docker` in the agent builds the job twice (new nonce, new salt) and prints `job nonce=<n> salt=<s>`; a held container's process is in a PID namespace whose parent is the namespace of a dockerd, that dockerd is (or is below) the init of
a container of the pod and the command of that container starts dockerd (so a dockerd that was `exec`ed into the pod does not count); the node's containerd lists neither the container nor the image.

Where the samples fail: nothing done; the agent keeps the containerd socket and the dind container is added; the dind container is not privileged; a dockerd started on the node with its socket mounted
(sibling mode: refused by the mount rule); the host root mounted into the sidecar; dockerd listening on tcp but the agent without DOCKER_HOST; a dockerd started by `crictl exec` into a pod whose
command is idle (the daemon is not the command of a container). Valid: emptyDir socket directory; tcp on 127.0.0.1:2375 with DOCKER_TLS_CERTDIR="" and DOCKER_HOST; one container that is agent and dockerd.

This module does NOT reimplement the test logic in Python. It just orchestrates the existing bash scripts under cases/compatibility/q53435138/ and converts their exit codes
into the structured `cases` dict.

Taxonomy category: Runtime Compatibility
"""

from pathlib import Path

from src.utils.shell import run_script, run_shell_snippet

# cases/compatibility/q53435138/ relative to the repo root
CASE_DIR = Path(__file__).resolve().parents[3] / "cases" / "compatibility" / "q53435138"


def run_tests(sample: dict, cfg: dict):
    """
    sample: {
        "case_id": "q53435138",
        "code": "<shell commands generated by the LLM>",
        "model": "optional model name, just for bookkeeping",
    }
    cfg: {"timeout": 60, ...}

    Returns (cases: dict, error_message: str | None), matching the
    run_tests(sample, cfg) convention.
    """
    cases: dict = {}
    error_message = None
    timeout = cfg.get("timeout", 60)
    cleanup_timeout = max(timeout, 180)      # the kubelet, containerd, the pods' containers, mounts and cgroups
    setup_timeout = max(timeout, 900)        # first run downloads the kubelet (~115 MB) and Docker (~65 MB) and builds the images
    pre_timeout = max(timeout, 400)          # the control pod starts a dockerd
    solution_timeout = max(timeout, 300)     # a solution waits for the kubelet to replace the pod
    oracle_timeout = max(timeout, 600)       # two jobs and the checks

    # 1. reset to a known clean state before every sample
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    setup = run_script(CASE_DIR / "setup.sh", timeout=setup_timeout)
    cases["setup_ok"] = setup.ok
    if not setup.ok:
        error_message = f"setup.sh failed: {setup.stdout.strip()[-300:]} {setup.stderr.strip()[-300:]}"
        return cases, error_message

    # 2. precondition oracle: the agent's docker fails on containerd's socket; a pod with its own dockerd builds and runs a job on this node (control)
    pre = run_script(CASE_DIR / "precondition.sh", timeout=pre_timeout)
    cases["precondition_passed"] = pre.ok
    if not pre.ok:
        error_message = "precondition failed: environment not in expected initial state"
        run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)
        return cases, error_message

    # 3. run the LLM-generated solution (falls back to no-op if empty,
    #    which is useful for testing that the oracle correctly fails)
    llm_code = sample.get("code", "")
    if llm_code.strip():
        solution = run_shell_snippet(llm_code, timeout=solution_timeout)
        cases["solution_executed"] = solution.ok
        cases["solution_stdout"] = solution.stdout[-2000:]
        cases["solution_stderr"] = solution.stderr[-2000:]
    else:
        cases["solution_executed"] = False
        cases["solution_stdout"] = ""
        cases["solution_stderr"] = "no code provided (no-op sample)"

    # 4. postcondition oracle: the pod's own dockerd builds and runs the jobs
    oracle = run_script(CASE_DIR / "oracle.sh", timeout=oracle_timeout)
    cases["oracle_passed"] = oracle.ok
    cases["oracle_output"] = oracle.stdout[-2000:]
    if not oracle.ok:
        error_message = error_message or f"oracle failed: {oracle.stdout.strip()[-500:]}"

    # 5. always tear down afterwards, whether it passed or not
    run_script(CASE_DIR / "cleanup.sh", timeout=cleanup_timeout)

    return cases, error_message
